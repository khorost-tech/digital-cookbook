// Package ratelimit — пять алгоритмов ограничения частоты на одном интерфейсе,
// плюс распределённый лимит на Redis. Стенд к статье «Rate limiting и throttling».
//
// Время во всех алгоритмах передаётся ЯВНО через AllowAt(now) — не берётся из
// time.Now() внутри. Это делает замеры детерминированными: тесты прогоняют
// сценарии по искусственным меткам времени, без сна и настенных часов, поэтому
// «на границе окна прошло 200 при лимите 100» — воспроизводимый факт, а не гонка.
package ratelimit

import "time"

// Decision — решение лимитера по одному запросу.
type Decision struct {
	Allowed    bool          // пропустить ли запрос
	RetryAfter time.Duration // если нет — через сколько имеет смысл повторить (для Retry-After)
}

// Limiter — общий интерфейс всех локальных алгоритмов.
type Limiter interface {
	// AllowAt решает судьбу одного запроса в момент now.
	AllowAt(now time.Time) Decision
}
