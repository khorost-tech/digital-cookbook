echo "=== ЧАСТЬ 2: подхват ВОЗВРАЩЁННОЙ джобы (UPDATE после reclaim) — poll против listen ==="
# Отличие от части 1 ровно одно: джоба не появляется INSERT'ом с нуля, а
# сначала берётся воркером с короткой арендой без heartbeat, воркер убивается
# (сценарий Задачи 1 — смерть посреди работы), аренда истекает, и explicit
# reclaim переводит джобу running -> queued. Это UPDATE OF state, и будит его
# именно jobs_notify_requeue, а не jobs_notify_ins. Отсчёт времени — от
# момента запуска reclaim, а не от постановки джобы: интересует именно
# задержка ВОЗВРАТА в работу, а не время жизни аренды.
#
# lat2 (воркер в проверяемом режиме) стартует ПОСЛЕ того, как джоба уже
# отдана "неудачливому" воркеру и стала running: если бы lat2 уже крутился в
# момент самой вставки джобы, он мог бы перехватить её сам (обычным claim, а
# не через reclaim) — тогда замерялся бы не тот путь пробуждения. Порядок
# внутри каждой попытки: INSERT -> stale забирает -> stale убит -> аренда
# истекает -> lat2 стартует на уже running (не queued) джобе -> reclaim.
#
# Сам reclaim исполняется ПРЯМЫМ SQL через уже открытое probe-соединение, а не
# запуском "$WORKER_BIN" -reclaim отдельным процессом (так было изначально —
# см. пояснение про накладные расходы измерительной оснастки в шапке файла).
# Запрос ниже — дословно тело ReclaimExpired (worker/queue.go): тот же WHERE
# (state='running' AND leased_until < now()), те же три поля (state -> queued,
# leased_by -> NULL, leased_until -> NULL) и explicit updated_at=now() —
# инвариант схемы jobs_lease_chk (leased_until/leased_by NULL везде, кроме
# running) соблюдён тем же способом, каким его соблюдает сам Go-код. RETURNING
# не нужен: интересен только факт UPDATE OF state, запускающий именно
# jobs_notify_requeue (WHEN NEW.state='queued' AND OLD.state IS DISTINCT FROM
# 'queued' — см. sql/01-schema.sql), а не jobs_notify_ins.

measure_requeue_once() {  # $1 = режим; печатает мс на stdout
    local mode="$1" spid w t0 ms
    "${PSQL_DIRECT[@]}" -q -c "INSERT INTO jobs (kind) VALUES ('requeue')" >/dev/null

    "$WORKER_BIN" -id stale -work 30s -lease 1s -heartbeat=false -for 30s \
        >>/tmp/bj-notify-stale.log 2>&1 &
    spid=$!
    sleep 0.3   # джоба взята, аренда 1с пошла
    kill -9 "$spid" 2>/dev/null || true
    wait "$spid" 2>/dev/null || true
    sleep 1.2   # аренда истекла; джоба всё ещё state=running, никто её не вернул

    "$WORKER_BIN" -id lat2 -mode "$mode" -work 10ms -for 12s \
        >>"/tmp/bj-notify-req-$mode.log" 2>&1 3>&- 4<&- &
    w=$!
    # Пауза 0.600-1.499с. Нижняя граница: lat2 должен успеть встать и увидеть
    # Claim-ом state=running (не queued), то есть уйти в опрос/LISTEN — иначе
    # мерился бы его старт, а не задержка пробуждения (600мс с запасом хватает
    # при старте бинаря ~30-35мс). Ширина 900мс размывает фазу poll-цикла lat2
    # относительно момента реклейма: все прочие паузы на пути сюда фиксированы
    # (0.3с, 1.2с), и без добавки попытки мерили бы одну точку распределения.
    # ИНВАРИАНТ, обязательный при любых правках:
    #   верхняя граница джиттера + open_probe + старт lat2  <<  таймаут
    #   WaitForJob из worker/main.go (сейчас 2с).
    # Сейчас: 1.5с + ~40мс против 2с — зазор ~460мс, около четверти цикла, при
    # наблюдаемой изменчивости положения стыка в десятки мс. Если кто-то
    # поменяет таймаут в worker/main.go, запас молча станет неверным, а числа
    # останутся правдоподобными — замер снова начнёт лгать тихо.
    #
    # Почему перенос окна — исключение известного эффекта, а не подгонка под
    # желаемую картинку: ШИРИНА джиттера при переносе сохранена (1000 -> 900мс),
    # сдвинуто только положение. Сужение ширины убило бы покрытие фазы и заодно
    # спрятало бы разброс; сдвиг лишь уводит выборку из зоны, где воркер НЕ
    # ПОДПИСАН. Задержка пробуждения неподписанного воркера — отдельная
    # величина, и она не замалчивается: про редкий скачок до 2с сказано в
    # выводах ниже и в пункте 3 шапки.
    sleep_jittered 600 900

    open_probe   # прогрев соединения — внутри open_probe, до t0
    t0=$(date +%s%3N)
    echo "UPDATE jobs SET state='queued', leased_by=NULL, leased_until=NULL, updated_at=now() WHERE state='running' AND leased_until < now();" >&3
    ms=$(wait_done "$t0")
    close_probe

    kill "$w" 2>/dev/null || true
    wait "$w" 2>/dev/null || true
    echo "$ms"
}

measure_requeue() {  # $1 = режим, $2 = пояснение к режиму
    local mode="$1" note="$2" i ms
    local samples=()
    : >"/tmp/bj-notify-stale.log"
    : >"/tmp/bj-notify-req-$mode.log"

    "${PSQL_DIRECT[@]}" -q -c "TRUNCATE jobs RESTART IDENTITY" >/dev/null
    for i in $(seq 1 "$TRIALS_REQUEUE"); do
        ms=$(measure_requeue_once "$mode")
        samples+=("$ms")
    done

    report "$mode" "$note" "${samples[@]}"
}

