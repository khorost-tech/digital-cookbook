#!/usr/bin/env bash
# Артефакт 8: задержка подхвата джобы — polling против LISTEN/NOTIFY.
#
# Схема даёт ДВА пути пробуждения на канал jobs_new (см. sql/01-schema.sql):
#   jobs_notify_ins     — AFTER INSERT;
#   jobs_notify_requeue — AFTER UPDATE OF state, когда джоба становится queued
#                          (реклейм истёкшей аренды, возврат после неудачи).
# Второй существует не для симметрии: джоба становится доступной не только при
# вставке, а слушать только INSERT значило бы, что возврат в очередь после
# reclaim замечается лишь на следующем опросе — LISTEN/NOTIFY молча
# деградировал бы до polling ровно в сценарии, ради которого писалась аренда
# (задачи 1-2). Поэтому ниже измеряются ОБА пути отдельно.
#
# ВАЖНО про сам замер (иначе он солжёт), два вопроса по отдельности.
#
# 1) Инструмент замера не должен быть медленнее того, что он измеряет.
# Остальные demo-скрипты серии гоняют каждую команду через
# `docker exec bj-postgres psql ...` — для замеров на секундах (артефакты 1-2,
# 6) это ничего не портит. Здесь речь о единицах-десятках миллисекунд, а один
# `docker exec ... psql -c` стоит ~90-100мс ТОЛЬКО на старт процесса (замерено
# отдельно, см. отчёт задачи) — сам инструмент был бы медленнее измеряемого.
# Поэтому: psql подключается НАПРЯМУЮ к проброшенному порту (localhost:5456,
# без docker exec), а критичный по времени опрос состояния джобы идёт через
# ОДИН заранее открытый psql-процесс (bash coproc) — круговой обмен через уже
# установленное соединение стоит ~1-2мс вместо ~90мс на новый процесс.
# Постановка джобы (INSERT, Часть 1) и её реклейм (UPDATE, Часть 2) остаются
# НАСТОЯЩИМИ мутациями против той же схемы с теми же двумя триггерами — но обе
# идут через уже открытое probe-соединение (echo "..." >&3), а не отдельным
# psql/Go-процессом. Низкие накладные расходы даёт только ИНСТРУМЕНТ замера,
# а не то, что меряется.
#
# В Части 2 это исправление, а не изначальный выбор: первая версия замера
# запускала "$WORKER_BIN" -reclaim ОТДЕЛЬНЫМ процессом после t0 — старт Go-
# бинаря плюс установка соединения (~30-35мс) попадали в измеряемый интервал
# ОБЕИХ веток. При штатном интервале опроса 100мс эти накладные расходы
# оказались того же порядка, что и сам измеряемый сигнал: poll и listen
# сближались до 35-40мс, контраст исчезал, а подпись при этом продолжала
# утверждать про нижнюю границу ~100мс — числа противоречили собственной
# подписи. Фальсификация (интервал опроса временно поднят до 500мс) показала,
# что механизм пробуждения работает верно (poll ~532мс, listen не изменился) —
# дефект был в оснастке замера, а не в LISTEN/NOTIFY. Реклейм теперь исполняется
# тем же SQL, что и ReclaimExpired (worker/queue.go): то же WHERE, те же три
# обнуляемых/проставляемых поля, тот же триггер jobs_notify_requeue — но через
# уже открытое соединение, без старта нового процесса внутри измеряемого окна.
#
# Из той же семьи — ещё два искажения оснастки, каждое из которых обнаружилось
# СНАЧАЛА в одной части и лишь потом оказалось общим для обеих. Оба вынесены в
# общий код именно поэтому: почини такое в одном месте — и оно останется во
# втором, а числа при этом выглядят правдоподобно.
#   - Непрогретое probe-соединение: coproc возвращает управление до того, как
#     psql договорился с Postgres, и это ожидание молча утекает в первый
#     измеряемый интервал. Лечится холостым запросом ВНУТРИ open_probe (см.
#     там же) — то есть для всех замеров сразу, а не по месту вызова.
#   - Фиксированные паузы подготовки синхронизируют момент события с фазой
#     poll-цикла воркера, из-за чего все попытки измеряют одну точку
#     распределения вместо разных. Лечится sleep_jittered (см. там же).
#
# 2) Одного замера на режим недостаточно. poll ждёт РАВНОМЕРНО от 0 до 100мс
# до следующей проверки очереди — единственный прогон может случайно упасть
# рядом с нулём и оказаться близко к listen не потому, что они одинаковы, а
# по чистой случайности жребия. Поэтому каждый режим прогоняется N раз, и в
# выводе — не только среднее, но и разброс (min/max): именно разброс, а не
# отдельное число, показывает разницу между «ждём до 100мс» и «просыпаемся
# по событию».
#
# 3) Попытки НЕЛЬЗЯ слать впритык одна к другой для listen (найдено вживую,
# не в теории). WaitForJob переподключается на каждый вызов (см. listen.go):
# после complete воркер идёт на новый цикл, и pgx.Connect + LISTEN занимают
# единицы миллисекунд. Если стрелять следующей вставкой без паузы, она
# иногда успевает раньше, чем воркер заново подпишется на канал —
# уведомление уходит в никуда (Postgres не буферизует NOTIFY для ещё не
# подписавшихся сессий), и подхват откладывается до собственного
# 2-секундного таймаута WaitForJob. Это НЕ баг измерения и не баг
# WaitForJob — это цена переподключения на каждый вызов, и без паузы между
# попытками она стабильно портила бы именно listen (было проверено: без
# паузы 4 из 5 попыток вместо единиц мс показывали ~2021мс). Пауза 300мс
# между попытками просто убирает эту искусственную гонку и возвращает
# сценарий к тому, что и должно измеряться: джобы приходят независимо от
# внутреннего цикла воркера, а не вплотную к предыдущему завершению.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
export GOPROXY=https://go.khorost.tech,direct
export PGPASSWORD=jobs

PSQL_DIRECT=(psql -X -h localhost -p 5456 -U jobs -d jobs)
# Обе части — по 7 выборок. У Части 1 разброс poll до недавнего появился только
# после устранения фазовой синхронизации: раньше попытки залипали на одном
# числе, и пяти хватало «с виду». На настоящем разбросе пять выборок заметно
# шумят — разброс средних между прогонами был 96мс против 29мс у Части 2 с
# семью. Довод тот же, по которому семь стоят в Части 2.
TRIALS_INSERT=7
# Часть 2 требует больше выборок, чем Часть 1. Задержка опроса распределена
# равномерно на [0, интервал опроса], поэтому при трёх выборках среднее гуляет
# слишком сильно: на ревью один прогон из трёх дал poll [38 40 38] против
# listen [44 35 33] — контраст исчезал целиком. Это была слабость ЗАМЕРА, а не
# наблюдение о механизме. Семь выборок стоят лишних секунд прогона (каждая
# попытка несёт ~2.5-3.5с подготовки — фиксированные паузы плюс джиттер, см.
# measure_requeue_once) и удерживают среднее у теоретической половины интервала.
TRIALS_REQUEUE=7

# --- Проверка окружения. Без неё недоступный Postgres или несобранный
# воркер выглядели бы как «джоба почему-то не подхватилась» — молчаливый
# ложный результат демонстрации, а не её явный отказ. ---
if ! pg_isready -h localhost -p 5456 -U jobs -d jobs >/dev/null 2>&1; then
    echo "ОШИБКА: PostgreSQL на localhost:5456 недоступен." >&2
    echo "Подними стенд: docker compose -f compose/compose.yml up -d" >&2
    exit 1
fi

WORKER_BIN="/tmp/bj-notify-demo-worker.$$"
# ВАЖНО: "exec 3>&- 2>/dev/null" (голый exec + редирект в одной команде) не
# просто закрывает fd3 — он ПЕРМАНЕНТНО переключает stderr ТЕКУЩЕЙ оболочки на
# /dev/null до конца скрипта (у exec без слова-команды редиректы применяются к
# самой оболочке, а не к одной команде). Обнаружено вживую: после такой строки
# у "bash -x" пропадала трассировка и скрипт падал молча. Поэтому "2>/dev/null"
# всегда через ГРУППУ команд { ...; } — она сохраняет и восстанавливает fd2
# вокруг блока, а не переопределяет его насовсем.
trap '{ exec 3>&-; } 2>/dev/null || true; { exec 4<&-; } 2>/dev/null || true
      kill $(jobs -p) 2>/dev/null || true; rm -f "$WORKER_BIN"' EXIT

echo "--- сборка воркера ---"
if ! ( cd worker && go build -o "$WORKER_BIN" . ); then
    echo "ОШИБКА: воркер не собрался — демонстрация невозможна." >&2
    exit 1
fi
# Собранный бинарник напрямую (не go run): при go run воркер стал бы дочерним
# процессом go-обёртки, и kill из этого скрипта убивал бы обёртку, а не сам
# процесс с LISTEN-соединением — измерение было бы неверным или зависшим.

# open_probe/close_probe/probe_state — единственный открытый psql-процесс для
# быстрого опроса состояния джобы (см. пояснение про накладные расходы выше).
open_probe() {
    coproc PROBE { "${PSQL_DIRECT[@]}" -t -A -q; }
    exec 3>&"${PROBE[1]}"
    exec 4<&"${PROBE[0]}"
    # bash сам держит открытыми PROBE[1]/PROBE[0] в дополнение к нашим дублям
    # 3/4 — если их не закрыть здесь же, ниже "exec 3>&-" в close_probe не
    # даст EOF psql (у пайпа останется ещё один писатель) и wait зависнет
    # навсегда, не заметив, что процесс никогда не получит команду завершиться.
    eval "exec ${PROBE[1]}>&-"
    eval "exec ${PROBE[0]}<&-"

    # ПРОГРЕВ — обязателен, и делается здесь, а не в вызывающем коде, чтобы
    # НИ ОДИН замер не мог его случайно пропустить. coproc возвращает управление
    # сразу после fork: psql к этому моменту ещё не договорился с Postgres
    # (TCP + аутентификация — единицы-десятки миллисекунд). Записи в его
    # stdin-пайп при этом НЕ падают и не блокируются — они просто оседают в
    # буфере пайпа, поэтому пропущенный прогрев не виден как ошибка: он молча
    # утекает в измеряемый интервал первой попытки.
    #
    # Найдено вживую дважды. В Части 2 (open_probe вызывается заново на каждой
    # попытке прямо перед t0) без прогрева ВСЕ попытки listen шли по ~52-57мс
    # вместо ~20мс. В Части 1 (open_probe вызывается один раз до цикла)
    # завышенной систематически оказывалась только ПЕРВАЯ попытка — во всех
    # прогонах listen начинался с ~50-54мс при остальных ~20мс, и ровно этот
    # артефакт занижал min у poll (63-64мс вместо ожидаемых по механизму
    # значений), из-за чего подпись строки поll противоречила её же числам.
    #
    # SELECT 1, а не probe_state: прогрев вызывается и на ПУСТОЙ таблице
    # (Часть 1 открывает probe сразу после TRUNCATE), а "SELECT state FROM jobs
    # ... LIMIT 1" на пустой таблице в режиме -t -A не печатает НИ ОДНОЙ
    # строки — read завис бы навсегда. SELECT 1 всегда возвращает ровно одну.
    local _warm
    echo "SELECT 1;" >&3
    read -r _warm <&4
}

close_probe() {
    { exec 3>&-; } 2>/dev/null || true
    { exec 4<&-; } 2>/dev/null || true
    wait "$PROBE_PID" 2>/dev/null || true
}

probe_state() {  # состояние последней (по id) джобы в таблице
    local line
    echo "SELECT state FROM jobs ORDER BY id DESC LIMIT 1;" >&3
    read -r line <&4
    printf '%s' "$line"
}

wait_done() {  # крутится в цикле через открытый probe, пока джоба не done; печатает миллисекунды
    # Бюджет — не 2с, а с запасом (см. ниже про WaitForJob и гонку переподключения).
    local t0="$1" i s t1
    for i in $(seq 1 3000); do
        s=$(probe_state)
        if [ "$s" = "done" ]; then
            t1=$(date +%s%3N)
            echo $((t1 - t0))
            return 0
        fi
    done
    echo "ОШИБКА: джоба не стала done за отведённое число опросов" >&2
    return 1
}

# sleep_jittered — пауза "$1 миллисекунд плюс случайные 0-999мс".
#
# Зачем случайная добавка, а не фиксированная пауза. Воркер в режиме poll
# тикает своим циклом через равные интервалы от момента СОБСТВЕННОГО старта,
# ни с чем внешним не синхронизируясь. Если весь путь от старта воркера до
# события, которое мы измеряем (вставка джобы в Части 1, реклейм в Части 2),
# состоит из фиксированных пауз, то момент события относительно ФАЗЫ
# poll-цикла у каждой попытки получается один и тот же — с точностью до
# дрожания планировщика ОС (единицы мс), а не в масштабе интервала опроса.
# Тогда N попыток измеряют ОДНУ И ТУ ЖЕ точку распределения [0, интервал)
# вместо N разных, и заявленный в пункте 2 шапки разброс — главное, что
# отличает "ждём до интервала" от "просыпаемся по событию" — исчезает.
#
# Это не теория: обнаружено фальсификацией с интервалом опроса 500мс. Часть 2
# до исправления давала [533 534 532 531 531 534 535] — семь раз одно число
# вместо выборки из [0,500). Часть 1 давала [539 214 214 212 214]: попытки
# 2-5 залипли на 213±1 (первая выбивается по другой причине — см. прогрев в
# open_probe). После добавления джиттера те же прогоны дают честный разброс.
#
# Диапазон добавки задаётся вторым аргументом, а не зашит константой, потому
# что у двух частей РАЗНЫЕ ограничения сверху, и подобрать одно число нельзя.
# Снизу требование общее: добавка обязана перекрывать хотя бы один полный
# период опроса, иначе фаза не размывается (при подстановке 500мс, которой
# проверяется сам замер, это значит "не меньше ~500мс").
#
# Сверху ограничение есть только у Части 2, и оно найдено вживую, когда
# джиттер там был сделан слишком широким (1.000-1.999с): один прогон дал
# listen [2026 23 25 22 22 23 24] — первая попытка вместо ~22мс улетела в
# 2026мс и одна испортила среднее (309мс). Это не поломка LISTEN/NOTIFY, а
# та самая гонка переподключения WaitForJob, описанная в пункте 3 шапки:
# воркер lat2 входит в WaitForJob примерно через 40мс после старта и сидит
# там циклами по 2с, а реклейм при верхней границе джиттера приходился ровно
# на стык двух циклов — в узкое окно между закрытием старого соединения и
# LISTEN на новом, где уведомление уходит в никуда. Скрипт НЕ должен сам
# подводить событие к этому стыку: шапка уже требует того же от Части 1
# (пауза 300мс между попытками именно для этого). Поэтому в Части 2 верхняя
# граница держится с запасом ниже 2с, а в Части 1, где событие приходит в
# начало свежего цикла WaitForJob сразу после complete, такого потолка нет.
sleep_jittered() {  # $1 = базовая пауза в мс, $2 = ширина случайной добавки в мс
    local total_ms=$(( $1 + RANDOM % $2 ))
    sleep "$(( total_ms / 1000 )).$(printf '%03d' $(( total_ms % 1000 )))"
}

report() {  # $1=режим $2=пояснение $3..=выборка мс; печатает сырые значения + min/avg/max
    local mode="$1" note="$2"; shift 2
    local samples=("$@")
    local n=${#samples[@]}
    local sum=0 min=${samples[0]} max=${samples[0]} s
    for s in "${samples[@]}"; do
        sum=$((sum + s))
        [ "$s" -lt "$min" ] && min=$s
        [ "$s" -gt "$max" ] && max=$s
    done
    local avg=$((sum / n))
    echo "$mode (${n} попыток): [${samples[*]}] мс -> min=${min} avg=${avg} max=${max} мс  $note"
}

echo
echo "=== ЧАСТЬ 1: подхват НОВОЙ джобы (INSERT) — poll против listen ==="

measure_insert() {  # $1 = режим, $2 = пояснение к режиму
    local mode="$1" note="$2" i t0 ms
    local samples=()

    "${PSQL_DIRECT[@]}" -q -c "TRUNCATE jobs RESTART IDENTITY" >/dev/null
    "$WORKER_BIN" -id lat -mode "$mode" -work 10ms -for 60s \
        >"/tmp/bj-notify-ins-$mode.log" 2>&1 3>&- 4<&- &
    W=$!
    sleep 3   # воркер уже крутится на пустой очереди: poll спит по 100мс, listen сидит в LISTEN

    open_probe
    for i in $(seq 1 "$TRIALS_INSERT"); do
        t0=$(date +%s%3N)
        echo "INSERT INTO jobs (kind) VALUES ('latency');" >&3
        ms=$(wait_done "$t0")
        samples+=("$ms")
        # Пауза между попытками ОБЯЗАТЕЛЬНА для listen. Сразу после complete
        # воркер идёт на новый цикл WaitForJob: pgx.Connect + LISTEN занимает
        # единицы миллисекунд (замерено отдельно). Если следующую вставку
        # слать без паузы, она иногда успевает раньше, чем воркер заново
        # подпишется на канал — уведомление уходит в никуда (Postgres не
        # буферизует NOTIFY для ещё не подписавшихся), и подхват откладывается
        # до собственного 2-секундного таймаута WaitForJob. Это НЕ баг замера
        # и не баг WaitForJob — это цена переподключения на каждый вызов
        # (см. комментарий в listen.go); пауза просто убирает искусственную
        # гонку, которую создаёт вставка джоб ВПРИТЫК одна к другой, и не
        # соответствует нормальному сценарию (джобы приходят независимо от
        # цикла воркера, а не мгновенно вслед за предыдущим completion).
        #
        # 300мс — именно МИНИМУМ, нужный против этой гонки, а сверху ложится
        # случайная добавка (см. sleep_jittered): без неё пауза фиксирована,
        # и вставки попадают в одну и ту же фазу poll-цикла воркера — попытки
        # 2-5 давали 116-118мс, то есть одно число вместо разброса по
        # [0, интервал). Обе цели совместимы: гонке важна нижняя граница
        # паузы, разбросу — её изменчивость. Итог 0.300-1.299с: верхнего
        # потолка здесь нет (в отличие от Части 2), потому что вставка
        # приходит в НАЧАЛО свежего цикла WaitForJob сразу после complete, а
        # не к его концу, и до стыка циклов остаётся больше половины бюджета.
        sleep_jittered 300 1000
    done
    close_probe

    report "$mode" "$note" "${samples[@]}"
    kill "$W" 2>/dev/null || true
    wait "$W" 2>/dev/null || true
}

