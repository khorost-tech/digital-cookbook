#!/usr/bin/env bash
# Артефакт 3: что происходит с ДОЛГОЙ джобой, когда воркеру приходит SIGTERM
# (например, деплой на проде). Смысл: сигнал НЕ бросает начатую джобу —
# воркер дорабатывает её до конца, новых больше не берёт, и лишь потом
# выходит (см. doWork/ctx в worker/main.go).
#
# Критическая деталь, найденная и исправленная в Задаче 3: пока идёт такая
# доработка, heartbeat ОБЯЗАН продолжать продлевать аренду. Наивная реализация
# «получили сигнал -> просто досыпаем остаток работы» перестаёт трогать
# leased_until, и если работа длиннее аренды, аренда истекает ПРЯМО В ХОДЕ
# штатного завершения: ReclaimExpired возвращает джобу в очередь, её
# подхватывает второй воркер — деплой сам себе создаёт отложенное двойное
# исполнение, то самое, ради которого вообще существует lease.
#
# Демонстрация не постулирует это, а делает измеримым: рядом с воркером,
# который дорабатывает джобу после сигнала, запускается конкурирующий
# `-reclaim`, и исход читается по числам в БД (state/attempt), а не по тону
# лога.
#
#   Оба сценария идут по ОДИНАКОВОМУ таймлайну: SIGTERM через ~1с после
#     старта (работы впереди ещё ~5с), конкурирующий `-reclaim` — через ~5с
#     после старта (~4с после SIGTERM), то есть уже ПОСЛЕ того, как истёк бы
#     исходный, непродлённый lease (3с). Единственное отличие между
#     сценариями — флаг -heartbeat; момент проверки в обоих одинаков, иначе
#     контраст доказывал бы не только его.
#   Сценарий A (heartbeat включён — штатное поведение): к моменту проверки
#     heartbeat уже несколько раз продлил аренду, поэтому `-reclaim` находит
#     0 истёкших аренд. Джоба доходит до done тем же воркером, attempt=1.
#   Сценарий B (падающий вариант — heartbeat ВЫКЛЮЧЕН, воспроизводит дефект
#     Задачи 3 до исправления): тот же work/lease/SIGTERM и тот же момент
#     проверки, но во время доработки аренда не продлевается — она истекла
#     ещё на 3-й секунде. Тот же `-reclaim` находит её и возвращает в
#     очередь; второй воркер забирает её и доводит до done — attempt=2.
#     Исходный воркер дописывает работу и обнаруживает, что аренда уже не
#     его.
#
# Доказательство несут ДВЕ точки наблюдения, которые снимаются в обеих ветках
# в один и тот же момент и зависят ровно от одного флага: «аренда_истекла»
# (f против t) и результат конкурирующего reclaim (0 против 1). Параметры
# воркера в ветках одинаковы — work/lease/for/момент SIGTERM, — отличается
# только heartbeat=true/false.
#
# Итоговое attempt=1 против attempt=2 — уже СЛЕДСТВИЕ, а не независимая улика:
# во второй ветке дополнительно запускается воркер-«спасатель», который
# доигрывает возвращённую джобу. Если читатель просто переключит heartbeat в
# первой ветке, он увидит не «done, attempt=2», а «queued, attempt=1» —
# джобу вернули в очередь, но добивать её в этой ветке некому. Расхождение
# от этого не исчезает: оно уже зафиксировано двумя точками выше.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
export GOPROXY=https://go.khorost.tech,direct

PSQL=(docker exec bj-postgres psql -U jobs -d jobs -t -A -F'|')

# --- Проверка окружения. Без неё недоступный Postgres или несобранный
# воркер выглядели бы как «джоба почему-то не done» — то есть как молчаливый
# ложный результат демонстрации, а не как её явный отказ. ---
if ! docker exec bj-postgres pg_isready -U jobs -d jobs >/dev/null 2>&1; then
    echo "ОШИБКА: PostgreSQL (контейнер bj-postgres) недоступен." >&2
    echo "Подними стенд: docker compose -f compose/compose.yml up -d" >&2
    exit 1
fi

WORKER_BIN="/tmp/bj-shutdown-demo-worker.$$"
trap 'kill $(jobs -p) 2>/dev/null || true; rm -f "$WORKER_BIN"' EXIT

echo "--- сборка воркера ---"
if ! ( cd worker && go build -o "$WORKER_BIN" . ); then
    echo "ОШИБКА: воркер не собрался — демонстрация невозможна." >&2
    exit 1
fi
# Собранный бинарник напрямую (не go run): SIGTERM должен дойти до самого
# воркера, а не до обёртки go build/run, иначе демонстрация была бы ложной.

# work заведомо длиннее lease: исход целиком зависит от того, продлевается ли
# аренда во время доработки после сигнала, а не от абсолютных величин таймеров.
WORK=6s
LEASE=3s

echo
echo "=== СЦЕНАРИЙ A: heartbeat включён, SIGTERM во время работы ==="
docker exec bj-postgres psql -U jobs -d jobs -q -c "TRUNCATE jobs RESTART IDENTITY"
bash scripts/seed.sh 1 >/dev/null

"$WORKER_BIN" -id deploy-a -work "$WORK" -lease "$LEASE" -for 20s -heartbeat=true \
    >/tmp/bj-shutdown-a.log 2>&1 &
DEMO_PID=$!
sleep 1
echo "--- джоба взята ~1с назад, отправляем SIGTERM (работы впереди ещё ~5с) ---"
kill -TERM "$DEMO_PID"

sleep 4
echo "--- 5с после старта: исходная (непродлённая) аренда в 3с истекла бы ещё"
echo "    2с назад — проверяем, продлил ли её heartbeat ---"
"${PSQL[@]}" -c "SELECT id, state, leased_by, leased_until < now() AS аренда_истекла, attempt FROM jobs"
echo "--- конкурирующий reclaim в тот же момент, что и в сценарии B ---"
"$WORKER_BIN" -reclaim | tail -1
echo "--- состояние после reclaim: джоба всё ещё running за тем же воркером ---"
"${PSQL[@]}" -c "SELECT id, state, leased_by, attempt FROM jobs"

wait "$DEMO_PID" 2>/dev/null || true
echo "--- лог воркера (последние строки) ---"
tail -4 /tmp/bj-shutdown-a.log
echo "--- итоговое состояние джобы ---"
"${PSQL[@]}" -c "SELECT id, state, leased_by, attempt FROM jobs"

echo
echo "=== СЦЕНАРИЙ B (падающий вариант): heartbeat выключен, тот же SIGTERM ==="
docker exec bj-postgres psql -U jobs -d jobs -q -c "TRUNCATE jobs RESTART IDENTITY"
bash scripts/seed.sh 1 >/dev/null

"$WORKER_BIN" -id deploy-b -work "$WORK" -lease "$LEASE" -for 20s -heartbeat=false \
    >/tmp/bj-shutdown-b.log 2>&1 &
DEMO_PID=$!
sleep 1
echo "--- джоба взята ~1с назад, отправляем тот же SIGTERM ---"
kill -TERM "$DEMO_PID"

sleep 4
echo "--- 5с после старта: аренда (3с) истекла ещё ДО завершения работы (6с) —"
echo "    доработка идёт, но продлевать её некому ---"
"${PSQL[@]}" -c "SELECT id, state, leased_by, leased_until < now() AS аренда_истекла, attempt FROM jobs"
echo "--- тот же конкурирующий reclaim: на этот раз находит истёкшую аренду ---"
"$WORKER_BIN" -reclaim | tail -1
"${PSQL[@]}" -c "SELECT id, state, leased_by, attempt FROM jobs"

echo "--- второй воркер разбирает освободившуюся джобу, пока первый ещё дорабатывает свою копию ---"
"$WORKER_BIN" -id rescuer -work 200ms -lease 5s -for 1500ms >/tmp/bj-shutdown-rescuer.log 2>&1
tail -2 /tmp/bj-shutdown-rescuer.log

wait "$DEMO_PID" 2>/dev/null || true
echo "--- лог первого воркера: дописал работу и обнаружил, что аренда уже не его ---"
tail -4 /tmp/bj-shutdown-b.log
echo "--- итоговое состояние джобы: attempt=2 — джоба выполнена ДВАЖДЫ ---"
"${PSQL[@]}" -c "SELECT id, state, leased_by, attempt FROM jobs"

echo
echo "Что показано (по числам в БД, не по тону лога):"
echo "  сценарий A: reclaim во время доработки вернул 0 джоб, итог attempt=1 —"
echo "  джобу довёл ОДИН воркер, SIGTERM не оборвал её и не породил повтор;"
echo "  сценарий B: те же work/lease/SIGTERM, отличие только heartbeat=false —"
echo "  тот же reclaim в тот же момент дорабатывания вернул 1 джобу в очередь,"
echo "  её забрал второй воркер, итог attempt=2 — джоба выполнена дважды."
echo
echo "Что это отбивает: тезис «воркер, доработавший джобу после SIGTERM, ведёт"
echo "себя безопасно сам по себе» — неверен. Безопасность даёт не факт"
echo "доработки, а heartbeat, продолжающий работать ВО ВРЕМЯ доработки. Без"
echo "него доработка — это гонка с истечением аренды, которую доработка же"
echo "и проигрывает, а значит превращает штатное завершение в источник"
echo "двойного исполнения."
