#!/usr/bin/env bash
# Артефакт 11 (одиннадцатый, дополнение к спеке): группировка коммитов (group
# commit) как механизм, задающий форму кривой пропускной способности.
#
# Артефакт 10 (throughput-demo.sh) показал странную форму: на воркера
# пропускная способность падает на треть на шаге 1 -> 2 и дальше держится
# константой (218 -> 147 -> 146 -> 143 джоб/сек на воркера). Отключение
# synchronous_commit локализовало причину в пути сброса журнала. Но САМ
# механизм оттуда не следовал: арифметика допускала группировку коммитов, а
# прямого наблюдения не было — только вывод из косвенных чисел.
#
# Здесь механизм наблюдается НАПРЯМУЮ. PostgreSQL 18 считает сбросы журнала в
# pg_stat_io (перенесены туда из pg_stat_wal): object='wal', context='normal',
# backend_type='client backend'. Снимаем дельту writes/fsyncs за окно замера и
# считаем, сколько коммитов проехало на одном сбросе.
#
# ГИПОТЕЗА ДО ЗАМЕРА (оставлена намеренно — видно, что именно проверялось):
# частота сбросов примерно постоянна по N, а коммитов на один сброс растёт
# пропорционально числу воркеров.
#
# ЧТО НАЙДЕНО: гипотеза верна лишь начиная с N=4, картина ТРЁХрежимная.
#   N=1  — путь сброса НЕ насыщен (~440 сбросов/с при потолке ~590), каждый
#          коммит получает свой сброс: ~1.02 коммита на сброс;
#   N=2  — путь сброса насыщен (~590/с), но группировки ЕЩЁ НЕТ: те же ~1.02.
#          Именно здесь выработка на воркера падает на треть — это плата за
#          вход в насыщенный режим, а не эффект группировки;
#   N>=4 — рост несёт только группировка: 2.07 при N=4, 4.09 при N=8, 8.2 при
#          N=16, при почти неизменной частоте сбросов.
# Наблюдения ложатся на правило комм/сброс ~ max(1, N/2). Оно подогнано на
# трёх точках и затем проверено предсказанием на N=16 (ожидалось ~8, измерено
# 8.18-8.30) — но остаётся регулярностью, а не механизмом: откуда берётся
# коэффициент 1/2, эти замеры не отвечают.
#
# Равенство «коммитов = 2 x джоб» держится на том, что heartbeat не срабатывает
# ни разу: при -lease 30s первый тик пришёлся бы на 10-ю секунду, а -work 0s
# завершает джобу мгновенно. Поднимете -work — множитель тихо перестанет быть
# верным, а таблица останется правдоподобной.
#
# Считаются сбросы только backend_type='client backend' — это путь коммита.
# У walwriter свой счётчик, и при wal_writer_delay=200ms он даёт единицы
# сбросов в секунду против ~590 здесь, то есть на результат не влияет.
#
# ПАДАЮЩИЙ ВАРИАНТ: если бы группировки не было и каждый коммит выпускал свой
# сброс, fsyncs/сек росли бы вместе с коммитами, а коммитов на сброс держалось
# бы около 1.0 при ЛЮБОМ N, включая 8 и 16. Это и есть проверяемое различие.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

WINDOW="${WINDOW:-10}"      # длительность окна замера, секунд
SEED_JOBS="${SEED_JOBS:-150000}"
PSQL=(docker exec bj-postgres psql -U jobs -d jobs -t -A)

# --- Проверка окружения: недоступный Postgres не должен выглядеть как
# «сбросов почему-то ноль». ---
if ! docker exec bj-postgres pg_isready -U jobs -d jobs >/dev/null 2>&1; then
    echo "ОШИБКА: PostgreSQL (контейнер bj-postgres) недоступен." >&2
    echo "Подними стенд: docker compose -f compose/compose.yml up -d" >&2
    exit 1
fi

# pg_stat_io с колонкой fsyncs существует не во всех версиях: в PG 18 счётчики
# сбросов WAL перенесены сюда из pg_stat_wal. Без этой проверки скрипт молча
# считал бы пустоту и напечатал бы нули как результат замера.
HAS_IO=$("${PSQL[@]}" -c "SELECT count(*) FROM pg_stat_io
                          WHERE object='wal' AND backend_type='client backend'")
if [ "${HAS_IO:-0}" -eq 0 ]; then
    echo "ОШИБКА: в pg_stat_io нет строк для object='wal' — эта версия PostgreSQL" >&2
    echo "не отдаёт счётчики сбросов журнала там, где их ждёт скрипт." >&2
    exit 1
fi

WORKER_BIN="/tmp/bj-groupcommit-worker.$$"
cleanup() { kill $(jobs -p) 2>/dev/null || true; rm -f "$WORKER_BIN"; }
trap cleanup EXIT

echo "--- сборка воркера ---"
export GOPROXY=https://go.khorost.tech,direct
if ! ( cd worker && go build -o "$WORKER_BIN" . ); then
    echo "ОШИБКА: воркер не собрался — демонстрация невозможна." >&2
    exit 1
fi

io_fsyncs() {
    "${PSQL[@]}" -c "SELECT fsyncs FROM pg_stat_io
                     WHERE object='wal' AND context='normal'
                       AND backend_type='client backend'"
}
done_count() { "${PSQL[@]}" -c "SELECT count(*) FROM jobs WHERE state='done'"; }

echo
echo "=== АРТЕФАКТ 11: сколько коммитов едет на одном сбросе журнала ==="
echo "Окно ${WINDOW}с на каждое N. Джоба = 2 автокоммит-UPDATE (claim и complete),"
echo "поэтому коммитов ровно вдвое больше выполненных джоб."
echo
printf "%3s %10s %10s %10s %12s %14s\n" "N" "джоб/сек" "комм/сек" "сбросов/с" "комм/сброс" "на воркера"

for N in 1 2 4 8 16; do
    # Очередь наполняется заново перед КАЖДЫМ N: накопленные мёртвые версии от
    # предыдущего замера замедлили бы следующий, и рост числа воркеров
    # смешался бы с ростом bloat.
    "${PSQL[@]}" -c "TRUNCATE jobs RESTART IDENTITY" >/dev/null
    docker exec -i bj-postgres psql -U jobs -d jobs -q -v ON_ERROR_STOP=1 <<SQL >/dev/null
INSERT INTO jobs (kind) SELECT 'gc' FROM generate_series(1, ${SEED_JOBS});
SQL

    for i in $(seq 1 "$N"); do
        "$WORKER_BIN" -id "g$i" -work 0s -lease 30s -for "$((WINDOW + 4))s" >/dev/null 2>&1 &
    done
    sleep 2   # окно открывается ПОСЛЕ подъёма воркеров: старт бинаря и
              # установка соединения не должны попасть в замер

    F0=$(io_fsyncs); D0=$(done_count); T0=$(date +%s.%N)
    sleep "$WINDOW"
    F1=$(io_fsyncs); D1=$(done_count); T1=$(date +%s.%N)

    wait 2>/dev/null || true

    # Делитель — РЕАЛЬНОЕ прошедшее время между снимками, а не номинальный
    # $WINDOW: если бы psql подтормозил, номинал завысил бы результат молча.
    awk -v f0="$F0" -v f1="$F1" -v d0="$D0" -v d1="$D1" \
        -v t0="$T0" -v t1="$T1" -v n="$N" 'BEGIN {
        el = t1 - t0; jobs = d1 - d0; fs = f1 - f0; com = jobs * 2;
        printf "%3d %10.1f %10.1f %10.1f %12.2f %14.1f\n",
               n, jobs/el, com/el, fs/el, (fs > 0 ? com/fs : 0), jobs/el/n;
    }'
done

echo
echo "ЧТО ЧИТАТЬ — исход ТРЁХрежимный, а не «есть группировка / нет группировки»:"
echo "  N=1  «сбросов/с» заметно НИЖЕ потолка, «комм/сброс» ~1.0 — путь сброса"
echo "       не насыщен, каждый коммит уезжает своим сбросом;"
echo "  N=2  «сбросов/с» вышло на потолок, «комм/сброс» ВСЁ ЕЩЁ ~1.0 — насыщение"
echo "       наступило, группировки ещё нет; здесь и падает выработка на воркера;"
echo "  N>=4 «сбросов/с» держится на потолке, «комм/сброс» растёт как ~N/2 —"
echo "       дальше пропускную способность наращивает только группировка."
echo "Если бы группировки не было вовсе, «комм/сброс» осталось бы ~1.0 и при"
echo "N=8, и при N=16, а «сбросов/с» росло бы вместе с «комм/сек»."
echo
echo "ОГОВОРКА: на WSL2 + Docker Desktop fdatasync не гарантированно доходит до"
echo "физического устройства, поэтому абсолютную частоту сбросов НЕ следует"
echo "читать как характеристику диска. Проверяется здесь не скорость сброса, а"
echo "то, СКОЛЬКО коммитов на один сброс приходится — это отношение от"
echo "особенностей виртуализации не зависит."
