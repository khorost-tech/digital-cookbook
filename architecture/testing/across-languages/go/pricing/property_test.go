// ПРИЁМ 2: property-based. Вместо примеров, выбранных человеком, — генератор
// случаев + ИНВАРИАНТ, который обязан держаться на любом входе. Плюс шринкинг:
// найдя падение, движок сам ужимает вход до короткого читаемого контрпримера
// (минимального ЛОКАЛЬНО — см. тест 3). Именно шринкинг отличает property-based
// от «накидаем рандома».
//
// Здесь три теста, и они рассказывают историю целиком:
//   1. инвариант, который держится;
//   2. НАИВНОЕ свойство монотонности — почти всегда проходит, хотя нарушение
//      реально есть: находит ненадёжно;
//   3. то же свойство с генератором, знающим структуру домена, — падает
//      и ужимается до границы тира.

// 1. Свойство, которое ДЕРЖИТСЯ: скидка неотрицательна и не больше суммы.
// Точность формулировки важна: свойство КВАНТИФИЦИРОВАНО над всем диапазоном
// («для любого total»), но движок проверяет ВЫБОРКУ из него (по умолчанию 100
// значений). Табличный тест знает всё про шесть точек; property заявляет про
// весь диапазон, а проверяет сэмпл. Разница между «утверждаю» и «проверил» —
// ровно то место, где ломается тест 2 ниже.
func TestProperty_DiscountВРазумныхГраницах(t *testing.T) {
	rapid.Check(t, func(t *rapid.T) {
		total := rapid.Int64Range(0, 1_000_000_000).Draw(t, "total")

		d := Discount(total)
		if d < 0 {
			t.Fatalf("скидка отрицательна: Discount(%d) = %d", total, d)
		}
		if d > total {
			t.Fatalf("скидка больше суммы заказа: Discount(%d) = %d", total, d)
		}
		if p := Price(total); p < 0 {
			t.Fatalf("итоговая цена отрицательна: Price(%d) = %d", total, p)
		}
	})
}

// monotonic — само свойство: заказ на большую сумму не может стоить дешевле.
// Звучит как очевидная истина, но у тиров есть скачок: на 99.99 скидки нет
// (платим 99.99), а на 100.00 сразу 5% (платим 95.00). Заплатить больше —
// выйдет дешевле. Табличный тест такое не ловит: он проверяет точки по
// отдельности, а не СВЯЗЬ между ними.
func monotonic(t *rapid.T, gen *rapid.Generator[int64]) {
	a := gen.Draw(t, "a")
	b := gen.Draw(t, "b")
	if a > b {
		a, b = b, a // a <= b
	}
	if Price(a) > Price(b) {
		t.Fatalf("заказ на %d стоит %d, а на %d — %d: заплатить больше оказалось дешевле",
			a, Price(a), b, Price(b))
	}
}

// 2. Наивная версия: «просто дай мне числа из диапазона».
//
// Тест почти всегда ПРОХОДИТ — и это ложное спокойствие: нарушение существует,
// но генератор попадает в него редко. На дефолтных 100 примерах rapid не нашёл
// его ни разу за 20 прогонов (это «редко», а не «никогда»: у jqwik с его
// дефолтом в 1000 попыток выходит примерно 1 находка на 8 прогонов).
// Чтобы поймать, нужна пара «a чуть ниже порога, b сразу за ним» — узкая полоса
// входов, а rapid смещает выдачу к малым числам и краям: насколько — видно в
// соседнем замере TestРаспределениеГенератора (distribution_test.go).
// Серию прогонов гоняет ../property-matrix.sh.
//
// Запуск (падает не всегда — в этом и суть демонстрации):
//
//	go test -tags=property_demo -run Наивн ./pricing/ -rapid.checks=20000
func TestProperty_МонотонностьНаивныйГенератор(t *testing.T) {
	if !propertyDemo {
		t.Skip("демонстрация: go test -tags=property_demo -run Наивн ./pricing/ -rapid.checks=20000")
	}
	rapid.Check(t, func(t *rapid.T) {
		monotonic(t, rapid.Int64Range(0, 30_000))
	})
}

// 3. Генератор, знающий СТРУКТУРУ домена, но не знающий про нарушение.
//
// Ключевая разница: мы не подсказываем движку ответ («упади на 9501»). Мы
// сообщаем факт из спецификации — у скидки есть пороги, и окрестности порогов
// это интересная область. Само нарушение по-прежнему находит свойство, а не
// человек.
//
// Теперь тест падает стабильно и на настройках по умолчанию, а шринкинг выдаёт
// контрпример на границе тира. Минимальность при этом ЛОКАЛЬНАЯ: в части
// прогонов выходит 19500 вместо истинного минимума 9501. Почему шринкер
// остановился именно там — не утверждаем: это требует трассировки шринкера.
//
//	go test -tags=property_demo -run Доменн ./pricing/
func TestProperty_МонотонностьДоменныйГенератор(t *testing.T) {
	if !propertyDemo {
		t.Skip("демонстрация: go test -tags=property_demo -run Доменн ./pricing/")
	}
	nearTiers := rapid.OneOf(
		rapid.Int64Range(0, 30_000),
		rapid.Int64Range(Tier1Cents-500, Tier1Cents+500),
		rapid.Int64Range(Tier2Cents-500, Tier2Cents+500),
	)
	rapid.Check(t, func(t *rapid.T) {
		monotonic(t, nearTiers)
	})
}
