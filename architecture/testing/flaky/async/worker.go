// Package async — класс flaky «асинхронность через Sleep».
// Результат готовится в горутине. Ждать его time.Sleep'ом — недетерминизм
// (горутина может не успеть); правильно — синхронизация каналом.
package async

// Compute запускает «медленную» работу в горутине и возвращает канал, по
// которому придёт результат. Читатель ждёт значение из канала, а не спит:
// синхронизация происходит по факту готовности, не по таймеру.
func Compute(x int) <-chan int {
	out := make(chan int, 1)
	go func() {
		out <- x * x // «работа»
	}()
	return out
}
