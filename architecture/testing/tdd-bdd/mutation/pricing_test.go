package mutation

import "testing"

// СЛАБЫЙ набор: проверяет только «серединные» значения тиров (150, 250) и
// одно без скидки (50). НЕ проверяет точные границы (ровно 100.00 / 200.00).
// Из-за этого мутант «>=» → «>» на границе выживет: 150 и 250 остаются в тех
// же тирах и после подмены, а границу никто не пинает.
func TestTotal_Weak(t *testing.T) {
	cases := []struct {
		price int64
		want  int64
	}{
		{5000, 5000},   // 50.00 — без скидки
		{15000, 14250}, // 150.00 — 5%
		{25000, 22500}, // 250.00 — 10%
	}
	for _, c := range cases {
		if got := Total([]Item{{c.price, 1}}); got != c.want {
			t.Errorf("Total(%d) = %d, want %d", c.price, got, c.want)
		}
	}
}
