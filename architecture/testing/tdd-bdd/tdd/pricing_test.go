package tdd

import "testing"

// Финальные тесты в table-driven форме — итог трёх red-green-refactor циклов.
// Границы тиров проверены явно: 99.99 (нет скидки) / 100.00 (5%) /
// 199.99 (5%) / 200.00 (10%).
func TestTotal(t *testing.T) {
	cases := []struct {
		name  string
		items []Item
		want  int64
	}{
		{"пустая корзина", nil, 0},
		{"ниже порога — без скидки", []Item{{2500, 2}}, 5000},               // 50.00
		{"на копейку ниже 100 — без скидки", []Item{{9999, 1}}, 9999},        // 99.99
		{"ровно 100.00 — 5%", []Item{{10000, 1}}, 9500},                      // 100.00 → 95.00
		{"150.00 — 5%", []Item{{15000, 1}}, 14250},                           // → 142.50
		{"на копейку ниже 200 — всё ещё 5%, скидка усекается", []Item{{19999, 1}}, 19000}, // 999.95к скидки → усечение до 999к
		{"ровно 200.00 — 10%", []Item{{20000, 1}}, 18000},                    // 200.00 → 180.00
		{"250.00 — 10%", []Item{{25000, 1}}, 22500},                          // → 225.00
		{"несколько позиций суммируются", []Item{{12000, 1}, {8000, 1}}, 18000}, // 200.00 → 10%
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := Total(c.items); got != c.want {
				t.Errorf("Total(%v) = %d, want %d", c.items, got, c.want)
			}
		})
	}
}
