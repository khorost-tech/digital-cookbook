package codec

// Нотации, в которых стенд описывает схемы. Строки те же, что в
// манифесте стенда: описание одно, и переводить его из одних слов в
// другие по дороге незачем.
const (
	NotationAvro       = "avro"
	NotationProtobuf   = "protobuf"
	NotationJSONSchema = "json-schema"
)

// Schema — схема, УЖЕ прочитанная и сверенная с манифестом стенда.
//
// Круг правок 6. Раньше кодеки и вычисление ожидания принимали ПУТЬ и
// каждый открывал файл сам: один и тот же файл читался три-пять раз за
// пробу, и между сверкой дайджеста и последним чтением оставалась щель.
// Щель не теоретическая: восемь прогонов из трёхсот успели напечатать
// чистые «ok», пройдя сверку и прочитав уже другое содержимое.
//
// Теперь файл читается ОДИН раз, дайджест считается по тем же байтам,
// которые здесь лежат, и дальше все — разбор схемы, кодирование,
// чтение — работают только с ними. Взять содержимое где-то ещё просто
// неоткуда.
//
// Name — имя записи манифеста. Оно же тождество схемы: две РАЗНЫЕ
// записи манифеста — это две разные схемы, даже если содержимое у них
// совпадает побайтово (см. вырожденную пару в spec.md).
type Schema struct {
	Name     string
	Notation string
	Bytes    []byte
}

// SameSchema отвечает, идёт ли речь об одной и той же схеме стенда.
// Сравниваются ЗАПИСИ манифеста, а не содержимое: пара разных записей с
// одинаковым содержимым — законный повод для вывода о вырожденности, а
// не основание считать их одним файлом.
func SameSchema(a, b Schema) bool { return a.Name == b.Name }
