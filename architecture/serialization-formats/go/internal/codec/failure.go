package codec

import "fmt"

// ErrProbeFailure — сентинел «сломалась проба, а не формат».
//
// Круг правок 4, вторая правка. До неё любая ошибка внутри Encode или
// Decode превращалась в один и тот же исход «формат отказался читать».
// Разница принципиальная: отказ формата — это находка, ради которой
// стенд существует, а невозможность прочитать файл схемы или собрать
// её в рабочий вид — наша поломка, и в таблицу она обязана попадать
// отдельной пометкой. Насколько это опасно, показал живой баг круга 3:
// пока компилятор JSON Schema спотыкался о разделители пути, ВСЯ
// колонка json-schema выглядела бы как «формат отказал» — таблица
// правдоподобная и целиком неверная.
//
// Граница проведена так: всё, что происходит ДО того, как схема
// заработала (прочитать файл, разобрать его, собрать дескриптор,
// скомпилировать), — сбой пробы. Всё, что формат решает УЖЕ ИМЕЯ
// рабочую схему (проверка совместимости, валидация записи, разбор
// байтов), — поведение формата.
var ErrProbeFailure = errNamed("сбой самой пробы, а не отказ формата")

type namedError string

func (e namedError) Error() string { return string(e) }

func errNamed(s string) error { return namedError(s) }

// probeFailure оборачивает ошибку подготовки схемы, сохраняя и исходную
// причину для человека, и сентинел для классификации. Опознание идёт
// через errors.Is по цепочке обёрток, а не по тексту: текст каждый
// кодек пишет по-своему, и сравнение строк развалилось бы на первой же
// правке формулировки.
func probeFailure(what string, err error) error {
	return fmt.Errorf("%s: %v (%w)", what, err, ErrProbeFailure)
}

// probeFailuref — то же самое там, где исходной ошибки нет, а есть
// только описание несостыковки.
func probeFailuref(format string, args ...any) error {
	return fmt.Errorf("%s (%w)", fmt.Sprintf(format, args...), ErrProbeFailure)
}
