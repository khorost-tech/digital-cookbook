#!/usr/bin/env bash
# Матрица: три плеча x две операции x гарантии долговечности.
# Плечи ЧЕРЕДУЮТСЯ по позиции внутри каждого круга (не по кругам целиком) по
# СБАЛАНСИРОВАННОЙ схеме — латинскому квадрату порядка 3 (см. функцию perm
# ниже): за три круга каждое плечо стоит на первой, второй и третьей позиции
# ровно по одному разу. Без этого позиция в списке — не только сама БД —
# становится систематическим фактором: первое плечо в круге всегда стартует
# в чуть других условиях (кэши, планировщик ОС), чем второе и третье, даже
# если сам хост не дрейфует; а несбалансированная ротация (например, простой
# выбор из 6 произвольных перестановок) может отдать одному плечу первую
# позицию чаще прочих и просто переставить смещение, а не убрать его.
# SEED печатается в фикстуру и задаёт лишь СДВИГ фиксированного квадрата
# (какое из трёх плеч стартует в круге 1) — сама схема детерминирована и
# сбалансирована при любом SEED, прогон с тем же SEED воспроизводим.
set -euo pipefail

# Windows/Git Bash: без этого docker compose иногда перегоняет POSIX-подобные
# пути в аргументах через путепреобразование MSYS.
export MSYS_NO_PATHCONV=1

N="${N:-20000}"
SEED="${SEED:-1337}"
# Скрипт запускается на ХОСТЕ (через docker compose exec), а не внутри
# контейнера bench, поэтому вывод пишем в ./fixtures относительно каталога
# скрипта — это тот же каталог, что смонтирован в контейнер как /fixtures.
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${OUT:-$SELF_DIR/../fixtures/latency.txt}"

run() { docker compose exec -T bench bench -arm "$1" -op "$2" -n "$N" -sync "$3" -pg-sync "$4"; }

# Группа A — полная долговечность: все три плеча synchronous=FULL /
# synchronous_commit=on. Группа B — ослабленная: sqlite NORMAL, оба
# Postgres-плеча synchronous_commit=off. Каждый элемент группы хранит СВОЮ
# пару (sync, pg-sync) — при перестановке меняется только порядок запуска,
# гарантии за каждым плечом остаются его собственными.
ARM_A=(sqlite pg-uds pg-tcp)
SYNC_A=(FULL FULL FULL)
PGSYNC_A=(on on on)

ARM_B=(sqlite pg-uds pg-tcp)
SYNC_B=(NORMAL FULL FULL)
PGSYNC_B=(on off off)

# Латинский квадрат порядка 3 через циклическую ротацию: perm(n) = (n, n+1,
# n+2) mod 3. За три ПОСЛЕДОВАТЕЛЬНЫХ круга (round=1,2,3, значит и n=k+1,k+2,
# k+3 для любого k) остаток n%3 обязан пройти все три вычета 0,1,2 по разу —
# значит каждое плечо стоит на первой позиции РОВНО один раз за три круга, и
# по построению ротации — точно так же ровно один раз на второй и на третьей.
# Никакой доп. перестановки (swap) нет специально: любая асимметрия между
# двумя оставшимися местами при добавлении второй степени свободы легко
# нарушает баланс по второй/третьей позиции (проверено и отброшено — более
# ранняя версия с (n/3)%2 давала перекос: если параметр n не пересекал
# границу кратности 3 одинаково для всех трёх кругов, вторая и третья
# позиции переставали быть равномерными). Чистая ротация без swap — то же
# самое свойство, что и у фиксированного квадрата (012, 120, 201), просто
# сдвинутого на SEED, поэтому оно сбалансировано всегда, при любом SEED.
perm() {
  local n="$1"
  local rot=$(( ((n % 3) + 3) % 3 ))
  local a=$rot b c
  b=$(( (rot + 1) % 3 ))
  c=$(( (rot + 2) % 3 ))
  echo "$a $b $c"
}

run_group() {
  local -n arms="$1"
  local -n syncs="$2"
  local -n pgsyncs="$3"
  local op="$4"
  local order="$5"
  local i
  for i in $order; do
    run "${arms[$i]}" "$op" "${syncs[$i]}" "${pgsyncs[$i]}"
  done
}

{
  echo "== латентность, n=$N операций на прогон =="
  date -u +"прогон: %Y-%m-%dT%H:%M:%SZ"
  echo "seed: $SEED (порядок плеч ротируется по кругам, см. комментарий в run-latency.sh)"
  for round in 1 2 3; do
    echo "-- круг $round --"
    # Разные смещения для групп A и B, чтобы порядок не совпадал внутри
    # одного круга: иначе позиционное смещение группы A предсказывало бы
    # позиционное смещение группы B.
    permA="$(( SEED + round ))"
    permB="$(( SEED + round + 11 ))"
    orderA="$(perm "$permA")"
    orderB="$(perm "$permB")"
    echo "порядок (полная долговечность): $orderA [индексы sqlite=0 pg-uds=1 pg-tcp=2]"
    echo "порядок (ослабленная долговечность): $orderB [индексы sqlite=0 pg-uds=1 pg-tcp=2]"
    for op in read insert; do
      run_group ARM_A SYNC_A PGSYNC_A "$op" "$orderA"
      run_group ARM_B SYNC_B PGSYNC_B "$op" "$orderB"
    done
  done
} | tee "$OUT"

echo "фикстура записана: $OUT"
