        ok=0; struct_ok=0
      fi
      if [ "${S_TASKS[$run:$ord:$off]}" != "$SHARD_COUNT" ]; then
        echo "[FAIL] Прогон $run, серия $ord, OFFSET=$off: Task Count=${S_TASKS[$run:$ord:$off]}, ожидали $SHARD_COUNT — запрос без фильтра по ключу обязан опросить все шарды."
        ok=0; struct_ok=0
      fi
    done
  done
done
if [ "$struct_ok" = "1" ]; then
  echo "[OK] Во всех $RUNS прогонах и в обеих сериях число строк, поднятых с шардов,"
  echo "     ТОЧНО равно $SHARD_COUNT × (OFFSET + $PAGE_LIMIT): от $(( SHARD_COUNT * PAGE_LIMIT )) при OFFSET=0"
  echo "     до $(( SHARD_COUNT * (MAX_OFFSET + PAGE_LIMIT) )) при OFFSET=$MAX_OFFSET. Рост линеен по OFFSET и кратен числу шардов."
fi

# 2. Падающий вариант по структуре: строки с шардов ОБЯЗАНЫ зависеть от OFFSET.
if [ "${S_ROWS[1:A:0]}" = "${S_ROWS[1:A:$MAX_OFFSET]}" ]; then
  echo "[FAIL] Число строк, поднятых с шардов, одинаково при OFFSET=0 и OFFSET=$MAX_OFFSET (${S_ROWS[1:A:0]}) — это и есть падающий вариант: смещение не стоит ничего."
  ok=0
fi

# 3. СТРУКТУРНЫЙ ГЕЙТ: способ доступа внутри шарда.
#    Серия А сортирует не по ключу шардирования — подходящего индекса нет,
#    шард обязан читать себя целиком (Seq Scan). Серия Б сортирует по ключу,
#    у которого PK начинается с customer_id — доступен Index Scan.
#    Это свойство схемы и планировщика, от скорости хоста не зависит.
access_ok=1
for run in $(seq 1 "$RUNS"); do
  for off in "${OFFSETS[@]}"; do
    if [ "${S_SHARDACCESS[$run:A:$off]}" != "Seq Scan" ]; then
      echo "[FAIL] Прогон $run, серия А, OFFSET=$off: доступ внутри шарда '${S_SHARDACCESS[$run:A:$off]}', ожидали 'Seq Scan' — сортировка НЕ по ключу шардирования обязана читать шард целиком."
      ok=0; access_ok=0
    fi
    case "${S_SHARDACCESS[$run:B:$off]}" in
      "Index Scan"|"Index Only Scan") : ;;
      *)
        echo "[FAIL] Прогон $run, серия Б, OFFSET=$off: доступ внутри шарда '${S_SHARDACCESS[$run:B:$off]}', ожидали Index Scan — сортировка по ключу шардирования обязана идти по PK."
        ok=0; access_ok=0
        ;;
    esac
    if [ "${S_SHARDSORTED[$run:A:$off]}" != "да" ]; then
      echo "[FAIL] Прогон $run, серия А, OFFSET=$off: шард НЕ сортировал у себя, ожидали сортировку — без индекса по ключу сортировки шард обязан отсортировать своё."
      ok=0; access_ok=0
    fi
    if [ "${S_SHARDSORTED[$run:B:$off]}" != "нет" ]; then
      echo "[FAIL] Прогон $run, серия Б, OFFSET=$off: шард сортировал у себя, ожидали обход без сортировки — Index Scan по PK обязан отдавать уже упорядоченное."
      ok=0; access_ok=0
    fi
  done
done
if [ "$access_ok" = "1" ]; then
  echo "[OK] Во всех $RUNS прогонах на всех OFFSET: серия А — Seq Scan + сортировка внутри шарда;"
  echo "     серия Б — Index Scan по PK, шард НЕ сортирует. Это структурное различие серий."
fi

# 4. СТРУКТУРНЫЙ ГЕЙТ: метод сортировки НА КООРДИНАТОРЕ на глубоком OFFSET.
#    Серия Б тащит на координатор лишнюю колонку ключа, и его сортировка
#    уходит на диск (external merge Disk), тогда как у серии А укладывается
#    в память. Гейтуется именно ЭТОТ КОНТРАСТ (память против диска), а НЕ
#    количество килобайт: kB зависят от work_mem и от прогона к прогону плавают.
#
#    ⚠️ Проверяется во ВСЕХ $RUNS прогонах, а не только в первом. Прежняя
#    редакция брала S_COORDSORT[1:...] — контраст объявлялся структурным
#    (то есть воспроизводимым), а проверялся на одном прогоне из трёх.
#    Утверждение было шире проверки; это ровно тот дефект, который в этом
#    файле вычищается везде, и здесь он был допущен в самом гейте.
sort_ok=1
for run in $(seq 1 "$RUNS"); do
  coord_a="${S_COORDSORT[$run:A:$MAX_OFFSET]}"
  coord_b="${S_COORDSORT[$run:B:$MAX_OFFSET]}"
  if echo "$coord_a" | grep -q 'Disk'; then
    echo "[FAIL] Прогон $run, серия А, OFFSET=$MAX_OFFSET: сортировка координатора ушла на диск ('${coord_a}'), ожидали сортировку в памяти. Контраст серий по методу сортировки в этом прогоне не воспроизводится."
    ok=0; sort_ok=0
  fi
  if ! echo "$coord_b" | grep -q 'Disk'; then
    echo "[FAIL] Прогон $run, серия Б, OFFSET=$MAX_OFFSET: сортировка координатора НЕ ушла на диск ('${coord_b}'), ожидали 'external merge Disk'. Контраст серий по методу сортировки в этом прогоне не воспроизводится."
    ok=0; sort_ok=0
  fi
done
if [ "$sort_ok" = "1" ]; then
  echo "[OK] Метод сортировки на координаторе при OFFSET=$MAX_OFFSET различается структурно во всех $RUNS прогонах:"
  for run in $(seq 1 "$RUNS"); do
    echo "     прогон $run: серия А — в памяти ('${S_COORDSORT[$run:A:$MAX_OFFSET]}'), серия Б — на диске ('${S_COORDSORT[$run:B:$MAX_OFFSET]}')."
  done
  echo "     ⚠️ Килобайты в этих строках НЕ цитировать: они зависят от work_mem (здесь 4MB)"
  echo "     и плавают между прогонами. Гейтуется только «в памяти против на диске»."
fi

# ---------------------------------------------------------------------------
# ДИАГНОСТИКА (НЕ ГЕЙТЫ). Всё, что ниже, печатается как наблюдение и НЕ влияет
# на код возврата.
#
# Почему так, и почему это изменение. Раньше временные величины — кратность
# роста серии А, монотонность медиан, межпрогонный разброс, направление
# эффекта Б против А — были ЖЁСТКИМИ гейтами и валили прогон. На практике
# скрипт дважды подряд упал у внешнего ревьюера НА ЭТОМ ЖЕ СТЕНДЕ, притом что
# структурный результат (число поднятых строк = 32 × (OFFSET + LIMIT))
# воспроизвёлся точно оба раза. По всем известным прогонам рост серии А
# гулял от 3.64× до 16.87× (у ревьюера 3.64–13.81, здесь до 16.87).
#
# Это был дефект проектирования гейтов, а не сбой стенда. Стенд однохостовый,
# время на нём шумит — об этом сказано во всех оговорках ниже, — и делать
# шумную величину условием успеха означает, что демонстрация падает у любого,
# кто её запустит. Пример обязан быть воспроизводимым, поэтому доказательной
# силой здесь наделена ТОЛЬКО структура: число поднятых строк, Task Count,
# способ доступа и метод сортировки. Времена печатаются как наблюдение.
# ---------------------------------------------------------------------------
echo
echo "----------------------------------------------------------------"
echo " Диагностика по времени (НЕ гейты: на код возврата не влияет)"
echo "----------------------------------------------------------------"
echo "Время на однохостовом стенде шумит: кратность и направление меняются от"
echo "прогона к прогону. Ниже — фактические числа как наблюдение, а не как"
echo "критерий успеха. Доказательная часть артефакта — структурные величины выше."

declare -A GROWTH_A_X GROWTH_B_X
for run in $(seq 1 "$RUNS"); do
  b="${MED[$run:A:0]}"; t="${MED[$run:A:$MAX_OFFSET]}"
  x="$(ratio_x "$b" "$t")"
  GROWTH_A_X["$run"]="$x"
  if is_ge "$x" "$MIN_GROWTH_X"; then
    echo "[наблюдение] Прогон $run, серия А: медиана выросла в ${x} раза (${b}→${t} мс) — не меньше ориентира ${MIN_GROWTH_X}×."
  else
    echo "[ПРЕДУПРЕЖДЕНИЕ] Прогон $run, серия А: медиана выросла лишь в ${x} раза (${b}→${t} мс) — меньше ориентира ${MIN_GROWTH_X}×. Прогон НЕ считается провальным: структура подтверждена выше, а время здесь шумное. Число поднятых с шардов строк — вот что доказывает стоимость OFFSET."
  fi
  GROWTH_B_X["$run"]="$(ratio_x "${MED[$run:B:0]}" "${MED[$run:B:$MAX_OFFSET]}")"
done

# Монотонность медиан — наблюдение.
for run in $(seq 1 "$RUNS"); do
  prev=""; mono=1
  for off in "${OFFSETS[@]}"; do
    cur="${MED[$run:A:$off]}"
    if [ -n "$prev" ] && ! is_ge "$cur" "$prev"; then
      echo "[ПРЕДУПРЕЖДЕНИЕ] Прогон $run, серия А: медиана при OFFSET=$off (${cur} мс) меньше, чем при предыдущем OFFSET (${prev} мс) — рост немонотонен. Это шум времени, а не опровержение: число поднятых строк растёт строго по формуле."
      mono=0
    fi
    prev="$cur"
  done
  [ "$mono" = "1" ] && echo "[наблюдение] Прогон $run, серия А: медианы росли монотонно по OFFSET."
done

# Межпрогонный разброс — наблюдение.
min_growth_ms="999999999"
for run in $(seq 1 "$RUNS"); do
  g="$(awk -v b="${MED[$run:A:0]}" -v t="${MED[$run:A:$MAX_OFFSET]}" 'BEGIN{printf "%.3f", t-b}')"
  if is_ge "$min_growth_ms" "$g"; then min_growth_ms="$g"; fi
done
for off in 0 "$MAX_OFFSET"; do
  vals=()
  for run in $(seq 1 "$RUNS"); do vals+=("${MED[$run:A:$off]}"); done
  spread="$(awk -v mn="$(min_of "${vals[@]}")" -v mx="$(max_of "${vals[@]}")" 'BEGIN{printf "%.3f", mx-mn}')"
  echo "[наблюдение] OFFSET=$off, серия А: разброс медиан между $RUNS прогонами = ${spread} мс; наименьший наблюдаемый рост (0→$MAX_OFFSET) = ${min_growth_ms} мс."
  if is_ge "$spread" "$min_growth_ms"; then
    echo "[ПРЕДУПРЕЖДЕНИЕ] Разброс между прогонами (${spread} мс) не меньше наименьшего наблюдаемого роста (${min_growth_ms} мс) — на этом хосте время плавает сильнее самого эффекта, усреднять его нельзя. На структурный вывод это не влияет."
  fi
done

# Направление эффекта Б против А — наблюдение.
#
# Раньше направление гейтовалось жёстко: считалось, что оно «держалось во всех
# наблюдавшихся прогонах». Это оказалось неверно — во втором запуске у внешнего
# ревьюера ожидаемое направление менялось трижды. Направление воспроизводится
# НЕ всегда, поэтому оно понижено до наблюдения.
for run in $(seq 1 "$RUNS"); do
  a0="${MED[$run:A:0]}";             b0="${MED[$run:B:0]}"
  aMax="${MED[$run:A:$MAX_OFFSET]}"; bMax="${MED[$run:B:$MAX_OFFSET]}"

  if is_lt "$b0" "$a0"; then
    echo "[наблюдение] Прогон $run, OFFSET=0: серия Б быстрее серии А (${b0} против ${a0} мс) — доступ по индексу внутри шарда окупается на первой странице."
  else
    echo "[ПРЕДУПРЕЖДЕНИЕ] Прогон $run, OFFSET=0: серия Б (${b0} мс) НЕ быстрее серии А (${a0} мс) — ожидаемое направление на мелком смещении не воспроизвелось в этом прогоне."
  fi

  if is_lt "$aMax" "$bMax"; then
    echo "[наблюдение] Прогон $run, OFFSET=$MAX_OFFSET: серия Б медленнее серии А (${bMax} против ${aMax} мс) — на глубокой странице выигрыш съедается сортировкой на координаторе."
  else
    echo "[ПРЕДУПРЕЖДЕНИЕ] Прогон $run, OFFSET=$MAX_OFFSET: серия Б (${bMax} мс) НЕ медленнее серии А (${aMax} мс) — ожидаемое направление на глубоком смещении не воспроизвелось в этом прогоне."
  fi
done

if [ "$ok" != "1" ]; then
