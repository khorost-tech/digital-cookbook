          [ "${S_TASKS[$key]}" = "$TASK_COUNT" ] \
            || fail "Task Count изменился между повторами одного запроса (серия $ord, OFFSET=$off): ${S_TASKS[$key]} против $TASK_COUNT."
        fi

        if [ "$run" = "1" ] && [ "$rep" = "1" ]; then
          echo
          echo "План (прогон 1, повтор 1, серия $ord, OFFSET=$off) для иллюстрации:"
          echo "$PLAN_TEXT"
        fi
      done
      med="$(median_of "${times[@]}")"
      mn="$(min_of "${times[@]}")"
      mx="$(max_of "${times[@]}")"
      MED["$key"]="$med"
      MIN["$key"]="$mn"
      MAX["$key"]="$mx"
      log "Прогон $run, серия $ord, OFFSET=$off: медиана=${med} мс (min=${mn}, max=${mx}); строк с шардов=${S_ROWS[$key]}; из ${REPS} повторов: ${times[*]}"
      unset times
    done
  done
done

