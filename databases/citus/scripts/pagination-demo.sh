#!/usr/bin/env bash
#
# pagination-demo.sh — артефакт 4: пагинация (LIMIT/OFFSET) поверх шардов.
# Один и тот же запрос, отличающийся РОВНО одной переменной — значением OFFSET:
#
#   SELECT order_id, total FROM orders_big ORDER BY total DESC LIMIT 20 OFFSET N;
#
# ЧТО ДОКАЗЫВАЕТСЯ. При сортировке НЕ по ключу шардирования координатор не
# знает, на каком шарде лежат нужные строки. Поэтому КАЖДЫЙ шард обязан
# отдать ему свои (OFFSET+LIMIT) кандидатов, а координатор — смержить всё
# это и отбросить первые OFFSET строк. Стоимость растёт как
# OFFSET × число_шардов, то есть пагинация вглубь дорожает поверх шардов
# принципиально быстрее, чем на одном узле.
#
# ── ПОЧЕМУ У АРТЕФАКТА СВОЯ ТАБЛИЦА orders_big ──────────────────────────────
#
# Таблица orders стенда (4000 строк на 32 шардах = ~125 строк на шард) для
# ЭТОГО артефакта непригодна, и это не мелочь, а порча замера. Механика выше
# работает ровно до тех пор, пока запрошенный «хвост» (OFFSET+LIMIT)
# помещается в шард. Как только OFFSET превышает число строк на шарде, шард
# просто отдаёт ВСЁ, что у него есть, и рост НАСЫЩАЕТСЯ — дальнейшее
# увеличение OFFSET не добавляет работы. На orders граница насыщения — 125
# строк, то есть уже OFFSET=1000 и тем более OFFSET=10000 лежат далеко за
# ней (а 10000 вдобавок больше всей таблицы). Замер на orders показывал бы
# не эффект, а его остаток: рост в единицы процентов вместо кратного, на
# уровне шума хоста.
#
# Поэтому артефакт создаёт СВОЙ набор данных — orders_big на 1 000 000
# строк, распределённую по customer_id в отдельной группе колокации. При 32
# шардах это ~31 тыс. строк на шард, и все используемые значения OFFSET
# лежат ВНУТРИ данных шарда, а не за ними. Таблица создаётся и удаляется
# самим скриптом (trap), в схеме стенда её быть не должно — тот же приём,
# что у carriers_sharded в reference-demo.sh. Наполнение идёт одним
# INSERT ... SELECT generate_series (миллион строк вставляется за секунды,
# а не за минуты).
#
# Фактические числа (строк на шард, границу насыщения и проверку, что
# выбранные OFFSET внутрь помещаются) скрипт измеряет и печатает САМ —
# см. preflight и самопроверку. Если данные разложились так, что
# максимальный OFFSET+LIMIT не помещается в наименьший шард, скрипт
# ОТКАЗЫВАЕТСЯ мерить и завершается ненулевым кодом: замер за границей
# насыщения бессмысленен.
#
# ── ГЛАВНАЯ ИЗМЕРЯЕМАЯ ВЕЛИЧИНА ─────────────────────────────────────────────
#
# Здесь измеряются ДВЕ вещи, и первая из них — структурная:
#
# 1) СТРУКТУРНЫЙ ПРИЗНАК (главный, детерминированный): сколько строк
#    координатор поднял с шардов. В плане это `rows=` на узле
#    `Custom Scan (Citus Adaptive)`. Величина обязана быть РОВНО равной
#    shard_count × (OFFSET + LIMIT) — то есть растёт линейно с OFFSET и
#    кратно числу шардов. Это не время: число не зависит от нагрузки на
#    машину и воспроизводится точно от запуска к запуску. Именно оно прямо
#    доказывает утверждение артефакта («каждый шард обязан отдать свои
#    кандидаты»), и именно оно гейтует самопроверку в первую очередь.
#
# 2) ВРЕМЯ (подтверждающее): `Execution Time` из EXPLAIN ANALYZE верхнего
#    узла плана. Снимается ИЗНУТРИ БД, а не секундомером вокруг
#    `docker exec` — накладные расходы docker exec составляют десятки
#    миллисекунд и на малых временах были бы того же порядка, что сигнал.
#    На нормальном объёме данных рост времени кратный (в разы), а не
#    процентный, поэтому он устойчив к шуму хоста — но он всё равно
#    остаётся вторичным по отношению к структурному признаку выше.
#
# ⚠️ ОГОВОРКА ПРО АБСОЛЮТНЫЕ ЧИСЛА. Координатор и оба воркера живут на одном
# хосте в Docker. Сетевой задержки между ними практически нет, поэтому
# абсолютная цена пересылки кандидатов с шардов координатору ЗАНИЖЕНА
# относительно настоящего кластера: на узлах в разных стойках/AZ каждый из
# 32 потоков данных шёл бы по сети, и разрыв между малым и большим OFFSET
# был бы ещё заметнее. Сравнивать Citus с обычным PostgreSQL по скорости
# здесь НЕЛЬЗЯ — ванильный PostgreSQL в этом артефакте не запускается.
#
# ⚠️ ПРОГРЕВ. Первый запрос после создания и наполнения таблицы всегда
# медленнее (холодные буферные кэши на координаторе и воркерах, свежая
# статистика). Скрипт делает отброшенный прогревочный запрос перед
# измерениями каждой серии в каждом прогоне.
#
# ── ОТДЕЛЬНАЯ ПРОВЕРКА: СОРТИРОВКА ПО КЛЮЧУ ШАРДИРОВАНИЯ ────────────────────
#
# Вопрос: меняется ли картина, если сортировать ПО ключу шардирования
# (ORDER BY customer_id) вместо произвольной колонки (ORDER BY total DESC)?
# Скрипт снимает ОБЕ серии одинаково и сравнивает не только время, но и
# ПЛАНЫ — что надёжнее. Конкретно извлекаются:
#   - Task Count (обе серии);
#   - способ доступа к данным ВНУТРИ задачи шарда (Index Scan против
#     Seq Scan + Sort);
#   - метод сортировки НА КООРДИНАТОРЕ (Sort Method) — и укладывается ли
#     она в память;
#   - объём данных, поднятых с шардов.
# Что из этого получилось — печатается в конце как самостоятельный вывод.
# Отрицательный результат тоже результат и не гейтует демонстрацию.
#
# ── ПАДАЮЩИЙ ВАРИАНТ ────────────────────────────────────────────────────────
#
# Если бы смещение ничего не стоило — если бы координатор мог «перепрыгнуть»
# первые OFFSET строк, не поднимая их с шардов, — то число строк, поднятых с
# шардов, не зависело бы от OFFSET и оставалось бы равным shard_count × LIMIT
# при любом смещении. Проверяется ИМЕННО ЭТО.
#
# ⚠️ Время в падающий вариант НЕ входит. Прежняя редакция добавляла второе
# условие — «время было бы примерно одинаковым для всех OFFSET» — и гейтовала
# его. Это оказалось несостоятельно: на однохостовом стенде время шумит
# настолько, что скрипт дважды подряд упал у внешнего ревьюера при точно
# воспроизведённой структуре, а наблюдавшийся рост гулял от 3.64× до 16.87×.
#
# ── ЧТО ГЕЙТУЕТСЯ, А ЧТО ТОЛЬКО НАБЛЮДАЕТСЯ ─────────────────────────────────
#
# ГЕЙТЫ (валят прогон ненулевым кодом), все — структурные и проверяются во
# ВСЕХ прогонах:
#   - число строк, поднятых с шардов == shard_count × (OFFSET + LIMIT), точно;
#   - Task Count == shard_count;
#   - способ доступа внутри шарда: Seq Scan у А, Index Scan у Б;
#   - сортировка внутри шарда: есть у А, нет у Б;
#   - метод сортировки на координаторе: в памяти у А, external merge Disk у Б;
#   - уборка (orders_big удалена, схема стенда вернулась к исходной).
#
# ДИАГНОСТИКА (печатается, код возврата НЕ меняет):
#   - кратность роста медианы серии А;
#   - монотонность медиан по OFFSET;
#   - разброс медиан между прогонами;
#   - направление эффекта Б против А на мелком и глубоком OFFSET.
# Все четыре величины временны́е, все на этом стенде плавают, и ни одна не
# является результатом артефакта. Отрицательный результат по ним печатается
# как [ПРЕДУПРЕЖДЕНИЕ] и демонстрацию не проваливает.
#
# Скрипт прогоняет всю схему измерения ТРИЖДЫ и сверяет структурные величины
# между прогонами — они обязаны совпасть точно. При провале СТРУКТУРНОГО гейта
# — ненулевой код возврата и явный отказ публиковать данные, а не
# правдоподобная картинка.
#
# Требует уже поднятого и наполненного стенда (bash scripts/up.sh).
#
# Запуск (из databases/citus/):
#   bash scripts/pagination-demo.sh

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$HERE"

DB_USER=shard
DB_NAME=shard

BIG_ROWS=1000000             # строк в orders_big: при 32 шардах даёт ~31 тыс.
                              # на шард, так что все OFFSET ниже помещаются
                              # ВНУТРЬ шарда и рост не насыщается
BIG_CUSTOMERS=50000          # различных customer_id (по 20 заказов на клиента) —
                              # достаточно для ровного разброса хеша по шардам
PAGE_LIMIT=20                # LIMIT страницы (как в брифе)
OFFSETS=(0 1000 10000 25000) # см. проверку в preflight: максимальный
                              # OFFSET+LIMIT обязан поместиться в НАИМЕНЬШИЙ шард
REPS=7                       # повторов на каждое значение OFFSET (>=5 по брифу).
                              # На кратном эффекте (разы, а не проценты) 7 хватает
                              # с запасом — в отличие от версии на мелких данных,
                              # где эффект тонул в шуме и не спасал даже 21 повтор
RUNS=3                       # вся схема измерения прогоняется трижды
MIN_GROWTH_X=3               # во столько РАЗ минимум обязана вырасти медиана
                              # от OFFSET=0 к максимальному OFFSET. Порог задан
                              # по существу механики (работа растёт линейно по
                              # OFFSET, а OFFSET меняется на три порядка), а не
                              # подбором под наблюдения: фактический рост много больше

log()  { echo "[pagination] $*" >&2; }
fail() { echo "[pagination] ОШИБКА: $*" >&2; exit 1; }

MAX_OFFSET="${OFFSETS[${#OFFSETS[@]}-1]}"

# --- Preflight ---------------------------------------------------------------

command -v docker >/dev/null 2>&1 || fail "docker не найден в PATH."
docker info >/dev/null 2>&1 || fail "docker недоступен (демон не отвечает)."

state="$(docker inspect --format '{{.State.Status}}' citus-coord 2>/dev/null || true)"
[ "$state" = "running" ] || fail "контейнер citus-coord не запущен. Сначала: bash scripts/up.sh"

psql_c() {
  docker exec -i citus-coord psql -X -v ON_ERROR_STOP=1 -U "$DB_USER" -d "$DB_NAME" "$@"
}

log "Preflight: проверяем стенд перед созданием собственного набора данных…"

WORKERS="$(psql_c -At -c "SELECT count(*) FROM pg_dist_node WHERE isactive AND noderole = 'primary' AND groupid <> 0;")"
[ -n "$WORKERS" ] && [ "$WORKERS" -ge 2 ] \
  || fail "в pg_dist_node меньше двух активных воркеров (нашли: ${WORKERS:-нет данных}). Сначала: bash scripts/up.sh"

orders_dist="$(psql_c -At -c "SELECT count(*) FROM pg_dist_partition WHERE logicalrelid = 'orders'::regclass;")"
[ "$orders_dist" = "1" ] || fail "таблица orders стенда не распределена — стенд не в исходном состоянии. Сначала: bash scripts/up.sh"

coloc_orders="$(psql_c -At -c "SELECT colocationid FROM pg_dist_partition WHERE logicalrelid = 'orders'::regclass;")"

log "Кластер: воркеров $WORKERS. Стенд на месте."

# --- orders_big: создаётся и удаляется этим скриптом --------------------------
#
# trap гарантирует уборку и при обычном завершении, и при прерывании (Ctrl+C,
# ошибка любой команды под set -e). DROP TABLE IF EXISTS идемпотентен.

cleanup() {
  log "Уборка: удаляем orders_big (существует только для этой демонстрации)…"
  docker exec -i citus-coord psql -X -U "$DB_USER" -d "$DB_NAME" \
    -c "DROP TABLE IF EXISTS orders_big;" >/dev/null 2>&1 || true
}
trap cleanup EXIT

log "Preflight: если orders_big осталась от прерванного прогона — удаляем перед началом…"
psql_c -c "DROP TABLE IF EXISTS orders_big;" >/dev/null

log "Создаём orders_big и распределяем по customer_id (отдельная группа колокации)…"
psql_c >/dev/null <<'SQL'
CREATE TABLE orders_big (
  customer_id BIGINT NOT NULL,
  order_id    BIGINT NOT NULL,
  total       NUMERIC(12,2) NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (customer_id, order_id)
);
SQL

psql_c -c "SELECT create_distributed_table('orders_big', 'customer_id', colocate_with => 'none');" >/dev/null

log "Наполняем orders_big: $BIG_ROWS строк одним INSERT ... SELECT generate_series…"
fill_start="$(date +%s)"
psql_c >/dev/null <<SQL
INSERT INTO orders_big (customer_id, order_id, total, created_at)
SELECT (i % ${BIG_CUSTOMERS}) + 1,
       i,
       round((random() * 10000)::numeric, 2),
       now() - make_interval(days => (i % 365)::int)
FROM generate_series(1, ${BIG_ROWS}) AS i;
SQL
fill_end="$(date +%s)"
log "Наполнение заняло $(( fill_end - fill_start )) с."

SHARD_COUNT="$(psql_c -At -c "SELECT shard_count FROM citus_tables WHERE table_name = 'orders_big'::regclass;")"
[ -n "$SHARD_COUNT" ] || fail "не удалось получить shard_count для orders_big."
[ "$SHARD_COUNT" -gt 1 ] || fail "shard_count для orders_big = $SHARD_COUNT — демонстрации нужно больше одного шарда."

BIG_N="$(psql_c -At -c "SELECT count(*) FROM orders_big;")"
[ "$BIG_N" = "$BIG_ROWS" ] || fail "в orders_big оказалось $BIG_N строк, ожидали $BIG_ROWS — наполнение прошло не полностью."

coloc_big="$(psql_c -At -c "SELECT colocationid FROM pg_dist_partition WHERE logicalrelid = 'orders_big'::regclass;")"
[ "$coloc_big" != "$coloc_orders" ] \
  || fail "orders_big оказалась в одной группе колокации с orders (colocationid=$coloc_big) — ожидали отдельную (colocate_with => 'none')."

PARTMETHOD="$(psql_c -At -c "SELECT partmethod FROM pg_dist_partition WHERE logicalrelid = 'orders_big'::regclass;")"

# --- Фактическое распределение строк по шардам -------------------------------
#
# Это ключевые числа артефакта: граница насыщения проходит по НАИМЕНЬШЕМУ
# шарду. Все выбранные OFFSET обязаны помещаться внутрь него вместе с LIMIT,
# иначе шард отдаёт всё что есть, рост насыщается и замер теряет смысл.

read -r MIN_PER_SHARD MAX_PER_SHARD AVG_PER_SHARD <<<"$(psql_c -At -F' ' -c "SELECT min(result::bigint), max(result::bigint), avg(result::bigint)::bigint FROM run_command_on_shards('orders_big', 'SELECT count(*) FROM %s');")"

for v in MIN_PER_SHARD MAX_PER_SHARD AVG_PER_SHARD; do
  [ -n "${!v}" ] || fail "не удалось измерить $v через run_command_on_shards — распределение строк по шардам неизвестно, продолжать нельзя."
done

NEEDED=$(( MAX_OFFSET + PAGE_LIMIT ))

log "orders_big: $BIG_N строк, $SHARD_COUNT шардов, partmethod='$PARTMETHOD'."
log "Строк на шард: минимум $MIN_PER_SHARD, максимум $MAX_PER_SHARD, в среднем $AVG_PER_SHARD."
log "Максимальный запрошенный хвост: OFFSET $MAX_OFFSET + LIMIT $PAGE_LIMIT = $NEEDED строк с каждого шарда."

if [ "$NEEDED" -ge "$MIN_PER_SHARD" ]; then
  fail "максимальный OFFSET+LIMIT ($NEEDED) не меньше числа строк в НАИМЕНЬШЕМ шарде ($MIN_PER_SHARD). За этой границей шард отдаёт всё, что у него есть, рост стоимости насыщается, и замер показывал бы остаток эффекта вместо эффекта. Увеличьте BIG_ROWS или уменьшите максимальный OFFSET."
fi

log "OK: запрошенный хвост ($NEEDED) помещается внутрь наименьшего шарда ($MIN_PER_SHARD) — рост не насыщается, замер осмыслен."

# --- Измерение ---------------------------------------------------------------

# measure_once <sql> — один EXPLAIN (ANALYZE, VERBOSE). Заполняет глобальные:
#   EXEC_MS        — Execution Time верхнего узла (время изнутри БД)
#   TASK_COUNT     — число задач (шардов), опрошенных запросом
#   ROWS_FROM_NODES— СКОЛЬКО СТРОК координатор поднял с шардов (главный
#                    структурный признак: обязано быть shard_count×(OFFSET+LIMIT))
#   TUPLE_DATA     — объём этих данных, как его печатает Citus
#   COORD_SORT     — метод сортировки НА КООРДИНАТОРЕ
#   SHARD_ACCESS   — способ доступа к данным ВНУТРИ задачи шарда
#   SHARD_SORTED   — сортирует ли шард данные у себя (да/нет)
measure_once() {
  local sql="$1" plan coord_part shard_part
  plan="$(psql_c -c "EXPLAIN (ANALYZE, VERBOSE) $sql")"
  PLAN_TEXT="$plan"

  EXEC_MS="$(echo "$plan" | grep -oP 'Execution Time: \K[0-9.]+' | tail -1 || true)"
  [ -n "$EXEC_MS" ] || fail "не нашли 'Execution Time' в плане: $sql — формат EXPLAIN изменился?"

  TASK_COUNT="$(echo "$plan" | grep -oP 'Task Count: \K[0-9]+' | head -1 || true)"
  [ -n "$TASK_COUNT" ] || fail "не нашли 'Task Count' в плане: $sql — формат EXPLAIN изменился?"

  # Число строк, поднятых координатором со всех шардов — с узла Citus Adaptive.
  ROWS_FROM_NODES="$(echo "$plan" | grep 'Custom Scan (Citus Adaptive)' | grep -oP 'rows=\K[0-9]+' | tail -1 || true)"
  [ -n "$ROWS_FROM_NODES" ] || fail "не нашли фактическое rows= на узле 'Custom Scan (Citus Adaptive)' в плане: $sql — формат EXPLAIN изменился?"

  TUPLE_DATA="$(echo "$plan" | grep -oP 'Tuple data received from nodes: \K.+' | head -1 | sed 's/[[:space:]]*$//' || true)"

  # План делится на часть координатора (до строки '-> Task') и часть шарда.
  coord_part="$(echo "$plan" | sed -n '1,/->  Task/p')"
  shard_part="$(echo "$plan" | sed -n '/->  Task/,$p')"

  COORD_SORT="$(echo "$coord_part" | grep -oP 'Sort Method: \K.+' | head -1 | sed 's/[[:space:]]*$//' || true)"
  [ -n "$COORD_SORT" ] || COORD_SORT="(нет сортировки на координаторе)"

  if echo "$shard_part" | grep -q 'Index Only Scan'; then
    SHARD_ACCESS="Index Only Scan"
  elif echo "$shard_part" | grep -q 'Index Scan'; then
    SHARD_ACCESS="Index Scan"
  elif echo "$shard_part" | grep -q 'Seq Scan'; then
    SHARD_ACCESS="Seq Scan"
  else
    SHARD_ACCESS="(не распознан)"
  fi

  if echo "$shard_part" | grep -q 'Sort Method:'; then
    SHARD_SORTED="да"
  else
    SHARD_SORTED="нет"
  fi
}

# pad <строка> <ширина> — печатает строку, дополненную пробелами до нужной
# ШИРИНЫ В СИМВОЛАХ. Обычный printf '%-34s' здесь непригоден: он считает
# БАЙТЫ, а кириллица в UTF-8 занимает два байта на символ, из-за чего колонки
# с русскими подписями разъезжаются. ${#s} в bash считает именно символы.
pad() {
  local s="$1" w="$2" i
  printf '%s' "$s"
  for (( i = ${#s}; i < w; i++ )); do printf ' '; done
  # Если значение и так шире колонки — всё равно отделить его от следующей
  # колонки хотя бы одним пробелом, иначе соседние ячейки слипаются.
  if [ "${#s}" -ge "$w" ]; then printf ' '; fi
}

# row3 / rowT / row5 — строки таблиц с колонками фиксированной ширины в символах.
row3() { pad "$1" 34; pad "$2" 30; printf '%s\n' "$3"; }
rowT() { pad "$1" 10; pad "$2" 30; printf '%s\n' "$3"; }
row5() { pad "$1" 10; pad "$2" 16; pad "$3" 18; pad "$4" 16; printf '%s\n' "$5"; }

median_of() { printf '%s\n' "$@" | sort -n | awk '{a[c++]=$1} END{print a[int(c/2)]}'; }
min_of()    { printf '%s\n' "$@" | sort -n | head -1; }
max_of()    { printf '%s\n' "$@" | sort -n | tail -1; }
is_ge()     { awk -v a="$1" -v b="$2" 'BEGIN{exit !(a>=b)}'; }
is_lt()     { awk -v a="$1" -v b="$2" 'BEGIN{exit !(a<b)}'; }
ratio_x()   { awk -v b="$1" -v t="$2" 'BEGIN{printf "%.2f", t/b}'; }

