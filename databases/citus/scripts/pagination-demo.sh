# --- Самопроверка ------------------------------------------------------------

echo
echo "================================================================"
echo " Самопроверка"
echo "================================================================"

ok=1

# 1. ГЛАВНЫЙ структурный гейт: строк с шардов == shard_count × (OFFSET+LIMIT),
#    точно, в обеих сериях, во всех прогонах.
struct_ok=1
for run in $(seq 1 "$RUNS"); do
  for ord in A B; do
    for off in "${OFFSETS[@]}"; do
      expected=$(( SHARD_COUNT * (off + PAGE_LIMIT) ))
      actual="${S_ROWS[$run:$ord:$off]}"
