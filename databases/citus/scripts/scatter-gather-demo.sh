#!/usr/bin/env bash
#
# scatter-gather-demo.sh — артефакт 1: запрос в один шард против
# scatter-gather. Два запроса к ОДНОЙ таблице (orders), отличающиеся
# РОВНО одной переменной — наличием фильтра по ключу шардирования
# (customer_id):
#
#   А: SELECT count(*) FROM orders WHERE customer_id = 42;   -- фильтр по ключу
#   Б: SELECT count(*) FROM orders WHERE total > 100;        -- фильтр НЕ по ключу
#
# Главная измеряемая величина — Task Count из EXPLAIN. Это структурный
# признак маршрутизации запроса: для А он равен 1 (координатор понял,
# в каком шарде лежит customer_id = 42, и обратился только к нему), для
# Б — числу шардов таблицы (координатор не может исключить ни один шард
# и опрашивает их все). Task Count не зависит от нагрузки на машину и
# воспроизводится точно от запуска к запуску — в отличие от времени.
#
# ВРЕМЯ снимается КАЖДЫЙ ИЗ REPS ПОВТОРОВ на ветку (не меньше 15 — так,
# чтобы иметь право говорить о разбросе, а не только о среднем из двух
# чисел). По собранной серии печатаются min / медиана / p95 / max — одного
# Execution Time на прогон мало даже для того, чтобы понять, насколько
# устойчиво само число. Task Count и структурная картина маршрутизации
# остаются ГЛАВНОЙ величиной; перцентили — дополнение к ней, не замена.
#
# ЧЕГО ЭТИ ПЕРЦЕНТИЛИ НЕ ДОКАЗЫВАЮТ: сравнивать ФОРМУ ХВОСТА между ветками
# А и Б по этому замеру нельзя. Ветки отличаются не только числом задач, но
# и предикатом, и суммарным объёмом сканирования — влияние веера (fan-out)
# здесь не изолировано. Ранняя редакция стенда такой вывод делала; при
# повторном прогоне он не воспроизвёлся и снят (подробности — в FIXTURES.md,
# раздел артефакта 1). Форму хвоста нужно мерить отдельным опытом, где
# меняется ТОЛЬКО число задач.
#
# ВАЖНО: все три узла кластера (координатор + 2 воркера) живут на одном
# хосте в Docker. Сетевой задержки между ними практически нет. На настоящем
# кластере, где узлы разнесены по стойкам/AZ, добавятся сетевой объём и
# удалённые взаимодействия между узлами; ВЕЛИЧИНА этого эффекта здесь не
# измерена, и направление изменения разрыва Б/А по времени утверждать
# нельзя. Арифметика «каждая строка × RTT» неверна: строки идут потоком,
# а не отдельным round-trip на строку.
#
# И отдельно, чтобы не слипалось: Task Count=32 — это 32 ЗАДАЧИ ПО ШАРДАМ,
# а не 32 узла. Воркеров ДВА, задачи раскладываются по ним по 16 на каждый.
#
# Сравнивать Citus с обычным PostgreSQL по скорости здесь НЕЛЬЗЯ: ванильный
# PostgreSQL в этом артефакте вообще не запускается, сравнивать буквально не
# с чем. На данных, влезающих в один узел, распределённая схема добавляет
# слой координации, и на ЭТОМ стенде он — чистые накладные расходы; но
# общего «распределённое всегда проигрывает на малых данных» отсюда не
# следует, и стенд такого вопроса не ставит.
#
# Скрипт прогоняет оба запроса REPS раз каждый и сверяет Task Count между
# ВСЕМИ повторами — это структурная величина, она обязана совпасть точно.
# Если Task Count у А и Б совпадает (падающий вариант — как выглядело
# бы, если бы маршрутизация по ключу не работала) или расходится между
# повторами одного и того же запроса — скрипт объявляет провал
# демонстрации и завершается ненулевым кодом, а не рисует правдоподобную
# картинку.
#
# Требует уже поднятого и наполненного стенда (bash scripts/up.sh).
#
# Запуск (из databases/citus/):
#   bash scripts/scatter-gather-demo.sh

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$HERE"

DB_USER=shard
DB_NAME=shard

log()  { echo "[scatter-gather] $*" >&2; }
fail() { echo "[scatter-gather] ОШИБКА: $*" >&2; exit 1; }

# --- Preflight ---------------------------------------------------------------

command -v docker >/dev/null 2>&1 || fail "docker не найден в PATH."
docker info >/dev/null 2>&1 || fail "docker недоступен (демон не отвечает)."

state="$(docker inspect --format '{{.State.Status}}' citus-coord 2>/dev/null || true)"
[ "$state" = "running" ] || fail "контейнер citus-coord не запущен. Сначала: bash scripts/up.sh"

psql_c() {
  docker exec -i citus-coord psql -X -v ON_ERROR_STOP=1 -U "$DB_USER" -d "$DB_NAME" "$@"
}

log "Preflight: проверяем, что orders распределена по ключу и наполнена…"

dist_check="$(psql_c -At -c "SELECT count(*) FROM pg_dist_partition WHERE logicalrelid = 'orders'::regclass;")"
[ "$dist_check" = "1" ] || fail "таблица orders не распределена (pg_dist_partition пуст для orders). Сначала: bash scripts/up.sh"

shard_count="$(psql_c -At -c "SELECT shard_count FROM citus_tables WHERE table_name = 'orders'::regclass;")"
[ -n "$shard_count" ] || fail "не удалось получить shard_count для orders из citus_tables."
[ "$shard_count" -gt 1 ] || fail "shard_count для orders = $shard_count — сценарию нужно больше одного шарда, иначе А и Б структурно неотличимы."
log "orders: $shard_count шардов."

orders_n="$(psql_c -At -c "SELECT count(*) FROM orders;")"
[ "$orders_n" -ge 4000 ] || fail "ожидали не меньше 4000 строк в orders, нашли: $orders_n. Наполнение не на месте — bash scripts/up.sh"

target_n="$(psql_c -At -c "SELECT count(*) FROM orders WHERE customer_id = 42;")"
[ "$target_n" -gt 0 ] || fail "у customer_id = 42 нет заказов (нашли: $target_n) — демонстрационный запрос А вернёт 0 и не даст показательного плана. Проверьте наполнение."
log "orders всего: $orders_n; заказов у customer_id=42: $target_n."

# --- Запросы -------------------------------------------------------------

SQL_A="SELECT count(*) FROM orders WHERE customer_id = 42;"
SQL_B="SELECT count(*) FROM orders WHERE total > 100;"

# run_explain <sql> — выполняет EXPLAIN (ANALYZE, VERBOSE), заполняет
# глобальные TASK_COUNT / EXEC_MS / PLAN_LAST. Плана НЕ печатает сама —
# при REPS повторах на ветку печатать план на каждом было бы неподъёмно
# многословно; вызывающий код печатает PLAN_LAST один раз, для первого
# повтора каждой ветки (для отчёта достаточно образца).
run_explain() {
  local sql="$1" plan
  plan="$(psql_c -c "EXPLAIN (ANALYZE, VERBOSE) $sql")"
  PLAN_LAST="$plan"

  TASK_COUNT="$(echo "$plan" | grep -oP 'Task Count: \K[0-9]+' | head -1 || true)"
  [ -n "$TASK_COUNT" ] || fail "не нашли 'Task Count' в плане для запроса: $sql — формат вывода EXPLAIN изменился?"

  # Последняя строка "Execution Time:" в выводе EXPLAIN ANALYZE — это
  # общее время верхнего узла плана (у А оно совпадает со временем задачи,
  # у Б — это время координатора поверх времени всех 32 задач).
  EXEC_MS="$(echo "$plan" | grep -oP 'Execution Time: \K[0-9.]+' | tail -1 || true)"
  [ -n "$EXEC_MS" ] || fail "не нашли 'Execution Time' в плане для запроса: $sql — формат вывода EXPLAIN изменился?"
}

REPS=20   # повторов на ветку — не меньше 15, чтобы p95 значил больше, чем max

# percentile <p> <val...> — nearest-rank перцентиль (p в процентах, 0-100)
# по уже собранному набору значений. Значения сортируются здесь же.
percentile() {
  local p="$1"; shift
  local -a sorted
  sorted=($(printf '%s\n' "$@" | sort -n))
  local n="${#sorted[@]}" idx
  idx="$(awk -v p="$p" -v n="$n" 'BEGIN{i=p/100*n; r=(i==int(i))?i:int(i)+1; if(r<1)r=1; if(r>n)r=n; print r}')"
  echo "${sorted[$((idx - 1))]}"
}
median_of() { percentile 50 "$@"; }
min_of()    { printf '%s\n' "$@" | sort -n | head -1; }
max_of()    { printf '%s\n' "$@" | sort -n | tail -1; }

declare -a TC_A TC_B TM_A TM_B

echo
echo "================================================================"
echo " Ветка А: с фильтром по ключу шардирования (customer_id = 42)"
echo "================================================================"
for rep in $(seq 1 "$REPS"); do
  run_explain "$SQL_A"
  if [ "$rep" = "1" ]; then
    echo "$PLAN_LAST"
  fi
  TC_A[$rep]="$TASK_COUNT"
  TM_A[$rep]="$EXEC_MS"
  [ "${TC_A[$rep]}" = "${TC_A[1]}" ] \
    || fail "Task Count для А разошёлся между повторами: повтор 1=${TC_A[1]}, повтор $rep=${TC_A[$rep]} — структурная величина обязана совпасть точно."
done
log "Ветка А: $REPS повторов, Task Count=${TC_A[1]} на всех, Execution Time от ${TM_A[*]} мс"

echo
echo "================================================================"
echo " Ветка Б: без фильтра по ключу шардирования (total > 100)"
echo "================================================================"
for rep in $(seq 1 "$REPS"); do
  run_explain "$SQL_B"
  if [ "$rep" = "1" ]; then
    echo "$PLAN_LAST"
  fi
  TC_B[$rep]="$TASK_COUNT"
  TM_B[$rep]="$EXEC_MS"
  [ "${TC_B[$rep]}" = "${TC_B[1]}" ] \
    || fail "Task Count для Б разошёлся между повторами: повтор 1=${TC_B[1]}, повтор $rep=${TC_B[$rep]} — структурная величина обязана совпасть точно."
done
log "Ветка Б: $REPS повторов, Task Count=${TC_B[1]} на всех, Execution Time от ${TM_B[*]} мс"

# --- Перцентили времени -------------------------------------------------------

A_MIN="$(min_of "${TM_A[@]}")";  A_MED="$(median_of "${TM_A[@]}")"
A_P95="$(percentile 95 "${TM_A[@]}")"; A_MAX="$(max_of "${TM_A[@]}")"
B_MIN="$(min_of "${TM_B[@]}")";  B_MED="$(median_of "${TM_B[@]}")"
B_P95="$(percentile 95 "${TM_B[@]}")"; B_MAX="$(max_of "${TM_B[@]}")"

echo
echo "================================================================"
echo " Сводка"
echo "================================================================"
printf '%-45s %-12s %-10s %-10s %-10s %-10s\n' "Запрос" "Task Count" "min мс" "медиана" "p95" "max мс"
printf '%-45s %-12s %-10s %-10s %-10s %-10s\n' "А: customer_id = 42 (по ключу)"    "${TC_A[1]}" "$A_MIN" "$A_MED" "$A_P95" "$A_MAX"
printf '%-45s %-12s %-10s %-10s %-10s %-10s\n' "Б: total > 100 (не по ключу)"      "${TC_B[1]}" "$B_MIN" "$B_MED" "$B_P95" "$B_MAX"
echo
echo "($REPS повторов на ветку. Task Count — СТРУКТУРНАЯ величина и остаётся"
echo "главной; перцентили времени — дополнение, не замена, см. оговорку об"
echo "однохостовом стенде ниже.)"

echo
echo "================================================================"
echo " Падающий вариант (что было бы, если бы маршрутизация не работала)"
echo "================================================================"
echo "Если бы координатор не умел исключать шарды по значению ключа"
echo "шардирования, ОБА запроса опрашивали бы все $shard_count шардов, и"
echo "Task Count у А и Б совпадал бы (оба = $shard_count). Именно это"
echo "число и есть провал демонстрации — оно проверяется ниже."

# --- Самопроверка: провал демонстрации = ненулевой код -----------------

echo
echo "================================================================"
echo " Самопроверка"
echo "================================================================"

ok=1

if [ "${TC_A[1]}" != "1" ]; then
  echo "[FAIL] Task Count для А = ${TC_A[1]}, ожидали 1 — запрос с фильтром по ключу шардирования должен уйти в один шард."
  ok=0
fi
if [ "${TC_B[1]}" != "$shard_count" ]; then
  echo "[FAIL] Task Count для Б = ${TC_B[1]}, ожидали $shard_count (все шарды orders) — запрос без фильтра по ключу должен быть scatter-gather."
  ok=0
fi
if [ "${TC_A[1]}" = "${TC_B[1]}" ]; then
  echo "[FAIL] Task Count у А и Б совпал (${TC_A[1]}) — это и есть падающий вариант: демонстрация не показывает разницы в маршрутизации."
  ok=0
fi

if [ "$ok" != "1" ]; then
  fail "демонстрация провалена (см. [FAIL] выше). Числа не воспроизвели ожидаемую картину — не публиковать эти данные как есть, разбираться в причине (порт/схема/наполнение/версия Citus)."
fi

echo "[OK] Task Count воспроизводится точно на всех $REPS повторах каждой ветки: А=1, Б=$shard_count. Маршрутизация по ключу шардирования подтверждена структурно."
echo
echo "Время — только порядок величины: А min/медиана/p95/max = $A_MIN/$A_MED/$A_P95/$A_MAX мс,"
echo "Б min/медиана/p95/max = $B_MIN/$B_MED/$B_P95/$B_MAX мс."
echo "Это однохостовый стенд: все узлы на localhost, сети между ними фактически нет."
echo "На настоящем кластере добавятся сетевой объём и удалённые взаимодействия."
echo "ВЕЛИЧИНА этого эффекта здесь НЕ ИЗМЕРЕНА, и НАПРАВЛЕНИЕ изменения разрыва Б/А"
echo "не утверждается. Прикидка «число строк × RTT» неверна: строки идут потоком,"
echo "а не по одному round-trip на строку."
echo
echo "ПРО ВЫВОД ПЛАНА Б: строка «Tasks Shown: One of ${shard_count}» — это штатное"
echo "поведение Citus, а не усечённый или сбойный вывод. EXPLAIN печатает подробности"
echo "ОДНОЙ задачи из ${shard_count} в качестве образца, потому что остальные устроены так же."
echo "Сколько задач было на самом деле, видно в строке «Task Count» выше — именно она"
echo "здесь и является измеряемой величиной."

log "Готово."
