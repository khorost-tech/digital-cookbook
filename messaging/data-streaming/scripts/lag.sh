#!/usr/bin/env bash
# Лаг по звеньям: сколько сообщений каждая группа ещё не обработала.
#
# Растущий LAG — сигнал нездоровья пайплайна, но НЕ единственная его причина:
# он растёт и тогда, когда апстрим льёт больше, чем звено успевает
# обработать, И тогда, когда звено попросту не запущено (см. артефакт №5 в
# отчёте Задачи 6 — там LAG 0→200 получен вторым способом: Kafka Streams был
# остановлен, а не "не успевал"). Число одно и то же в обоих случаях — вывод
# lag.sh их не различает, различать нужно по контексту прогона (жив ли
# процесс звена).
#
# ⚠️ LAG=1 у ds-sink на customer.totals — НЕ обязательно отставание. Kafka
# Streams пишет в customer.totals с PROCESSING_GUARANTEE=EXACTLY_ONCE_V2
# (см. streams/src/main/java/StreamsApp.java): транзакционный продюсер кладёт
# в топик служебные control-записи (маркеры commit/abort) вперемешку с
# обычными. Control-записи занимают offset, но не являются данными — обычный
# консьюмер (в т.ч. ds-sink) их не читает как сообщения. Если последняя
# запись в топике — control-маркер, LOG-END-OFFSET может на 1 опережать
# позицию, до которой ds-sink способен продвинуться, и kafka-consumer-
# groups.sh покажет LAG=1, который никогда не станет 0 сам по себе. Это
# артефакт EXACTLY_ONCE_V2, а не "не успел закоммитить до таймера" — не
# путайте с реальным отставанием (когда LAG растёт со временем под нагрузкой,
# см. артефакт №5). Проверяйте по факту: сколько строк реально легло в
# витрину (scripts/lag.sh не показывает это — см. sql/02-clickhouse.sql,
# customer_totals/raw_totals).
#
# Ошибки НЕ глушатся, и для двух разных классов "тихой смерти" — разные
# проверки:
#
# 1) docker exec на отсутствующий/незапущенный контейнер падает с ненулевым
#    кодом. Раньше это шло в пайп `2>/dev/null | awk ...`: при пайплайне
#    ошибка docker exec роняла бы весь скрипт с голым "PIPE_FAILED", без
#    единого слова о причине. Ловушка: просто перехватить вывод в переменную
#    (`out="$(docker exec ... 2>&1)"`) как ПРОСТУЮ команду — недостаточно.
#    Под `set -e` провал такого присваивания убивает скрипт СРАЗУ же, ДО
#    того, как следующая строка успела бы напечатать `$out` — видимое
#    поведение при этом байт-в-байт совпадает со старым `2>/dev/null`: RC=1,
#    ни слова диагностики, просто в другом месте. Поэтому присваивание
#    обёрнуто в `if ! out=...; then ...; fi`: часть условия `if` не
#    прерывает скрипт под `set -e`, и внутри `then` есть возможность
#    напечатать `$out` ПЕРЕД выходом.
#
# 2) Если группа ни разу не коммитила оффсет (звено ни разу не
#    запускалось), kafka-consumer-groups.sh на этом брокере (Kafka 4.3.1)
#    завершается кодом 0 и печатает "Error: ... GroupIdNotFoundException" в
#    stdout — ни `set -e`, ни pipefail это не ловят (код 0!), а awk-фильтр
#    эту строку не матчит и молча ничего не печатает: пустая секция
#    выглядит неотличимо от "лаг 0". Поэтому вывод, уже перехваченный в
#    переменную по п.1, отдельно проверяется на признак "группы нет" ДО
#    того, как передаётся в awk.
set -euo pipefail
for g in ds-streams ds-sink; do
  echo "=== группа $g ==="
  if ! out="$(docker exec ds-kafka /opt/kafka/bin/kafka-consumer-groups.sh \
    --bootstrap-server localhost:9092 --describe --group "$g" 2>&1)"; then
    echo "ОШИБКА: не удалось опросить брокер (docker exec упал): $out" >&2
    exit 1
  fi
  if echo "$out" | grep -qi "GroupIdNotFoundException\|^Error:"; then
    echo "ОШИБКА: группа $g не существует (ни разу не коммитила оффсет) — не путать с лагом 0"
    echo "$out" | grep -i "Error:" || true
    exit 1
  fi
  # Заголовок (строка "GROUP ...") + строки данных по orders.events,
  # customer.totals И внутреннему repartition-топику Kafka Streams (лаг на
  # нём — такой же настоящий сигнал здоровья пайплайна, как и на входном
  # топике; прятать его нельзя, даже если статья про него отдельно не
  # рассказывает).
  echo "$out" | awk '/^GROUP|orders\.events|customer\.totals|-repartition/'
done
