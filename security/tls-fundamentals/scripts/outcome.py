"""Контракт строки, которую печатает любой клиент стенда.

Клиентов четыре, и сравнивать их между собой можно только если они
отвечают одинаково. Здесь единственное место, где этот контракт задан;
разборы всех осей опираются на него, а не переписывают проверки заново.

ТРИ ИСХОДА, И ТРЕТИЙ ОТДЕЛЬНО ОТ ВТОРОГО:

  connected — соединение установлено и живо: обмен состоялся;
  rejected  — соединение не состоялось ИЗ-ЗА ПРОВЕРКИ СЕРТИФИКАТА, чьей
              угодно, и причина названа;
  error     — проба не смогла запуститься.

Определение отказа было уже уточнено. Сперва оно звучало как «клиент
отказался» и описывало лишь одно направление; на взаимном рукопожатии
отказывает сервер, и его отказ приходит клиенту отдельным сообщением уже
ПОСЛЕ того, как рукопожатие завершилось. Кто именно и на каком этапе —
отдельное необязательное поле handshake_ok.

Последний существует потому, что наша поломка не должна попадать в
таблицу как поведение клиента. Недоступный сервер, не собранный
бинарник, не найденный сертификат — это про нас, а не про то, доверяет
ли клиент сертификату.
"""

import json

OUTCOMES = ("connected", "rejected", "error")
FIELDS = ("kind", "case", "client", "outcome", "detail")


def parse_line(line):
    """Разбирает строку клиента, отвергая всё, что не соответствует контракту.

    Отказ и сбой обязаны объяснять себя: без объяснения строку нечем
    отличить от чужого отказа по другой причине, а вся матрица держится
    на том, ПОЧЕМУ клиент отказался.
    """
    row = json.loads(line)
    for field in FIELDS:
        if field not in row:
            raise ValueError("нет обязательного поля %s" % field)
    if row["outcome"] not in OUTCOMES:
        raise ValueError("недопустимый исход %r" % row["outcome"])
    if row["outcome"] != "connected" and not str(row["detail"]).strip():
        raise ValueError("исход %r обязан нести объяснение в detail"
                         % row["outcome"])
    return row


def read_fixture(path):
    """Читает фикстуру целиком, требуя маркер завершения.

    Оборванная фикстура — это прогон, который упал посередине. Разбирать
    её нельзя: получится частичная картина, выглядящая как полная.
    """
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    if "\nCOMPLETE\n" not in text and not text.rstrip().endswith("COMPLETE"):
        raise ValueError("%s: нет маркера завершения — прогон оборван" % path)
    rows = []
    for line in text.split("\n"):
        line = line.strip()
        if line.startswith("{"):
            rows.append(parse_line(line))
    return rows
