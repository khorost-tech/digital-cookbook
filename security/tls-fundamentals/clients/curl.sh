#!/usr/bin/env bash
# Клиент стенда на curl — В КОНТЕЙНЕРЕ, с зафиксированной версией.
#
# ПОЧЕМУ НЕ ХОСТОВЫЙ CURL. Контрольная проверка поймала: под Windows curl
# собран с системным движком TLS, а не с OpenSSL, и он требует проверки
# отзыва, которую для частного удостоверяющего центра выполнить негде.
# Целая цепочка получала отказ «состояние отзыва неизвестно» — то есть
# вся колонка curl в матрице была бы ложными отказами, и выглядели бы они
# правдоподобно.
#
# Отсюда правило: клиент, чьё поведение зависит от того, чем его собрали,
# должен браться из зафиксированного образа, а не с машины автора.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
parse_args "$@"
require_tools curl docker

IMAGE="curlimages/curl:8.18.0"

# Клиентский сертификат — вторая ось стенда.
cert_args=()
if [ -n "$CLIENT_CERT" ]; then
    cert_args=(--cert "$CLIENT_CERT" --key "$CLIENT_KEY")
fi

# Внутри контейнера имя стенда направляется на хост: сервер слушает там.
# --connect-to сохраняет имя в SNI и в проверке, подменяя только адрес.
raw="$(docker run --rm \
        -v "$STAND_ROOT:/stand:ro" -w /stand \
        "$IMAGE" \
        --silent --show-error \
        --cacert "$CAFILE" "${cert_args[@]}" \
        --connect-to "$SERVERNAME:$PORT:host.docker.internal:$PORT" \
        --max-time 15 \
        "https://$SERVERNAME:$PORT/" 2>&1)"
rc=$?

# Отказом клиента считаются ТОЛЬКО коды, относящиеся к проверке
# сертификата и рукопожатию. Всё прочее — сбой пробы.
#
# Умолчание здесь принципиально. Если незнакомый код считать отказом,
# наша собственная поломка попадёт в таблицу как недоверие клиента к
# сертификату — и будет выглядеть совершенно правдоподобно.
case "$rc" in
    0)
        outcome="connected"; detail="" ;;
    35|51|58|59|60|64|66|77|82|83|91)
        outcome="rejected"; detail="curl($rc): $raw" ;;
    52|56)
        # Соединение оборвалось. Это не наша поломка: если в сообщении
        # есть сигнал тревоги, связь разорвал собеседник по итогам
        # проверки сертификата. Без такого признака — всё-таки сбой
        # пробы, и выдавать его за вердикт нельзя.
        if printf '%s' "$raw" | grep -qi "alert"; then
            outcome="rejected"; detail="curl($rc): $raw"
        else
            outcome="error"; detail="curl($rc): $raw"
        fi ;;
    *)
        outcome="error"; detail="curl($rc): $raw" ;;
esac

emit curl "$outcome" "$detail"
