#!/usr/bin/env bash
# Клиент стенда на OpenSSL.
#
# Печатает ОДНУ строку JSON по общему контракту: kind, case, client,
# outcome, detail. Три исхода — connected, rejected, error, — и третий
# отделён от второго намеренно: сбой пробы не должен попадать в таблицу
# как недоверие клиента.
#
# ПОЧЕМУ В КОНТЕЙНЕРЕ. На машине автора нашлось ДВА разных OpenSSL —
# 3.5.5 и 3.0.13, — и какой сработает, решал порядок каталогов в PATH.
# Под одним проба видела сведения о сессии, под другим нет, и один и
# тот же случай получал разные исходы. Фикстура молча зависела бы от
# того, из какой оболочки её сняли. Образ собирается из image/.
#
# ДОВЕРЕННЫЙ ЦЕНТР ПЕРЕДАЁТСЯ ЯВНО. Системное хранилище не используется:
# иначе результат зависел бы от машины, на которой снят прогон, и
# фикстура перестала бы воспроизводиться у читателя.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
parse_args "$@"
require_tools openssl docker grep cat

IMAGE="tls-stand-openssl:1"

# Список отозванных подкладывается в то же хранилище доверия, что и
# корень: отдельной опции для него у s_client нет, а PEM-файл может
# содержать и сертификаты, и списки — openssl читает оттуда оба.
#
# Файл кладётся рядом со стендом обычным относительным путём: mktemp даёт
# путь вида /tmp/..., а нативный OpenSSL под Windows его не открывает —
# тот же случай, что и с подстановкой процесса при выпуске сертификатов.
# Клиентский сертификат — вторая ось стенда. Здесь он просто
# передаётся, если задан.
cert_args=()
if [ -n "$CLIENT_CERT" ]; then
    # -cert берёт ТОЛЬКО первый сертификат из файла. Без -cert_chain
    # сервер получает лист без пути к корню, и любой слом выглядит
    # как «неизвестный центр» — включая контрольный случай.
    cert_args=(-cert "$CLIENT_CERT" -key "$CLIENT_KEY"
               -cert_chain "$CLIENT_CERT")
fi

# Потолок версии. Нужен для пары о понижении: сервер остаётся способным
# на 1.3, а клиент предлагает только 1.2 — и метку о понижении сервер
# кладёт именно в этом случае.
ver_args=()
case "$MAX_VERSION" in
    1.2) ver_args=(-tls1_2) ;;
    1.3) ver_args=(-tls1_3) ;;
    "")  ;;
    *) echo "неизвестный потолок версии: $MAX_VERSION" >&2; exit 2 ;;
esac

crl_args=()
trust="$CAFILE"
if [ -n "$CRLFILE" ]; then
    trust="pki/.trust-with-crl.pem"
    cat "$CAFILE" "$CRLFILE" > "$trust"
    crl_args=(-crl_check)
fi

# Посылаем запрос и ЧИТАЕМ ответ, а не выходим сразу.
#
# С командой выхода проба закрывала связь, не пытаясь читать, — и
# отказ, который приходит уже ПОСЛЕ рукопожатия, до неё не доходил.
# На взаимном рукопожатии это давало «соединился» там, где сервер
# отверг клиентский сертификат.
# Запрос кладётся в файл и подаётся перенаправлением, а не конвейером.
#
# Через конвейер контейнер получал ввод не сразу: openssl доходил до
# ожидания, печатал «read R BLOCK», ответа не дожидался, и контрольный
# случай выглядел отказом.
REQ="fixtures/.request.txt"
mkdir -p fixtures
printf 'GET / HTTP/1.1\r\nHost: %s\r\n\r\n' "$SERVERNAME" > "$REQ"

raw="$(docker run --rm -i \
        -v "$STAND_ROOT:/stand:ro" -w /stand \
        "$IMAGE" s_client \
        -ign_eof \
        "${crl_args[@]}" "${cert_args[@]}" "${ver_args[@]}" \
        -connect "host.docker.internal:$PORT" \
        -servername "$SERVERNAME" \
        -verify_hostname "$SERVERNAME" \
        -CAfile "$trust" \
        -verify_return_error \
        < "$REQ" 2>&1)"
rc=$?

# Разбор идёт по двум надёжным признакам: сигнал тревоги и код
# возврата.
#
# Признаком успеха до этого по очереди служили строка о проверке
# СЕРВЕРНОГО сертификата (она про другое), блок сведений о сессии
# (печатается не всегда) и полученное тело ответа (зависит от того,
# как контейнеру подали ввод). Каждый раз это было что-то, видимое НЕ
# ВСЕГДА, и контрольный случай выглядел отказом.
#
# Сначала отличаем сбой пробы от разговора с сервером. «Неизвестная
# опция» — тоже сбой пробы: без этого openssl, упавший на незнакомом
# ключе, выдавал код 1, и скрипт объявлял это отказом клиента.
#
FAIL='connect:errno|no such file|unable to load|unknown option|use -help'
ALERT='ssl/tls alert|alert number|tlsv1[.0-9]* alert|sslv3 alert'

if printf '%s' "$raw" | grep -qiE "$FAIL"; then
    outcome="error"
    detail="$(printf '%s' "$raw" | grep -iE "$FAIL" | head -1)"
elif printf '%s' "$raw" | grep -qiE "$ALERT"; then
    # Сигнал тревоги называет причину и приходит как при отказе в
    # рукопожатии, так и после него.
    outcome="rejected"
    detail="$(printf '%s' "$raw" | grep -iE "$ALERT" | head -1)"
elif [ "$rc" -eq 0 ]; then
    outcome="connected"
    detail=""
else
    outcome="rejected"
    detail="$(printf '%s' "$raw" | grep -iE 'verify error|Verify return code' | head -1)"
    [ -z "$detail" ] && detail="код возврата $rc без явной диагностики"
fi

# Отказ, пришедший ПОСЛЕ рукопожатия, — другое событие, чем «не
# договорились», и смешивать их нельзя.
#
# Строка о согласованном шифре печатается ровно тогда, когда
# рукопожатие состоялось. Блок сведений о сессии для этого не
# годится: он печатается не всегда, и на нём проба уже ошиблась.
handshake_ok=false
printf '%s' "$raw" | grep -qE 'New, TLS' && handshake_ok=true

emit openssl "$outcome" "$detail" "$handshake_ok"
