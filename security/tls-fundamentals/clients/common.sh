# Общее для всех оболочечных клиентов стенда: разбор флагов, объявление
# нужных инструментов и экранирование. Подключается через source.
#
# ВСЕ ПАРАМЕТРЫ — ЯВНЫЕ ФЛАГИ, БЕЗ ПЕРЕМЕННЫХ ОКРУЖЕНИЯ.
#
# Раньше вид пробы и список отозванных передавались через окружение. При
# запуске из-под другого процесса до оболочки они не доходили ВООБЩЕ — а
# прогон при этом отрабатывал и выглядел осмысленным: фикстура получала
# вид пробы по умолчанию, список отозванных просто не применялся, и
# таблица «отозванный против неотозванного» показывала одно и то же в
# обеих строках. Ручка, которой не видно, однажды окажется
# неподключённой, и заметить это будет нечем.
#
# Флаги видны в командной строке и у всех четырёх клиентов одинаковые.

set -uo pipefail

export MSYS_NO_PATHCONV=1

KIND="chain"
CASE=""
ADDR="127.0.0.1:18443"
SERVERNAME="stand.local"
CAFILE="pki/root.pem"
CRLFILE=""
CLIENT_CERT=""
CLIENT_KEY=""
MAX_VERSION=""
STAND_ROOT="$(pwd)"

parse_args() {
    local arg
    for arg in "$@"; do
        case "$arg" in
            --kind=*)        KIND="${arg#*=}" ;;
            --case=*)        CASE="${arg#*=}" ;;
            --addr=*)        ADDR="${arg#*=}" ;;
            --servername=*)  SERVERNAME="${arg#*=}" ;;
            --ca=*)          CAFILE="${arg#*=}" ;;
            --crl=*)         CRLFILE="${arg#*=}" ;;
            --client-cert=*) CLIENT_CERT="${arg#*=}" ;;
            --client-key=*)  CLIENT_KEY="${arg#*=}" ;;
            --max-version=*) MAX_VERSION="${arg#*=}" ;;
            --stand-root=*)  STAND_ROOT="${arg#*=}" ;;
            # Неизвестный флаг — это опечатка в вызове, а значит проба
            # померила бы не то, что просили. Молча игнорировать нельзя.
            *) echo "неизвестный флаг: $arg" >&2; exit 2 ;;
        esac
    done
    [ -n "$CASE" ] || { echo "не задан --case" >&2; exit 2; }
    PORT="${ADDR##*:}"
}

# Отсутствие инструмента — это СБОЙ ПРОБЫ, а не поведение клиента, и он
# обязан быть виден. Раньше пропавший grep не мешал напечатать «отказал»:
# наша поломка уходила в таблицу как недоверие клиента к сертификату.
require_tools() {
    local client="$1"; shift
    local tool
    for tool in "$@"; do
        command -v "$tool" >/dev/null 2>&1 && continue
        printf '{"kind":"%s","case":"%s","client":"%s","outcome":"error","detail":"нет инструмента %s"}\n' \
            "$KIND" "$CASE" "$client" "$tool"
        exit 0
    done
}

# Экранирование — ТОЛЬКО встроенными средствами оболочки.
#
# Здесь по очереди стояли python, а потом tr и sed, и оба раза ломалось
# одинаково и ТИХО: при запуске из-под другого процесса нужной команды в
# PATH не оказывалось, подстановка возвращала пустую строку, а код
# возврата оставался нулевым — ни set -e, ни pipefail такого не видят.
# Отказы приходили без объяснения, и матрица заполнилась бы строками
# «отказал, причина неизвестна», неотличимыми от отказа по совсем другой
# причине.
#
# Поймал это не глаз, а контракт строки: он требует, чтобы отказ объяснял
# себя.
#
# Обратный слэш и кавычка вынесены в переменные, а шаблоны закавычены:
# кавычка прямо внутри подстановки открывает цитирование и обрывает
# разбор всего скрипта, а незакавыченный слэш понимается как
# экранирование и не удваивается.
json_escape() {
    local s=${1-}
    local bs='\'
    local dq='"'
    s="${s//$'\r'/}"
    s="${s//$'\n'/ }"
    s="${s//$'\t'/ }"
    s="${s//"$bs"/"$bs$bs"}"
    s="${s//"$dq"/"$bs$dq"}"
    printf '%s' "$s"
}

# emit <клиент> <исход> [объяснение] [состоялось ли рукопожатие]
#
# Четвёртый аргумент отделяет «не договорились» от «договорились, а
# потом отказали». Он необязателен: у клиента, по которому этого не
# видно, поля просто не будет. Выдумывать значение нельзя — отсутствие
# наблюдения и наблюдение «нет» это разные вещи.
emit() {
    local tail=""
    [ -n "${4-}" ] && tail=",\"handshake_ok\":$4"
    printf '{"kind":"%s","case":"%s","client":"%s","outcome":"%s","detail":"%s"%s}\n' \
        "$KIND" "$CASE" "$1" "$2" "$(json_escape "${3-}")" "$tail"
}
