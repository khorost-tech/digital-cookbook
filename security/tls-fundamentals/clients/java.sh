#!/usr/bin/env bash
# Клиент стенда на Java — В КОНТЕЙНЕРЕ, с зафиксированной версией среды.
#
# ПОЧЕМУ КОНТЕЙНЕР. То же правило, что и для curl: клиент, чьё поведение
# зависит от того, чем и с какими умолчаниями его собрали, надо брать из
# зафиксированного образа, а не с машины автора. У Java это особенно
# заметно — набор доверенных центров и политика проверки живут в самой
# среде и различаются между сборками.
#
# ПОЧЕМУ БЕЗ СБОРЩИКА. У пробы нет ни одной внешней зависимости — только
# стандартная библиотека. Запуск исходника напрямую убирает из стенда
# скачивание зависимостей: иначе воспроизводимость прогона зависела бы от
# доступности внешнего репозитория.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
parse_args "$@"
require_tools java docker

IMAGE="eclipse-temurin:25-jdk"
# Путь относительный: скрипт и так исполняется из корня стенда, а
# корень, прошедший через оболочку Windows, превращается в мусор.
ERRLOG="fixtures/.java-probe.err"
mkdir -p "$(dirname "$ERRLOG")"

extra=()
if [ -n "$CLIENT_CERT" ]; then
    extra+=("--client-cert=$CLIENT_CERT" "--client-key=$CLIENT_KEY")
fi

# Внутри контейнера сервер стенда живёт на хосте. Адрес подменяется, имя
# для SNI и для проверки передаётся отдельно и остаётся прежним.
docker run --rm \
    -v "$STAND_ROOT:/stand:ro" -w /stand \
    "$IMAGE" \
    java clients/java/Probe.java \
        "--kind=$KIND" "--case=$CASE" \
        "--addr=host.docker.internal:$PORT" \
        "--servername=$SERVERNAME" \
        "--ca=$CAFILE" \
        "${extra[@]}" \
    2>"$ERRLOG"

rc=$?
if [ $rc -ne 0 ]; then
    # Проба не запустилась — это про нас, а не про недоверие клиента.
    emit java error "java($rc): $(<"$ERRLOG")"
fi
