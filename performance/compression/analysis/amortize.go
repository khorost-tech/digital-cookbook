// TotalCostMs — полная процессорная стоимость: сжать один раз и разжать
// reads раз. Величина, которая делит режимы «холодное хранение» и
// «одноразовый промежуточный результат»: при больших reads вклад сжатия
// становится второстепенным, и плотный медленный кодек оправдан.
//
// reads < 0 не встречается в предметной области (нельзя прочитать
// отрицательное число раз) — трактуется как 0, а не как ошибка: вызывающая
// сторона здесь не обязана валидировать вход, достаточно не выдать
// абсурдный (отрицательный) результат.
func TotalCostMs(compressMs, decompressMs float64, reads int) float64 {
	if reads < 0 {
		reads = 0
	}
	return compressMs + decompressMs*float64(reads)
}
