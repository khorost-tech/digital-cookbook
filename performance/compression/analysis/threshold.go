// Package analysis — чистые расчёты выводов статьи. Ни ввода-вывода, ни
// замеров: сюда приходят измеренные величины, отсюда уходят числа, которые
// можно проверить арифметически.
package analysis

import "fmt"

// ThresholdBandwidthMBs — пороговая полоса, ниже которой сжатие на канале
// окупается.
//
// Вывод. Без сжатия время передачи S байт при полосе B равно S/B. Со сжатием
// оно складывается из времени сжатия S/V и передачи сжатого S/(r·B). Сжатие
// выгодно, когда S/V + S/(r·B) < S/B; сокращая S и приводя, получаем
// V > B·r/(r−1), откуда B* = V·(r−1)/r.
//
// Модель идеализирована: сжатие целиком перед отправкой, отсутствие
// постоянных издержек на запрос, полоса как единственное ограничение.
// Поэтому результат — оценка порядка величины, а не предсказание точки
// перелома на живом HTTP-пути.
func ThresholdBandwidthMBs(compressMBs, ratio float64) (float64, error) {
	if compressMBs <= 0 {
		return 0, fmt.Errorf("скорость сжатия %v — должна быть положительной", compressMBs)
	}
	if ratio <= 1 {
		return 0, fmt.Errorf("ratio %v: сжатие не уменьшает объём, порога не существует", ratio)
	}
	return compressMBs * (ratio - 1) / ratio, nil
}
