package main

import (
	"fmt"
	"math"
	"sort"
	"time"
)

// minDurationMs — порог достоверности замера: длительность, ниже которой
// разница между кодеками тонет в шуме таймера и планировщика ОС, и число
// становится неотличимо от случайного. На этом стенде одиночный проход на
// реальном корпусе (profiles/products.ndjson, ~36 МБ) даёт разжатие lz4 и
// zstd на большинстве уровней в диапазоне 20–45 мс — ниже порога, хотя сами
// операции корректны и воспроизводимы, а не случайны. Отбросить такие замеры
// значит потерять половину матрицы сравнения не из-за свойств кодеков, а
// из-за методики измерения. Поэтому вместо снижения порога (это вернуло бы
// именно ту недостоверность, от которой он защищает) харнесс подбирает
// число проходов подряд внутри одного замера — см. calibratePasses и
// maxPasses: суммарная длительность серии проходов делится на их число,
// и полученная оценка одного прохода имеет ту же точность, что дала бы
// одна операция такой суммарной длины. Порог по-прежнему применяется к
// суммарной длительности серии, а не к результату деления.
const minDurationMs = 50.0

// maxPasses — верхний предел числа проходов, подбираемых внутри одного
// замера. Без предела вырожденные входы (пустые данные, единицы байт)
// увели бы подбор в неразумные значения: если один проход стоит долей
// микросекунды, формальный расчёт «сколько проходов нужно, чтобы
// накопить minDurationMs» может потребовать сотен тысяч и более повторов
// и превратить один замер в многосекундный цикл ради данных, которые всё
// равно не репрезентативны — сжатие нескольких байт не говорит ничего о
// поведении кодека на реальном корпусе.
//
// Откуда именно 100_000. calibratePasses домножает с запасом safetyMargin:
// целевая сумма — minDurationMs × 1.5 = 75 мс. Проход длительностью около
// 750 нс (75 мс / 100_000) — это и есть граница: проход быстрее неё требует
// по формуле больше проходов, чем разрешает предел, и число проходов
// перестаёт отражать «сколько нужно», становясь просто константой-потолком.
// На реальном корпусе (profiles/*.ndjson, десятки мегабайт) ни один из 12
// кодеков не подходит к этой границе даже близко — максимум на живых
// данных 3 прохода (см. task-2-report.md); упереться в предел может только
// вход, на котором один проход занимает доли микросекунды, то есть заведомо
// не репрезентативный объём. Величина предела заодно ограничивает время
// калибровки на таких вырожденных входах: 100_000 проходов вырожденно
// дешёвой операции — это доли секунды, а не минуты.
//
// С этого фикса упор в предел сам по себе делает замер непубликуемым (см.
// passesAtLimit и проверку в Measure) — независимо от того, что показала
// суммарная длительность серии после упора. Раньше решение зависело от
// факта: если суммарная длительность на пределе всё же пересекала порог,
// замер публиковался, хотя число проходов не отражало намерения (см. отчёт
// о ревью Задачи 2). Теперь исчерпание предела и недостижение порога —
// две самостоятельные причины отказа.
const maxPasses = 100_000

// calibrationSamples — число прогревочных сэмплов, по которым калибруется
// число проходов (отдельно для сжатия и для разжатия). Один прогревочный
// сэмпл прогревает кэши и аллокации, но калибровка по нему одному
// невоспроизводима: ревью Задачи 2 (см. task-2-report.md, раздел «Медианная
// калибровка и покрытие ветки порога») показало на реальном корпусе, что
// одного сэмпла, случайно попавшего в выброс планировщика ОС (например,
// ~51 мс на разжатии zstd уровня 3 при истинной стоимости ~41 мс), хватает,
// чтобы calibratePasses выбрал passes=1 — и тогда серия из одного прохода
// снова даёт ~41 мс, порог не достигается, и кодек пропадает из матрицы
// между запусками не из-за своих свойств, а из-за момента, когда сработал
// таймер. Это ровно тот же класс проблемы, от которого в основной серии
// защищает медиана, а не среднее и не единичный замер (см. Measure) —
// решение здесь симметрично: калибровать по медиане нескольких прогревочных
// сэмплов, а не по одному. Три — минимум, для которого медиана вообще
// отличается от среднего двух (у двух значений «медиана» — это просто их
// среднее, которое размывает выброс, а не отбрасывает его). Цена — два
// лишних прохода compress/decompress поверх уже имевшегося прогрева;
// подробности живой проверки дисперсии до/после — в task-2-report.md.
const calibrationSamples = 3

// maxRecalibrations — сколько раз харнесс имеет право пересчитать число
// проходов по фактически измеренной медиане серии (а не по прогревочному
// сэмплу) и перепрогнать серию заново, если та не набрала minDurationMs.
//
// Проблема, которую это решает: calibratePasses в первый раз калибруется по
// warmCompressMs/warmDecompressMs — медиане calibrationSamples=3 прогревочных
// сэмплов, снятых ДО основной серии. Когда истинная стоимость операции
// близка к порогу (пример из брифа: разжатие zstd уровня 3 на products.ndjson
// стоит ~41 мс при пороге 50 мс), любое расхождение между этой прогревочной
// оценкой и тем, что покажет реальная серия, может увести число проходов в
// сторону, при которой суммарная длительность серии не дотягивает до порога
// — не потому что кодек медленный, а потому что предсказание разошлось с
// фактом. Раньше это расхождение было окончательным приговором: серия
// заканчивалась, порог не был достигнут — и Measure сразу отказывал.
//
// Фикс: если серия завершилась, но порог не достигнут, число проходов
// пересчитывается той же calibratePasses, но на входе теперь — медиана
// длительности одного прохода, измеренная в только что прошедшей реальной
// серии (median(ms) в calibrateAndMeasure), а не прогревочный сэмпл. Серия
// перепрогоняется с новым числом проходов.
//
// Почему предел — 2 (то есть до двух повторных попыток, итого до трёх
// измеренных серий на операцию): процесс сходится за один пересчёт почти
// всегда, потому что вход пересчёта качественно надёжнее входа первой
// калибровки. Первая калибровка опирается на медиану всего calibrationSamples
// (=3) ОТДЕЛЬНЫХ прогревочных вызовов кодека — коротких одиночных операций
// вне основной серии. Пересчёт же опирается на медиану по minReps повторам
// РЕАЛЬНОЙ серии из passes проходов подряд — той же операции, тем же
// кодеком, на тех же данных, в тех же условиях, что и публикуемый замер, а
// не в отдельном прогревочном окне заранее. Это разные по надёжности
// оценки: вторая получена практически в момент основного замера и не может
// разойтись с ним так, как прогревочная оценка может разойтись с фактом.
//
// Раньше (до финального ревью Задачи 2) здесь стоял предел 1, а
// обоснование утверждало, что единственный сценарий, где один пересчёт не
// спасает, — устойчивый СДВИГ стоимости операции МЕЖДУ сериями (посторонняя
// нагрузка началась именно между попытками), и что от него не защитил бы
// никакой предел. Это рассуждение неявно моделировало стоимость как
// случайное блуждание и упускало второй, отдельный класс: МОНОТОННО
// УБЫВАЮЩУЮ стоимость, которая ЗАТЕМ СТАБИЛИЗИРУЕТСЯ — прогрев кэшей
// процессора и аллокатора, разгон частоты ядра под нагрузкой. Такой сдвиг
// направлен ИМЕННО в сторону отказа (стоимость калибровки всегда выше
// стоимости уже прогретой операции) и лишняя попытка пересчёта от него
// защищает строго: первый пересчёт использует стоимость ещё не до конца
// прогретой первой серии и может снова недооценить число проходов, а
// второй — стоимость уже более прогретой второй серии, которая ближе к
// установившейся. Раньше это демонстрировал fakeRecalibrationExhaustedCodec —
// интеграционный двойник с busyWait на реальном времени (см. измерение под
// нагрузкой ниже); он удалён в пользу детерминированного, не зависящего от
// часов юнит-теста TestCalibrateAndMeasureExhaustsRecalibrationAttempts
// (measure_test.go), который вызывает calibrateAndMeasure напрямую с
// подставной seriesClock и проверяет тот же непрекращающийся класс числами,
// а не гонкой с планировщиком.
//
// От чего предел 2 НЕ защищает и не может защитить в принципе — устойчивый
// СДВИГ стоимости между сериями (посторонняя нагрузка началась в процессе
// измерения) или НЕПРЕКРАЩАЮЩЕЕСЯ (не стабилизирующееся) падение стоимости:
// стоимость операции измеряется заново на каждом пересчёте, а не
// накапливается по прошлым попыткам, так что после второго, третьего и т.д.
// пересчёта харнесс с тем же успехом мог бы застать очередной сдвиг или
// продолжающееся падение. От этого класса не защищает НИКАКОЙ конечный
// предел — расширение сверх 2 не даёт здесь дополнительной защиты, только
// дороже стоит на входах, которые и так не наберут порог ни при каком
// разумном числе попыток (см. TestCalibrateAndMeasureExhaustsRecalibrationAttempts
// в measure_test.go: детерминированный, без единого обращения к часам
// сценарий с непрекращающимся, НЕ стабилизирующимся убыванием стоимости от
// серии к серии — 20мс → 8мс → 2мс, — который ни один конечный
// maxRecalibrations не спасает).
//
// На реальном корпусе (profiles/products.ndjson и events-small.ndjson,
// кодеки lz4/zstd/gzip всех уровней стенда — brotli исключён из этой
// проверки: даже его самый быстрый уровень занимает на этом корпусе больше
// секунды на одно сжатие, то есть многопроходная калибровка для него
// структурно недостижима, гонять его повторно не даёт информации, см.
// task-2-report.md), холостой ход, n=306 успешных вызовов Measure: второй
// пересчёт (после которого разница между пределом 1 и пределом ≥2 вообще
// проявилась бы) НЕ потребовался НИ РАЗУ (0 из 306). Ровно один пересчёт
// потребовался 4 раза из 306 — предел 1 уже покрывал бы и их, предел 2 их
// не отличает. Предел 2 здесь — дешёвый запас на класс «стабилизирующийся
// прогрев», который на этом конкретном прогоне корпуса не проявился ни
// разу, а не доказательство того, что он когда-либо понадобится именно на
// этих данных (см. task-2-report.md, раздел «Фиксы финального ревью», для
// полного протокола и чисел).
const maxRecalibrations = 2

type Measurement struct {
	Codec            string
	Level            int
	Profile          string
	InputBytes       int64
	OutputBytes      int64
	Ratio            float64
	CompressMBs      float64
	DecompressMBs    float64
	Reps             int
	CompressMs       []float64
	DecompressMs     []float64
	CompressPasses   int
	DecompressPasses int
	// CompressAttempts/DecompressAttempts — сколько серий потребовалось
	// измерить, прежде чем суммарная длительность достигла minDurationMs:
	// 1 — исходная серия набрала порог сразу, 2 — потребовался один пересчёт
	// по фактической медиане (см. maxRecalibrations). Заполняется только для
	// опубликованных замеров: отброшенные (недостигшие порога) попытки в
	// CompressMs/DecompressMs не попадают, но их число видно здесь.
	CompressAttempts   int
	DecompressAttempts int
}

func median(xs []float64) float64 {
	s := append([]float64(nil), xs...)
	sort.Float64s(s)
	n := len(s)
	if n == 0 {
		return 0
	}
	if n%2 == 1 {
		return s[n/2]
	}
	return (s[n/2-1] + s[n/2]) / 2
}

// calibratePasses оценивает, сколько проходов подряд нужно выполнить внутри
// одного замера, чтобы их суммарная длительность заведомо превысила
// minDurationMs, — по oneMs, оценке длительности одного прохода (с этого
// фикса — медиана calibrationSamples прогревочных сэмплов, а не единственный
// сэмпл; см. calibrationSamples). Идея та же, что у testing.B: если одна
// итерация короче порога надёжности таймера, гонят несколько подряд и делят
// суммарное время на их число.
//
// Расчёт делается один раз, здесь, а не заново на каждом повторе основной
// серии: иначе разные повторы одного замера измерялись бы разной методикой
// (разным числом проходов), и медиана по ним потеряла бы смысл.
//
// Запас safetyMargin над порогом защищает от того, что случайный дрожащий
// повтор в основной серии окажется чуть короче оценки, сделанной по одному
// прогревочному проходу, и уйдёт под порог заново. Если проход уже не короче
// порога сам по себе — домножать нечего, достаточно одного прохода: это
// самый частый случай в реальной матрице (сжатие почти всех уровней уже
// перекрывает порог за один проход, множитель нужен в основном разжатию
// быстрых кодеков).
//
// Если прогрев дал неразличимо малую длительность (таймер вернул 0 — то
// самое явление, из-за которого порог вообще существует), оценить множитель
// по формуле «сколько проходов нужно» нельзя: делить пришлось бы на ноль.
// В этом случае берётся maxPasses — и этого достаточно, чтобы Measure сразу
// отверг замер (см. passesAtLimit): раз оценить нужное число проходов не
// удалось даже приблизительно, maxPasses здесь — это потолок, а не оценка,
// и сам факт упора в него является основанием для отказа, без ожидания
// того, что покажет суммарная длительность серии.
func calibratePasses(oneMs float64) int {
	if oneMs >= minDurationMs {
		return 1
	}
	if oneMs <= 0 {
		return maxPasses
	}
	const safetyMargin = 1.5
	target := minDurationMs * safetyMargin
	passes := int(math.Ceil(target / oneMs))
	if passes < 1 {
		passes = 1
	}
	if passes > maxPasses {
		passes = maxPasses
	}
	return passes
}

// passesAtLimit сообщает, упёрлась ли калибровка в maxPasses. Это чистая
// функция от числа, а не от того, как оно получено: вызывающая сторона
// (Measure) решает, что делать с фактом упора, эта функция лишь его
// констатирует. Используется >= (а не ==), потому что calibratePasses
// гарантирует передавать сюда только значения не выше maxPasses, но сама
// граница проверки должна быть верна и для пограничного/чуть большего
// значения, если вызвана напрямую (в тестах — синтетическими числами).
func passesAtLimit(passes int) bool {
	return passes >= maxPasses
}

// meetsThreshold сообщает, достаточно ли суммарная длительность серии
// проходов (totalMs) для публикации замера при пороге thresholdMs. Порог
// включительный: длительность, равная порогу, считается достоверной.
// Чистая функция от чисел — не знает ни о кодеках, ни о часах; конкретные
// totalMs/thresholdMs вызывающая сторона получает из реального замера
// (Measure) или подставляет напрямую в тестах.
func meetsThreshold(totalMs, thresholdMs float64) bool {
	return totalMs >= thresholdMs
}

// seriesClock измеряет суммарную длительность одного вызова run() — одного
// повтора серии из passes проходов подряд, — и возвращает её в мс. run()
// выполняет сами проходы; clock решает, как посчитать их длительность.
// passes передаётся клоку отдельно (а не выводится им из run()), потому что
// run() сама не знает, сколько проходов внутри неё было сделано — это знает
// только вызывающая runSeries сторона, а подставным клокам в тестах число
// проходов нужно, чтобы явно задать суммарную длительность через стоимость
// ОДНОГО прохода, а не тотала целиком.
//
// В проде единственная реализация — wallClock (реальные часы). Тестам это
// позволяет подставить детерминированную функцию, которая возвращает заранее
// заданное число вместо измеренного времени, — так проверка логики
// исчерпания попыток пересчёта (см. calibrateAndMeasure и
// TestCalibrateAndMeasureExhaustsRecalibrationAttempts /
// TestMeasureRejectsWhenRecalibrationAttemptsExhausted в measure_test.go)
// перестаёт зависеть от планировщика ОС и посторонней нагрузки на машине.
type seriesClock func(passes int, run func()) float64

// wallClock — реализация seriesClock поверх реальных часов: ровно то же
// измерение (time.Now() до, time.Since() после), что раньше было зашито
// напрямую в runSeries и в прогреве Measure. Используется во всех
// продакшен-путях (см. Measure).
func wallClock(_ int, run func()) float64 {
	t0 := time.Now()
	run()
	return float64(time.Since(t0).Microseconds()) / 1000
}

// runSeries выполняет minReps повторов из passes проходов подряд вызова op
// над input и возвращает по каждому повтору длительность одного прохода
// (суммарное время серии проходов, измеренное clock и делённое на их число),
// а также выход последнего вызова последнего повтора. Не знает ни о
// кодеках, ни о пороге достоверности — это чистая механика измерения,
// используется и для сжатия, и для разжатия через замыкание op.
func runSeries(op func([]byte) ([]byte, error), input []byte, passes, minReps int, clock seriesClock) ([]float64, []byte, error) {
	ms := make([]float64, 0, minReps)
	var last []byte
	for i := 0; i < minReps; i++ {
		var out []byte
		var opErr error
		total := clock(passes, func() {
			for p := 0; p < passes; p++ {
				out, opErr = op(input)
				if opErr != nil {
					return
				}
			}
		})
		if opErr != nil {
			return nil, nil, opErr
		}
		ms = append(ms, total/float64(passes))
		last = out
	}
	return ms, last, nil
}

// calibrateAndMeasure прогоняет серию op (minReps повторов из passes
// проходов подряд), и если её суммарная длительность не достигла
// minDurationMs, пересчитывает число проходов той же calibratePasses, но на
// входе — медиана длительности одного прохода, фактически измеренная в этой
// серии (а не прогревочный сэмпл), и перепрогоняет серию заново — не более
// maxRecalibrations раз (см. константу и обоснование сходимости там же).
//
// Если очередной пересчёт сам упирается в maxPasses, лишняя серия не
// прогоняется: упор в предел — самостоятельная причина отказа независимо от
// того, что показала бы такая серия по факту (тот же принцип, что и для
// самой первой калибровки в Measure), так что цикл останавливается сразу.
// Важно: в этом случае возвращаемые ms/finalPasses НЕ переписываются на
// newPasses — они остаются от последней реально прогнанной серии (той,
// median(ms) которой и породила newPasses). Раньше finalPasses был
// присвоен newPasses (=maxPasses) при том, что ms так и оставался от серии
// с прежним, много меньшим числом проходов — пара становилась
// рассогласованной, и Measure домножал длительность одной серии на число
// проходов другой, никогда не выполнявшейся (см. отчёт о финальном ревью
// Задачи 2). Факт упора в предел сигнализируется отдельно, через hitLimit:
// вызывающая сторона обязана отказать по нему ДО того, как считать
// суммарную длительность, а не полагаться на то, что рассогласованное
// произведение случайно не пересечёт порог.
//
// Возвращает финальные ms/out/passes (всегда согласованную пару — passes
// это число проходов, которым реально измерен ms), число реально
// измеренных серий (attempts) и hitLimit — упёрся ли пересчёт в предел.
// Решение о публикации и текст ошибки остаются на вызывающей стороне
// (Measure): эта функция знает только механику пересчёта, а не про
// кодеки, профили или тексты ошибок.
//
// clock — см. seriesClock: в проде всегда wallClock (реальные часы), в
// тестах — детерминированная подстановка, не зависящая от того, как
// планировщик ОС и посторонняя нагрузка на машине отработали в момент
// прогона (см. TestCalibrateAndMeasureExhaustsRecalibrationAttempts).
func calibrateAndMeasure(op func([]byte) ([]byte, error), input []byte, passes, minReps int, clock seriesClock) (ms []float64, out []byte, finalPasses, attempts int, hitLimit bool, err error) {
	ms, out, err = runSeries(op, input, passes, minReps, clock)
	if err != nil {
		return nil, nil, passes, 0, false, err
	}
	attempts = 1
	for !meetsThreshold(median(ms)*float64(passes), minDurationMs) && attempts <= maxRecalibrations {
		newPasses := calibratePasses(median(ms))
		if passesAtLimit(newPasses) {
			// Пересчёт сам упёрся в предел — не тратим время на серию,
			// которая всё равно не будет опубликована (см. doc-комментарий
			// выше). attempts не растёт: реально измеренных серий на этом
			// пересчёте не прибавилось, только что убедились в упоре.
			// passes и ms НЕ переписываются на newPasses/эту непрогнанную
			// серию — они остаются согласованной парой от последней
			// реально прогнанной серии; hitLimit сообщает вызывающей
			// стороне отказать независимо от того, что показало бы это
			// (несуществующее) произведение.
			hitLimit = true
			break
		}
		passes = newPasses
		newMs, newOut, rerunErr := runSeries(op, input, passes, minReps, clock)
		if rerunErr != nil {
			return nil, nil, passes, attempts, false, rerunErr
		}
		ms, out = newMs, newOut
		attempts++
	}
	return ms, out, passes, attempts, hitLimit, nil
}

// Measure выполняет minReps повторов сжатия и разжатия и возвращает медианы.
// Публикуется медиана, а не среднее: одиночный выброс планировщика не должен
// сдвигать результат. Все повторы сохраняются — они идут в CSV, чтобы
// читатель видел разброс, а не только итог.
//
// Каждый повтор сжатия и каждый повтор разжатия внутри него — это не всегда
// одна операция, а cPasses/dPasses проходов подряд (см. calibratePasses):
// число проходов подбирается отдельно для сжатия и для разжатия, потому что
// их длительности на одних и тех же данных различаются в разы, и общий
// множитель заставил бы более медленную операцию делать лишнюю работу.
// CompressMs/DecompressMs хранят длительность одного прохода (суммарное
// время серии, делённое на число проходов) — иначе CSV и сравнения между
// кодеками с разными множителями стали бы несопоставимы. Ratio, InputBytes
// и OutputBytes берутся с одного (прогревочного) прохода и от числа
// проходов не зависят: многопроходность — это только методика измерения
// времени, она не должна влиять на измеренные размеры.
//
// Если серия (сжатия или разжатия) не набрала порог с первой попытки,
// calibrateAndMeasure пересчитывает число проходов по факту и перепрогоняет
// — см. calibrateAndMeasure и maxRecalibrations. Сжатие и разжатие
// пересчитываются полностью независимо друг от друга: если сжатие набрало
// порог с первой попытки, а разжатие — нет, перепрогоняется только серия
// разжатия. Публикуются CompressMs/DecompressMs ТОЛЬКО последней (успешной)
// серии — отброшенные попытки в них не попадают, но их число сохраняется в
// CompressAttempts/DecompressAttempts.
//
// Measure сама — тонкая обёртка над measureWithClock, всегда подставляющая
// wallClock (реальные часы). Разделение сделано ради тестируемости: тесты
// (measure_test.go) вызывают measureWithClock напрямую с подставной
// seriesClock, чтобы проверить ветки калибровки (в частности — исчерпание
// лимита пересчётов, см. TestMeasureRejectsWhenRecalibrationAttemptsExhausted)
// детерминированно, без зависимости от реального времени и загрузки машины.
// Публичная сигнатура Measure при этом не меняется.
func Measure(c Codec, profile string, data []byte, minReps int) (Measurement, error) {
	return measureWithClock(c, profile, data, minReps, wallClock)
}

func measureWithClock(c Codec, profile string, data []byte, minReps int, clock seriesClock) (Measurement, error) {
	if minReps < 1 {
		return Measurement{}, fmt.Errorf("minReps=%d", minReps)
	}

	// Прогрев: calibrationSamples повторов оплачивают аллокации и прогрев
	// кэшей и не должны попадать в статистику замеров (в CompressMs/
	// DecompressMs) — но их длительности нужны, чтобы откалибровать число
	// проходов ниже. Берётся не последний и не первый сэмпл, а медиана всех
	// calibrationSamples — той же функцией median, что и для основной серии
	// повторов, — чтобы единичный выброс планировщика ОС на одном
	// прогревочном сэмпле не решал калибровку в одиночку (см.
	// calibrationSamples). comp сохраняется с последнего сэмпла: сжатие
	// детерминировано по входу, так что Ratio/InputBytes/OutputBytes не
	// зависят от того, какой именно из calibrationSamples проходов взят.
	warmCompressSamples := make([]float64, 0, calibrationSamples)
	warmDecompressSamples := make([]float64, 0, calibrationSamples)
	var comp []byte
	for i := 0; i < calibrationSamples; i++ {
		var out []byte
		var cErr error
		warmC := clock(1, func() {
			out, cErr = c.Compress(data)
		})
		if cErr != nil {
			return Measurement{}, fmt.Errorf("%s уровень %d: сжатие (прогрев): %w", c.Name(), c.Level(), cErr)
		}
		warmCompressSamples = append(warmCompressSamples, warmC)
		comp = out

		var warmBack []byte
		var dErr error
		warmD := clock(1, func() {
			warmBack, dErr = c.Decompress(comp)
		})
		if dErr != nil {
			return Measurement{}, fmt.Errorf("%s уровень %d: разжатие (прогрев): %w", c.Name(), c.Level(), dErr)
		}
		warmDecompressSamples = append(warmDecompressSamples, warmD)
		if len(warmBack) != len(data) {
			return Measurement{}, fmt.Errorf("%s уровень %d: round-trip (прогрев) дал %d байт вместо %d",
				c.Name(), c.Level(), len(warmBack), len(data))
		}
	}
	warmCompressMs := median(warmCompressSamples)
	warmDecompressMs := median(warmDecompressSamples)

	cPasses := calibratePasses(warmCompressMs)
	dPasses := calibratePasses(warmDecompressMs)

	// Упор в maxPasses — самостоятельная причина отказа, а не повод ждать,
	// что покажет суммарная длительность серии после того, как мы всё же
	// прогоним предельное число проходов. Если калибровка уткнулась в
	// предел, число проходов не отражает намерения (см. maxPasses и
	// passesAtLimit), и это истинно вне зависимости от того, пересечёт ли
	// суммарная длительность порог по факту. Проверяется сразу после
	// калибровки, до основной серии: если замер всё равно не будет
	// опубликован, незачем тратить время на maxPasses реальных вызовов
	// кодека.
	if passesAtLimit(cPasses) {
		return Measurement{}, fmt.Errorf(
			"%s уровень %d, профиль %s: калибровка сжатия исчерпала предел проходов "+
				"maxPasses=%d (медиана %d прогревочных сэмплов дала ~%.6f мс) — замер "+
				"недостоверен, увеличьте объём данных",
			c.Name(), c.Level(), profile, maxPasses, calibrationSamples, warmCompressMs)
	}
	if passesAtLimit(dPasses) {
		return Measurement{}, fmt.Errorf(
			"%s уровень %d, профиль %s: калибровка разжатия исчерпала предел проходов "+
				"maxPasses=%d (медиана %d прогревочных сэмплов дала ~%.6f мс) — замер "+
				"недостоверен, увеличьте объём данных",
			c.Name(), c.Level(), profile, maxPasses, calibrationSamples, warmDecompressMs)
	}

	// Основная серия сжатия: calibrateAndMeasure сама пересчитает cPasses и
	// перепрогонит серию, если суммарная длительность не наберёт порог (см.
	// doc-комментарий у calibrateAndMeasure/maxRecalibrations). out here не
	// используется дальше: comp (детерминированный выход прогрева) — тот же
	// набор байт, что дал бы любой compress-проход основной серии на этом же
	// входе, и именно comp кормит разжатие ниже.
	cMs, _, cPasses, cAttempts, cHitLimit, err := calibrateAndMeasure(
		func(_ []byte) ([]byte, error) { return c.Compress(data) }, data, cPasses, minReps, clock)
	if err != nil {
		return Measurement{}, fmt.Errorf("%s уровень %d: сжатие: %w", c.Name(), c.Level(), err)
	}
	// Проверяется ДО вычисления суммарной длительности: если пересчёт упёрся
	// в предел, cMs/cPasses — согласованная пара от последней РЕАЛЬНО
	// прогнанной серии (см. calibrateAndMeasure), а не от гипотетической
	// серии на maxPasses. Считать totalMedC в этом случае незачем и
	// небезопасно — до фикса именно это давало рассогласованное
	// произведение медианы одной серии на число проходов другой, которая
	// никогда не выполнялась (см. отчёт о финальном ревью Задачи 2).
	if cHitLimit {
		return Measurement{}, fmt.Errorf(
			"%s уровень %d, профиль %s: пересчёт по фактической медиане серии сжатия "+
				"исчерпал предел проходов maxPasses=%d (после %d измеренной(ых) серии(й), "+
				"медиана последней реально прогнанной серии ~%.6f мс за проход) — замер "+
				"недостоверен, увеличьте объём данных",
			c.Name(), c.Level(), profile, maxPasses, cAttempts, median(cMs))
	}
	medC := median(cMs)
	totalMedC := medC * float64(cPasses)
	if !meetsThreshold(totalMedC, minDurationMs) {
		return Measurement{}, fmt.Errorf(
			"%s уровень %d, профиль %s: суммарная длительность серии сжатия %.3f мс "+
				"(проходов=%d) всё ещё ниже порога %.0f мс после %d попыт(ок) калибровки — "+
				"лимит пересчётов (%d) исчерпан, замер недостоверен, увеличьте объём данных",
			c.Name(), c.Level(), profile, totalMedC, cPasses, minDurationMs, cAttempts, maxRecalibrations)
	}

	// Разжатие пересчитывается полностью независимо от сжатия: вход у него
	// фиксирован (comp, детерминированный выход compress) и не зависит от
	// того, сколько попыток потребовалось сжатию, а решение о пересчёте
	// разжатия принимается по его собственной суммарной длительности.
	dMs, back, dPasses, dAttempts, dHitLimit, err := calibrateAndMeasure(
		func(src []byte) ([]byte, error) { return c.Decompress(src) }, comp, dPasses, minReps, clock)
	if err != nil {
		return Measurement{}, fmt.Errorf("%s уровень %d: разжатие: %w", c.Name(), c.Level(), err)
	}
	// См. симметричную проверку для сжатия выше: отказ по hitLimit — ДО
	// вычисления суммарной длительности, до проверки round-trip и до median.
	if dHitLimit {
		return Measurement{}, fmt.Errorf(
			"%s уровень %d, профиль %s: пересчёт по фактической медиане серии разжатия "+
				"исчерпал предел проходов maxPasses=%d (после %d измеренной(ых) серии(й), "+
				"медиана последней реально прогнанной серии ~%.6f мс за проход) — замер "+
				"недостоверен, увеличьте объём данных",
			c.Name(), c.Level(), profile, maxPasses, dAttempts, median(dMs))
	}
	// Проверяется длина только последнего прохода последней измеренной
	// серии, а не каждого повтора/прохода: корректность round-trip самих
	// библиотек кодеков уже покрыта TestCodecRoundTrip (по разу на
	// кодек/уровень); пересчёт и multiplier здесь — исключительно методика
	// измерения времени, а не повторная проверка корректности.
	if len(back) != len(data) {
		return Measurement{}, fmt.Errorf("%s уровень %d: round-trip дал %d байт вместо %d",
			c.Name(), c.Level(), len(back), len(data))
	}
	medD := median(dMs)
	totalMedD := medD * float64(dPasses)
	if !meetsThreshold(totalMedD, minDurationMs) {
		return Measurement{}, fmt.Errorf(
			"%s уровень %d, профиль %s: суммарная длительность серии разжатия %.3f мс "+
				"(проходов=%d) всё ещё ниже порога %.0f мс после %d попыт(ок) калибровки — "+
				"лимит пересчётов (%d) исчерпан, замер недостоверен, увеличьте объём данных",
			c.Name(), c.Level(), profile, totalMedD, dPasses, minDurationMs, dAttempts, maxRecalibrations)
	}

	mb := float64(len(data)) / (1024 * 1024)
	return Measurement{
		Codec:              c.Name(),
		Level:              c.Level(),
		Profile:            profile,
		InputBytes:         int64(len(data)),
		OutputBytes:        int64(len(comp)),
		Ratio:              float64(len(data)) / float64(len(comp)),
		CompressMBs:        mb / (medC / 1000),
		DecompressMBs:      mb / (medD / 1000),
		Reps:               minReps,
		CompressMs:         cMs,
		DecompressMs:       dMs,
		CompressPasses:     cPasses,
		DecompressPasses:   dPasses,
		CompressAttempts:   cAttempts,
		DecompressAttempts: dAttempts,
	}, nil
}
