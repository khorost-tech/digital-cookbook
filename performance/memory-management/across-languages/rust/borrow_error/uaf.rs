//! Опора 2 — характерный баг use-after-free НЕ КОМПИЛИРУЕТСЯ.
//!
//! Этот файл ЗАВЕДОМО не проходит borrow checker и лежит ВНЕ `src/`,
//! чтобы обычный `cargo build` оставался зелёным. Компилировать напрямую:
//!
//!     rustc --edition 2021 borrow_error/uaf.rs
//!
//! Ожидается ошибка E0502: нельзя одновременно держать неизменяемую ссылку
//! на элемент вектора и вызывать `push`, который может перевыделить буфер и
//! инвалидировать эту ссылку (классический dangling pointer / use-after-free).
//!
//! В C++ тот же паттерн (`auto& r = v[0]; v.push_back(x); use(r);`) молча
//! компилируется и роняет программу в рантайме. В Rust это ловит компилятор.

fn main() {
    let mut v = vec![1, 2, 3];

    // Неизменяемая ссылка на первый элемент внутри буфера вектора.
    let first = &v[0];

    // push может перевыделить внутренний буфер -> `first` повиснет.
    // Требуется изменяемый заём `v`, пока жив неизменяемый `first`. E0502.
    v.push(4);

    // Использование ссылки ПОСЛЕ потенциальной реаллокации — это и есть UAF.
    println!("first = {}", first);
}
