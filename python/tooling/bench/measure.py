"""Измеритель: перцентили и сбалансированная ротация.

Дублирует одноимённый модуль стенда python/concurrency намеренно: стенды
должны быть самодостаточными, читатель приходит в один из них, а не в оба.
"""

import math


def percentile(xs, q: float) -> float:
    """Перцентиль методом nearest-rank: idx = ceil(q*n) - 1.

    Не floor((n-1)*q): та формула занижает верхние перцентили на позицию.
    Сортируется КОПИЯ — список вызывающего не портится.
    """
    if not xs:
        return 0
    s = sorted(xs)
    idx = math.ceil(q * len(s)) - 1
    return s[min(max(idx, 0), len(s) - 1)]


def latin_square(seed: int, round_no: int, k: int) -> list[int]:
    """Циклическая ротация порядка целей — латинский квадрат порядка k.

    За k последовательных кругов каждая цель занимает каждую позицию ровно
    один раз, при любом seed. Случайная перестановка такого баланса на малом
    числе кругов не даёт: на этом уже спотыкался соседний стенд.
    """
    n = seed + round_no
    return [(n + i) % k for i in range(k)]


def counterbalance(order, first, second, flip):
    """Задаёт относительный порядок двух элементов внутри круга.

    Циклический сдвиг балансирует ПОЗИЦИИ, но не относительный порядок
    пары. Для списка из пяти запросов, где heavy-rows стоит третьим, а
    heavy-entities четвёртым, из пяти сдвигов лишь один ставит их в
    обратном порядке: за одиннадцать кругов выходит примерно 9:2. Для
    контролируемой пары это значит, что порядок запуска остаётся почти
    постоянным и подмешивается к измеряемому эффекту.

    Здесь порядок пары задаётся явно флагом, а вызывающий чередует флаг по
    кругам. Остальная перестановка не трогается: позиции по-прежнему
    балансирует сдвиг.

    flip=False — first раньше second, flip=True — наоборот.
    """
    order = list(order)
    pos = {value: index for index, value in enumerate(order)}
    a, b = pos[first], pos[second]
    if (a < b) == bool(flip):
        order[a], order[b] = order[b], order[a]
    return order
