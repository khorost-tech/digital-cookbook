"""Кэши инструментов: перечислить, измерить, очистить по отдельности.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ. «Холодная установка» — самая обманчивая
формулировка в замерах упаковки. У каждого инструмента свой набор кэшей:
метаданные индекса, скачанные архивы, распакованные колёса, само
окружение. Прогон, в котором очищено три кэша из четырёх, измеряет
четвёртый — и выглядит совершенно нормально, потому что числа получаются
правдоподобные.

Поэтому здесь кэши не «чистятся перед замером», а ИЗМЕРЯЮТСЯ до каждого
прогона, и размеры уходят в фикстуру. Утверждение «кэш был холодный»
проверяется по фикстуре, а не по памяти автора.

ЧТО СЧИТАЕТСЯ КЭШЕМ. Всё, что инструмент сохраняет между запусками, кроме
самого окружения: окружение — это результат, а не кэш, и оно
пересоздаётся отдельно.
"""

import shutil
from pathlib import Path

# У каждого инструмента ОДИН корень кэша, заданный переменной окружения в
# docker-compose. Так сделано намеренно: разложить кэши по разным местам
# значило бы, что очистка одного инструмента задевает другой.
ROOTS = {
    "uv": Path("/caches/uv"),
    "pip": Path("/caches/pip"),
    "poetry": Path("/caches/poetry"),
}


def size_mib(path):
    """Размер каталога в мебибайтах. Отсутствующий каталог — ноль."""
    path = Path(path)
    if not path.exists():
        return 0.0
    total = sum(f.stat().st_size for f in path.rglob("*") if f.is_file())
    return round(total / 1024 / 1024, 2)


def sizes():
    """Размеры всех кэшей. Уходит в каждую строку фикстуры."""
    return {name: size_mib(root) for name, root in ROOTS.items()}


def clear(tool_name):
    """Полностью убирает кэш одного инструмента.

    Удаляется каталог целиком, а не его содержимое выборочно: выборочная
    очистка — это и есть тот случай, когда «холодным» остаётся не всё, а
    замер об этом молчит.
    """
    root = ROOTS[tool_name]
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True, exist_ok=True)


def assert_cold(tool_name, limit_mib=0.5):
    """Проверяет, что кэш действительно пуст.

    Порог не ноль: инструменты создают служебные файлы блокировок сразу
    при запуске, и требовать буквального нуля значило бы падать на пустом
    месте. Но полмегабайта — это уже не «пусто».
    """
    actual = size_mib(ROOTS[tool_name])
    if actual > limit_mib:
        raise RuntimeError(
            f"кэш {tool_name} не пуст перед холодным прогоном: {actual} МиБ — "
            f"замер измерил бы тёплый кэш под видом холодного")
    return actual
