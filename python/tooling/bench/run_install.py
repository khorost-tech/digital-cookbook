"""Сценарий установки: три инструмента в трёх состояниях кэша.

ТРИ СОСТОЯНИЯ, И КАЖДОЕ ОТВЕЧАЕТ РЕАЛЬНОМУ СЛУЧАЮ.

    cold   кэш пуст, окружения нет      — новая машина, первый прогон CI
    warm   кэш полон, окружения нет     — CI с восстановленным кэшем
    noop   кэш полон, окружение на месте — повторный install у разработчика

ПОРЯДОК СОСТОЯНИЙ РОТИРУЕТСЯ, И ЭТО ГЛАВНОЕ В УСТРОЙСТВЕ СЦЕНАРИЯ.

Первая версия гоняла состояния строго подряд: cold, warm, noop. Рассуждение
было такое: «тёплый» означает «после холодного», значит порядок задан
смыслом и ротации не поддаётся. Рассуждение неверное. Кэш можно наполнить
ВНЕ ЗАМЕРА, а потом привести окружение к нужному состоянию — и тогда любое
состояние достижимо на любой позиции.

Цена ошибки была не в аккуратности, а в выводе. При фиксированном порядке
разность cold − warm включала не только эффект кэша, но и эффект позиции:
страничный кэш ОС, прогрев процессора и файловой системы. Числа честные,
но приписывались они не тому.

Поэтому здесь перед КАЖДЫМ замером выполняется одинаковый неучитываемый
прогон (prime), и лишь затем состояние доводится до нужного:

    cold   prime, затем кэш инструмента очищается, окружение удаляется
    warm   prime, затем удаляется только окружение
    noop   prime, и больше ничего

Одинаковая работа перед всеми тремя состояниями выравнивает то, что
раньше в них различалось. Дальше ротируются ДВА порядка, и они обязаны
быть независимы.

ПЕРВАЯ ПОПЫТКА РАЗВЕСТИ ИХ ПРОВАЛИЛАСЬ, причём незаметно. Порядок
состояний брался тем же латинским квадратом со смещением на номер
инструмента — казалось, что смещение развязывает ротации. На деле оно
связало их намертво: у uv «состояние на первой позиции» означало ровно
«uv запускается третьим, после Poetry и pip». Разложение времени по
позиции состояния было в точности разложением по позиции инструмента, и
приписать наблюдение одному из двух факторов было нельзя.

    круг 1: pip, poetry, uv   -> у uv warm на 1-й позиции
    круг 2: poetry, uv, pip   -> у uv warm на 3-й позиции
    круг 3: uv, pip, poetry   -> у uv warm на 2-й позиции

ТЕПЕРЬ ДВА КЛЮЧА, И ОНИ НЕЗАВИСИМЫ. Порядок инструментов задаётся
циклическим сдвигом по (r-1) % 3, порядок состояний — одной из ШЕСТИ
перестановок по (r-1) // 3. За 18 кругов каждая пара «сдвиг × перестановка»
встречается ровно один раз, поэтому позиция инструмента и позиция
состояния разложены полностью.

Шесть перестановок вместо трёх циклических взяты не для красоты: при
циклических холодный замер стоял бы раньше тёплого в двух кругах из трёх,
а при полном переборе — ровно в половине.

В каждую строку пишутся ОБЕ позиции плюс сквозная позиция замера в круге
(0..8). Разбор проверяет, что ни один фактор не оказался функцией другого.

ПЕРВЫЙ КРУГ ОТБРАСЫВАЕТСЯ. Кэши переживают прогоны, и их содержимое
зависит от того, чем закончился прошлый сеанс. Подробности — в warmup.

ЧТО ЗДЕСЬ НАЗЫВАЕТСЯ ХОЛОДНЫМ. Пустым делается кэш ИНСТРУМЕНТА, а не
страничный кэш операционной системы: последний прогрет одинаково перед
всеми тремя состояниями и потому из сравнения выпадает. Это и есть
предмет замера — «первый install на машине, где пакетов ещё не скачивали»,
а не «install на только что загруженной машине».

Позиция каждого замера в круге пишется в фикстуру, чтобы остаточный
эффект позиции можно было ПОСЧИТАТЬ, а не заверить словами.

ОТДЕЛЬНОЕ ПЛЕЧО — ПРОТИВ НАСТОЯЩЕГО PyPI. Оно помечено в фикстуре как
невоспроизводимое и нужно лишь для порядка величины: основные числа сняты
с локального индекса, то есть в условиях, которых в жизни не бывает.
Подробности — в pypi_arm.

ЧТО ПОПАДАЕТ В КАЖДУЮ СТРОКУ. Время, размеры ВСЕХ кэшей до прогона, число
установленных пакетов и хеш набора. Последнее — чтобы «быстрее» никогда не
означало «сделал меньше»: расхождение хеша с эталоном видно прямо в
фикстуре, а не только на блокирующей проверке до замера.
"""

import itertools
import json
import os
import shutil
import sys
import time

sys.path.insert(0, "/bench")

import caches  # noqa: E402
import installed  # noqa: E402
import measure  # noqa: E402
import tools  # noqa: E402

STATES = ("cold", "warm", "noop")
# Все шесть перестановок, а не три циклические: при циклических холодный
# замер стоял бы раньше тёплого в двух кругах из трёх, а нужно поровну.
STATE_ORDERS = tuple(itertools.permutations(STATES))
PYPI_URL = "https://pypi.org/simple"
# Повторов у плеча против сети больше одного намеренно: разброс здесь
# и есть главное, что о нём надо знать. Два прогона одной и той же
# команды на этом стенде разошлись в восемь раз, и одно число создало
# бы впечатление измеренной величины.
PYPI_REPEATS = int(os.environ.get("PYPI_REPEATS", "2"))


def prime(tool):
    """Неучитываемый прогон перед каждым замером.

    Делает две вещи разом. Во-первых, приводит кэш и окружение в полное
    состояние, из которого любое из трёх нужных достижимо удалением, — а
    значит состояние перестаёт зависеть от позиции в круге. Во-вторых,
    прогревает машину одинаково перед всеми состояниями: раньше эту роль
    играл один разогрев на круг, и доставался он только первому замеру.

    Результат отбрасывается. Время prime в фикстуру не идёт.
    """
    tools.install(tool)


def pypi_arm(out):
    """Холодный прогон против настоящего PyPI — там, где это возможно.

    ЭТИ ЧИСЛА НЕВОСПРОИЗВОДИМЫ, и помечены они соответственно. PyPI
    отвечает по-разному в разное время суток, канал до него у каждого
    свой, а зеркала различаются между собой сильнее, чем инструменты.
    Ранжировать инструменты по этому плечу нельзя.

    Зачем оно тогда нужно. Основные числа сняты с локального индекса, то
    есть в условиях, которых в жизни не бывает. Плечо показывает порядок
    величины: во сколько раз дороже та же установка, когда за пакетами
    надо идти в сеть.

    ПОЧЕМУ ЗДЕСЬ НЕ ВСЕ ТРИ ИНСТРУМЕНТА. У Poetry источник записан в
    pyproject.toml и продублирован в poetry.lock; сменить его снаружи
    нечем, а правка проекта означала бы другую задачу. Пропуск
    записывается в фикстуру строкой с причиной — молчаливое отсутствие
    строки читалось бы как «не успели», а не как «нельзя».

    Перед каждым замером проверяется, что переопределение адреса вообще
    действует: установка с мёртвого адреса обязана упасть. Без этой
    проверки первая версия плеча показала для Poetry 4,2 секунды
    «против PyPI» — ровно столько же, сколько без сети, потому что в
    сеть он не ходил вовсе.
    """
    for repeat in range(1, PYPI_REPEATS + 1):
        pypi_pass(out, repeat)


def pypi_pass(out, repeat):
    for tool in tools.TOOLS:
        if tool.name not in tools.INDEX_ENV:
            if repeat > 1:
                continue
            out.write(json.dumps({
                "kind": "pypi",
                "reproducible": False,
                "tool": tool.name,
                "repeat": repeat,
                "measured": False,
                "reason": tools.NO_INDEX_OVERRIDE[tool.name],
            }, ensure_ascii=False, sort_keys=True) + chr(10))
            out.flush()
            print(f"PyPI {tool.name}: не измеряется — "
                  f"{tools.NO_INDEX_OVERRIDE[tool.name]}", file=sys.stderr)
            continue

        caches.clear(tool.name)
        tools.assert_index_honoured(tool)
        caches.clear(tool.name)
        tools.prepare(tool)
        caches.assert_cold(tool.name)

        env = tools.index_env(tool.name, PYPI_URL)
        before = caches.sizes()
        started = time.perf_counter()
        tools.install(tool, env_extra=env)
        elapsed = time.perf_counter() - started
        snap = installed.snapshot(tools.venv_path(tool))
        out.write(json.dumps({
            "kind": "pypi",
            "reproducible": False,
            "measured": True,
            "tool": tool.name,
            "repeat": repeat,
            "state": "cold",
            "seconds": round(elapsed, 3),
            "caches_before_mib": before,
            "packages": snap["count"],
            "sha256": snap["sha256"],
        }, ensure_ascii=False, sort_keys=True) + chr(10))
        out.flush()
        print(f"PyPI {tool.name} (повтор {repeat}): {elapsed:.1f} с",
              file=sys.stderr)


def measure_state(tool, state, round_no, tool_position, state_position,
                  global_position):
    """Один прогон в заданном состоянии.

    Состояние доводится ПОСЛЕ неучитываемого прогона, поэтому порядок
    состояний в круге свободен.
    """
    prime(tool)
    if state == "cold":
        caches.clear(tool.name)
        tools.prepare(tool)
        caches.assert_cold(tool.name)
    elif state == "warm":
        # Кэш наполнен прогоном prime, убирается только окружение.
        tools.prepare(tool)
    elif state == "noop":
        # Ни кэш, ни окружение не трогаем: после prime на месте и то, и
        # другое, и установка обязана понять, что делать нечего.
        pass
    else:
        raise ValueError(state)

    before = caches.sizes()
    started = time.perf_counter()
    tools.install(tool)
    elapsed = time.perf_counter() - started

    snap = installed.snapshot(tools.venv_path(tool))
    return {
        "tool": tool.name,
        "state": state,
        "round": round_no,
        # Три позиции вместо одной. Первая версия писала только позицию
        # состояния, и она оказалась неотличима от позиции инструмента.
        "tool_position": tool_position,
        "state_position": state_position,
        "global_position": global_position,
        "seconds": round(elapsed, 3),
        "caches_before_mib": before,
        "packages": snap["count"],
        "sha256": snap["sha256"],
        "bootstrap": snap["bootstrap"],
    }


def warmup():
    """Полный круг, результат которого отбрасывается целиком.

    ЗАЧЕМ ОН НУЖЕН. Кэши инструментов переживают прогоны, и их СОДЕРЖИМОЕ
    зависит от того, чем сеанс закончился в прошлый раз. После плеча
    против PyPI кэш uv весил 154,55 МиБ, тогда как установившийся размер —
    138,28: в нём лежали файлы, скачанные из сети. Первый круг мерил
    установку по этому кэшу, и его тёплый замер вышел 2,81 с против 1,68 у
    таких же замеров в следующих кругах.

    Один отбрасываемый круг приводит кэши к установившемуся содержимому и
    заодно прогревает страничный кэш. Разница между «первым кругом» и
    «остальными» после этого исчезает — а если не исчезнет, разбор
    покажет это разбросом внутри позиции.
    """
    for tool in tools.TOOLS:
        for state in STATES:
            measure_state(tool, state, 0, 0, 0, 0)


def main():
    rounds = int(os.environ.get("ROUNDS", "5"))
    seed = int(os.environ.get("SEED", "0"))
    out_path = os.environ.get("OUT", "/fixtures/install.txt")

    if os.environ.get("WARMUP", "1") == "1":
        started = time.time()
        warmup()
        print(f"прогревочный круг отброшен за {time.time() - started:.0f} с",
              file=sys.stderr)

    with open(out_path, "a", encoding="utf-8") as out:
        for r in range(1, rounds + 1):
            started = time.time()
            order = measure.latin_square(seed, r, len(tools.TOOLS))
            # Перестановка состояний зависит от НОМЕРА БЛОКА кругов, а не
            # от номера инструмента: только так два порядка независимы.
            states = STATE_ORDERS[(seed + (r - 1) // len(tools.TOOLS))
                                  % len(STATE_ORDERS)]
            for tool_position, idx in enumerate(order):
                tool = tools.TOOLS[idx]
                for state_position, state in enumerate(states):
                    row = measure_state(
                        tool, state, r, tool_position, state_position,
                        tool_position * len(STATES) + state_position)
                    out.write(json.dumps(row, ensure_ascii=False,
                                         sort_keys=True) + "\n")
                    out.flush()
            print(f"круг {r} готов за {time.time() - started:.0f} с",
                  file=sys.stderr)

        if os.environ.get("PYPI_ARM", "1") == "1":
            pypi_arm(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
