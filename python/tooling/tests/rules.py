"""Проверки бизнес-правил, общие для настоящей базы и для фейка.

ЗАЧЕМ ОБЩИЙ ФАЙЛ. Наборы «на SQLite» и «на PostgreSQL» обязаны проверять
ОДНО И ТО ЖЕ. Скопируй утверждения в два файла — и через неделю они
разойдутся, а разница в результатах будет объясняться не базой, а тем,
что где-то забыли обновить ожидание.

Набор с моками сюда не входит, и это не упущение: мок не выполняет
запрос, поэтому проверить им те же утверждения нечем. Он проверяет, что
репозиторий обратился к соединению и вернул то, что оно отдало. Разница в
утверждениях — не изъян сравнения, а его предмет.
"""


def check_unfinished(repo):
    """Незавершённые — 2, 3 и 4. Третья без статуса, и она тоже не сдана."""
    assert repo.unfinished() == [2, 3, 4]


def check_search_is_case_insensitive(repo):
    """«summa» обязана находить «SUMMA TECHNOLOGIAE»."""
    assert repo.search("summa") == [4]


def check_per_author(repo):
    """По автору: всего задач и сколько завершено."""
    assert repo.per_author() == [("lem", 2, 0), ("strugatsky", 2, 1)]


ALL = (check_unfinished, check_search_is_case_insensitive, check_per_author)
