#!/usr/bin/env bash
# Установка: три инструмента в трёх состояниях кэша.
# Подробности — в bench/run_install.py.
set -euo pipefail

cd "$(dirname "$0")/.."
export MSYS_NO_PATHCONV=1

PREFLIGHT="$(bash "$(dirname "$0")/preflight.sh")"
echo "$PREFLIGHT"

# 18 кругов, а не произвольное число: план замера строится из трёх
# сдвигов порядка инструментов и шести перестановок порядка состояний,
# и полный перебор их пар занимает ровно 18 кругов.
ROUNDS="${ROUNDS:-18}"
SEED="${SEED:-0}"
out=fixtures/install.txt

{
  echo "# Установка набора зависимостей: uv, pip, poetry"
  echo "# rounds=${ROUNDS} seed=${SEED}, порядок инструментов по латинскому квадрату"
  echo "# состояния кэша: cold, warm, noop"
  echo "# два независимых порядка: сдвиг инструментов x перестановка состояний"
  echo "# 18 кругов = полный перебор 3 сдвигов и 6 перестановок"
  echo "# перед каждым замером — одинаковый неучитываемый прогон (prime)"
  echo "# первый полный круг отброшен: кэши приводятся к установившемуся виду"
  echo "# индекс локальный, сеть за скобками"
  echo "# отдельным плечом — прогон против PyPI, помечен как невоспроизводимый"
  echo "# снято: $(date -u '+%Y-%m-%dT%H:%M:%SZ')"
  # Каждую строку preflight — со своей решёткой. Он печатает две строки
  # (вердикт и размеры кэшей), и подстановка целиком уводила вторую в
  # фикстуру без комментария: разбор спотыкался на ней как на данных.
  printf '%s
' "$PREFLIGHT" | sed 's/^/# среда: /' 
  echo "#"
} > "$out"

docker compose exec -T -e ROUNDS="$ROUNDS" -e SEED="$SEED" \
  -e OUT=/fixtures/install.txt -w /bench bench python run_install.py

echo "готово: $out"

# Разбор запускается сразу и БЕЗ конвейера. Дважды в этой серии
# конструкция вида `script | tail` теряла код возврата: отбитый прогон
# выглядел успешным, а фикстура молча уходила в работу. Здесь вызов
# прямой, поэтому set -e останавливает сценарий на негодном замере.
PY="$(command -v python3 || command -v python)"
"$PY" scripts/analyze-install.py
