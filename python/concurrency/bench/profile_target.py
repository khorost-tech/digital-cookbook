"""Нагрузка для сравнения двух видов профайлеров.

Устроена так, чтобы детерминированный и сэмплирующий профайлеры дали РАЗНУЮ
картину на одном и том же коде. Для этого в ней два вида работы примерно
одинаковой суммарной длительности, но с разной зернистостью:

* tiny_step — очень дешёвая функция, вызываемая десятки тысяч раз;
* chunky_step — дорогая функция, вызываемая редко.

Детерминированный профайлер платит фиксированную цену на КАЖДОМ вызове,
поэтому он раздувает долю мелких частых функций. Сэмплирующий смотрит на
стек по таймеру и о числе вызовов ничего не знает, поэтому такого
искажения у него нет. Разница между их картинами — не погрешность
измерения, а следствие устройства инструментов.
"""

import sys
import time

TINY_PER_ITER = 2000
CHUNKY_SIZE = 5000
_MASK = 0xFFFFFFFF


def tiny_step(x: int) -> int:
    """Дешёвая функция: работы на пару операций, накладные расходы на вызов
    сопоставимы с самой работой."""
    return (x * 1103515245 + 12345) & _MASK


def chunky_step(n: int) -> int:
    """Дорогая функция: та же арифметика, но целиком внутри одного вызова."""
    x = 1
    for i in range(n):
        x = (x * 1103515245 + 12345 + i) & _MASK
        x ^= x >> 7
    return x


def mixed_task() -> int:
    x = 1
    for _ in range(TINY_PER_ITER):
        x = tiny_step(x)
    return x ^ chunky_step(CHUNKY_SIZE)


def main(iters: int) -> int:
    # Свёртка позиционная, а не XOR: XOR одинаковых значений чётное число
    # раз даёт ноль, и такая контрольная сумма прошла бы при любой работе.
    acc = 0
    for _ in range(iters):
        acc = (acc * 31 + mixed_task()) & _MASK
    return acc


if __name__ == "__main__":
    iters = int(sys.argv[1]) if len(sys.argv) > 1 else 3000
    # Время печатает сам скрипт: под профайлером в него попадают накладные
    # расходы инструмента, а это ровно то, что мы хотим сравнить.
    t0 = time.perf_counter()
    acc = main(iters)
    elapsed = time.perf_counter() - t0
    print(f"iters={iters} checksum={acc} elapsed_s={elapsed:.4f}", file=sys.stderr)
