"""Две задачи, на которых стоит весь стенд.

cpu_task — чистый Python-байткод без вызовов в C: такая задача удерживает GIL
и потому чувствительна к нему. Библиотечные функции (math, hashlib, zlib) не
годятся: многие из них GIL отпускают, и замер показал бы не границу GIL, а
поведение конкретной библиотеки.

io_task — ожидание. Вычислений в нём нет намеренно: это второе плечо,
на котором GIL не должен быть узким местом.
"""

import asyncio
import time

_MASK = 0xFFFFFFFF


def cpu_task(n: int) -> int:
    """Детерминированное перемешивание целого n шагов.

    Детерминизм обязателен: он позволяет сверить контрольные суммы разных
    моделей исполнения и убедиться, что они считают одно и то же, а не просто
    тратят разное время.
    """
    x = 1
    for i in range(n):
        x = (x * 1103515245 + 12345 + i) & _MASK
        x ^= x >> 7
    return x


def io_task(delay_s: float) -> None:
    """Блокирующее ожидание — для потоков и процессов."""
    time.sleep(delay_s)


async def async_io_task(delay_s: float) -> None:
    """То же ожидание в идиоме asyncio.

    Это не другая задача: ожидание одной длительности выражено средствами
    модели. Вычислительной работы, которая могла бы отличаться, здесь нет.
    """
    await asyncio.sleep(delay_s)
