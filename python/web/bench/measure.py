"""Измеритель: перцентили и сбалансированная ротация.

Дублирует одноимённый модуль стенда python/concurrency намеренно: стенды
должны быть самодостаточными, читатель приходит в один из них, а не в оба.
"""

import math


def percentile(xs, q: float) -> float:
    """Перцентиль методом nearest-rank: idx = ceil(q*n) - 1.

    Не floor((n-1)*q): та формула занижает верхние перцентили на позицию.
    Сортируется КОПИЯ — список вызывающего не портится.
    """
    if not xs:
        return 0
    s = sorted(xs)
    idx = math.ceil(q * len(s)) - 1
    return s[min(max(idx, 0), len(s) - 1)]


def latin_square(seed: int, round_no: int, k: int) -> list[int]:
    """Циклическая ротация порядка целей — латинский квадрат порядка k.

    За k последовательных кругов каждая цель занимает каждую позицию ровно
    один раз, при любом seed. Случайная перестановка такого баланса на малом
    числе кругов не даёт: на этом уже спотыкался соседний стенд.
    """
    n = seed + round_no
    return [(n + i) % k for i in range(k)]
