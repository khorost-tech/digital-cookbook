"""Детерминированный набор Parquet, разбитый на разделы по дню.

ПОЧЕМУ РАЗДЕЛЫ, А НЕ ОДИН ФАЙЛ. Вопрос сценария — избежал ли движок
лишней работы. Первая версия пыталась измерить это в байтах, прочитанных
системными вызовами (`rchar` из /proc/self/io), и упёрлась в то, что
величины несопоставимы между движками: pandas читает через read(), а
polars отображает файл в память, и его системные вызовы почти ничего не
показывают — 23 КБ против трёх мегабайт на одной и той же работе. Число
было настоящим и означало у двух плеч разное.

Отключить отображение у ленивого плеча нельзя: `scan_parquet` такого
параметра не имеет. Передать вместо пути свой считающий файловый объект
тоже не выход — тогда polars перестаёт делать проброс, то есть ломается
ровно то, что мы измеряем.

Поэтому мера сменилась с «сколько прочитано» на «а можно ли было
прочитать». Данные лежат разделами, и разделы, которые запрос обязан
отбросить, делаются ФИЗИЧЕСКИ НЕЧИТАЕМЫМИ. Движок, который их не тронул,
доходит до ответа; движок, который полез читать всё, падает с отказом в
доступе. Это целое «да/нет», одинаково устроенное для обоих движков и не
зависящее ни от способа чтения, ни от страничного кэша.

ЧТО В ДАННЫХ.

    day_bucket     раздел, 0..19 — по нему идёт отбор
    day            int64 внутри раздела
    category       строка малой мощности, по ней группировка
    amount_cents   int64 — деньги в копейках

ДЕНЬГИ ЦЕЛЫЕ, И ЭТО НЕ МЕЛОЧЬ. Суммы с плавающей точкой два движка сложат
в разном порядке и получат разные последние биты — проверка равенства
результата падала бы на арифметике, а не по существу.

ГЕНЕРАТОР БЕЗ СЛУЧАЙНОСТИ: значения выводятся из номера строки
арифметикой, поэтому набор побайтово одинаков при каждом запуске.
"""

import hashlib
import os
import shutil
import sys
from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq

ROWS = int(os.environ.get("ROWS", "200000"))
BUCKETS = int(os.environ.get("BUCKETS", "20"))
CATEGORIES = ("книги", "музыка", "кино", "игры")
# Запрос берёт РАННИЕ разделы, а поздние обязан отбросить — их и делают
# нечитаемыми.
#
# ПОЧЕМУ ИМЕННО РАННИЕ, А НЕ ПОЗДНИЕ. Первая версия отбирала поздние и
# закрывала ранние — и падали все пять плеч, включая те, что умеют
# отбрасывать. Причина в порядке действий: схему набора движок выводит по
# ПЕРВОМУ найденному файлу, до всякого отбора. Первым же оказывался
# закрытый раздел, и до проброса дело не доходило.
#
# Это не изъян движков, а свойство любого набора без объявленной схемы:
# чтобы узнать, какие есть столбцы, надо открыть хотя бы один файл.
BUCKET_TO = int(os.environ.get("BUCKET_TO", "5"))


def rows_for(bucket: int):
    """Строки одного раздела. Никакой случайности: только арифметика."""
    size = ROWS // BUCKETS
    start = bucket * size
    day = [bucket * 10 + (i % 10) for i in range(start, start + size)]
    category = [CATEGORIES[i % len(CATEGORIES)] for i in range(start,
                                                               start + size)]
    amount = [100 + (i * 37) % 9900 for i in range(start, start + size)]
    payload = ["".join(chr(0x430 + (i + shift) % 32) for shift in range(48))
               for i in range(start, start + size)]
    return pa.table({
        "day": pa.array(day, pa.int64()),
        "category": pa.array(category, pa.string()),
        "amount_cents": pa.array(amount, pa.int64()),
        # Ненужный запросу столбец: без него нечего было бы не читать.
        "payload": pa.array(payload, pa.string()),
    })


def main_into(root) -> str:
    """Пишет набор и возвращает его хеш.

    Хеш идёт в фикстуру как часть условий: набор порождается арифметикой
    без случайности, поэтому он обязан совпадать от прогона к прогону, и
    расхождение означало бы, что сравниваются разные данные.
    """
    root = Path(root)
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)

    digest = hashlib.sha256()
    for bucket in range(BUCKETS):
        part = root / f"day_bucket={bucket}"
        part.mkdir()
        target = part / "part.parquet"
        # Сжатие выключено: со сжатием размеры зависели бы ещё и от того,
        # как хорошо сжались именно эти байты.
        pq.write_table(rows_for(bucket), target, compression="none")
        digest.update(target.read_bytes())

    total = sum(f.stat().st_size for f in root.rglob("*.parquet"))
    value = digest.hexdigest()[:16]
    print(f"разделов {BUCKETS}, строк {ROWS}, размер {total} Б, "
          f"хеш набора {value}", file=sys.stderr)
    print(f"запрос берёт разделы до {BUCKET_TO}: "
          f"{BUCKET_TO} из {BUCKETS}", file=sys.stderr)
    return value


def main():
    main_into(os.environ.get("DATASET", "/fixtures/sales"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
