#!/bin/sh
# Измеритель версии fmt: читает FMT_VERSION из ЗАГОЛОВКОВ УСТАНОВЛЕННОГО
# пакета, одинаково для всех плеч оси.
#
# ПОЧЕМУ НЕ ИЗ МАНИФЕСТА. Раньше плечо conan доставало версию `sed`-ом из
# service/conanfile.txt — из файла, который написал автор стенда. Такое
# «измерение» вернуло бы 11.0.2 и при полностью сломанном разрешении
# зависимости, а проверка «у vcpkg и conan одна версия» сравнивала бы
# измеренное число с объявленным и была бы наполовину тавтологией.
# Здесь версия берётся из того, что реально легло на диск.
#
# ПОЧЕМУ ТРЕБУЕТСЯ РОВНО ОДНО ЗНАЧЕНИЕ. Если под корнем нашлось два
# разных FMT_VERSION, измеритель не знает, какой из них принадлежит
# сборке, и обязан упасть, а не выбрать первый попавшийся: молча
# выбранное число выглядело бы измерением ровно так же, как верное.
#
# Запускается через `sh`, а не по exec-биту: бит выполнения не переживает
# путешествие файла через файловую систему Windows, и Dockerfile,
# зависящий от него, ломался бы через раз.
set -eu

root="$1"
out="$2"

values=$(find "$root" -type f -path '*/include/fmt/*.h' \
           -exec sed -n 's/^#define FMT_VERSION \([0-9][0-9]*\).*/\1/p' {} + \
         | sort -u)
count=$(printf '%s\n' "$values" | grep -c '^[0-9]' || true)

if [ "$count" != "1" ]; then
    echo "fmt-version: под $root найдено $count различных значений" \
         "FMT_VERSION [$(printf '%s' "$values" | tr '\n' ' ')] —" \
         "измерить версию нечем" >&2
    exit 3
fi

printf '%s\n' "$values" > "$out"
echo "FMT_VERSION_MEASURED=$values"
