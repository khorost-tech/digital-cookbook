"""Вывод в UTF-8 независимо от кодовой страницы консоли.

ЗАЧЕМ ЭТО ЕСТЬ. Найдено вторым прогоном — на хосте Windows, где консоль
живёт в cp1251. Все четыре оси там сняты успешно, а `analyze-repro.py`
упал на печати: знак «≠» в cp1251 не существует, и Python свалился с
UnicodeEncodeError. Сводный прогон честно остановился на шаге разбора и
не поставил маркер.

Дефект не в знаке. Знак можно было бы заменить словом, и разбор ожил бы
до следующего такого символа: стенд печатает по-русски и вставляет «×»,
«→», «≠» там, где они уместны. Чинить надо поток, а не текст.

Поэтому каждый печатающий скрипт стенда переключает свои потоки в UTF-8
первым делом. Проверка `test_console_encoding.py` следит, чтобы ни один
не забыл, а диверсия `console-utf8-not-forced` её роняет.
"""

import sys


def force_utf8():
    """Переключает stdout и stderr в UTF-8, если поток это умеет.

    Молчаливый пропуск здесь уместен: поток, перенаправленный в файл или
    в конвейер, может не поддерживать reconfigure, и это не повод
    ронять прогон. Ошибка кодировки, которую этот вызов предотвращает,
    возникает только у консоли.
    """
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:
            continue
        try:
            reconfigure(encoding="utf-8")
        except (ValueError, OSError):
            pass
