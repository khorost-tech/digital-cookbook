"""Разбор перехваченного вывода компоновщика.

ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО ЗДЕСЬ НЕТ.

Здесь нет ни одной строки, объявляющей, ЧТО компоновщик печатает.
Печатает он то, что печатает; сюда приходит перехваченный поток ошибок
процесса линковки (scripts/docker.py:relink_stderr), и всё, что делает
этот модуль, — находит в нём строки и приводит их к сравнимому виду.

ПРИЗНАК ПРИСУТСТВИЯ. Признаком служит подстрока `MARKER` — она короче
самого предупреждения и не содержит ни имени функции, ни версии
библиотеки: если бы признак совпадал со всей строкой целиком, он ловил
бы РОВНО ту редакцию текста, которую автор однажды видел, и молчал бы о
любой другой. Признак записывается в фикстуру рядом с сырым выводом,
чтобы читатель видел, ЧТО именно сопоставлялось, а не верил на слово.

НОРМАЛИЗАЦИЯ, КОТОРАЯ НЕ СЪЕДАЕТ СУТЬ. Строка предупреждения содержит
смещение в секции (`main.cpp:(.text.startup+0x444)`): у двух плеч пары
оно разное, потому что код лежит по разным адресам, и сравнение строк
целиком развело бы плечи там, где предупреждение одинаково. Заменяется
РОВНО смещение и ничего больше — сам текст предупреждения остаётся как
есть. Сырой вывод при этом никуда не девается: он тоже идёт в фикстуру,
и по нему нормализацию можно перепроверить.
"""

import re

# Признак предупреждения о статической линковке с glibc. Сопоставляется
# с ПЕРЕХВАЧЕННЫМ выводом, а не с ожидаемым.
MARKER = "requires at runtime the shared libraries"

# Улика того, что линковка действительно шла. Без неё пустой stderr
# означал бы «линковать было нечего», а не «предупреждения нет».
LINK_STEP_MARKER = "Linking CXX executable"

# Что именно заменяется при нормализации — и это единственная замена.
OFFSET = re.compile(r"\+0x[0-9a-fA-F]+")
OFFSET_PLACEHOLDER = "+0x<смещение>"
NORMALIZATION = ("заменено только шестнадцатеричное смещение в секции: "
                 "%s -> %r" % (OFFSET.pattern, OFFSET_PLACEHOLDER))


def normalize(text):
    """Смещение в секции заменяется плейсхолдером. Больше ничего."""
    return OFFSET.sub(OFFSET_PLACEHOLDER, text)


def warning_lines(stderr):
    """Строки перехваченного stderr, несущие признак предупреждения.

    Возвращаются НОРМАЛИЗОВАННЫМИ и без ведущего имени компоновщика:
    GNU ld печатает предупреждение двумя строками, и признак стоит во
    второй. Первая (`/usr/bin/ld: ...o: in function 'main':`) остаётся в
    сыром выводе — она про место, а не про само предупреждение.
    """
    return [normalize(line.strip())
            for line in stderr.splitlines() if MARKER in line]


def has_warning(stderr):
    """Признак присутствия. Читается из вещества, а не из объявления."""
    return bool(warning_lines(stderr))


def link_step_ran(stdout):
    """Была ли линковка вообще."""
    return LINK_STEP_MARKER in stdout
