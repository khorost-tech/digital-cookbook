#!/usr/bin/env bash
# Сводный прогон стенда: с нуля до маркера завершения.
#
# МАРКЕР СТАВИТСЯ ТОЛЬКО ПОСЛЕ ВСЕГО.
#
# Оборванный прогон не должен выглядеть как полный — просто с меньшим
# числом строк. Поэтому маркер пишется последним и только если прошли все
# четыре оси (у первой два замера: упаковка и вывод компоновщика), все
# четыре разбора, сводка прогона И весь набор проверок.
#
# ПОЧЕМУ КОД ВОЗВРАТА ПРОВЕРЯЕТСЯ ПОСЛЕ КАЖДОГО ШАГА.
#
# Конвейер глотает код возврата: `bash run-all.sh | grep ...` вернёт код
# grep, и прогон, отбитый на середине, дважды выглядел бы успешным. Этот
# дефект на стенде уже случался — разбор шёл по стухшей фикстуре. Поэтому
# код каждого шага снимается отдельно и прогон немедленно
# останавливается.
#
# СКОЛЬКО ЭТО ИДЁТ. Порядка получаса: 7 сборок оси сборки в двух
# прогонах, 24 сборки оси воспроизводимости, 12 сборок оси соседей,
# 6 образов упаковки, 66 холодных запусков контейнера и 5 перезапусков
# шага линковки.
set -uo pipefail

# Каталог стенда: без -e неудачный cd не остановил бы прогон, и все
# дальнейшие шаги пошли бы из чужого каталога — по чужим фикстурам.
STAND_DIR="$(dirname "${BASH_SOURCE[0]}")/.."
if ! cd "$STAND_DIR"; then
    echo "НЕ УДАЛОСЬ ПЕРЕЙТИ В КАТАЛОГ СТЕНДА: $STAND_DIR" >&2
    exit 2
fi
if [ ! -f "scripts/run-manifest.py" ]; then
    echo "ЭТО НЕ КАТАЛОГ СТЕНДА: $(pwd) — нет scripts/run-manifest.py" >&2
    exit 2
fi

# Маркер снимается ПЕРВЫМ делом: пока прогон идёт, его нет, и это видно.
MARKER="fixtures/RUN-COMPLETE"
rm -f "$MARKER"

# --- предполётная проверка -------------------------------------------
#
# Хостовые зависимости объявляются и проверяются ДО первой сборки. Своё
# окружение, выданное за свойство стенда, — ровно та болезнь, против
# которой стенд и построен: прогон, падающий на середине у читателя,
# у автора «проходил целиком».
need() {
    command -v "$1" >/dev/null 2>&1 && return 0
    echo "НЕТ ЗАВИСИМОСТИ: $1 — $2" >&2
    return 1
}

missing=0
need docker "все сборки и все пробы идут в контейнерах" || missing=1

# Толкователь Python зовётся по-разному. Жёстко записанное «python» там,
# где есть только python3, роняет прогон на первом же шаге.
PY=""
for candidate in python3 python; do
    if command -v "$candidate" >/dev/null 2>&1; then PY="$candidate"; break; fi
done
if [ -z "$PY" ]; then
    echo "НЕТ ЗАВИСИМОСТИ: python3 — на нём написаны прогоны и разборы" >&2
    missing=1
elif ! "$PY" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 8) else 1)'; then
    echo "СТАРЫЙ PYTHON: нужен 3.8 или новее, найден $("$PY" -V 2>&1)" >&2
    missing=1
fi

# Наличие клиента docker ещё не значит, что демон отвечает. Проверка
# отдельная: иначе первая же сборка упала бы сообщением про сокет, и
# читатель искал бы дефект в стенде.
if [ "$missing" -eq 0 ] && ! docker info >/dev/null 2>&1; then
    echo "DOCKER НЕ ОТВЕЧАЕТ: клиент есть, демон недоступен" >&2
    missing=1
fi

if [ "$missing" -ne 0 ]; then
    echo >&2
    echo "Прогон не начат: не хватает хостовых зависимостей." >&2
    echo "Нужны docker с работающим демоном и python 3.8+;" >&2
    echo "компилятор, cmake, vcpkg, Conan, Go и Rust приезжают образами." >&2
    exit 2
fi
echo "зависимости на месте: docker, $PY ($("$PY" -V 2>&1))"

# Вывод — в UTF-8, даже если консоль живёт в другой кодовой странице.
# Найдено прогоном на втором хосте: на консоли cp1251 разбор упал на
# печати знака «не равно». Сами скрипты переключают свои потоки сами
# (scripts/console.py), но набор проверок печатает сообщения устами
# unittest, и ему нужна эта переменная.
export PYTHONIOENCODING=utf-8


step() {
    title="$1"; shift
    printf '\n=== %s\n' "$title"
    "$@"
    rc=$?
    if [ $rc -ne 0 ]; then
        printf '\nПРОГОН ОСТАНОВЛЕН на шаге «%s» (код %d).\n' "$title" $rc
        printf 'Маркер завершения не поставлен — фикстуры неполны.\n'
        exit $rc
    fi
}

# Оси, снимаемые дважды, снимаются дважды ЗДЕСЬ. Пара прогонов — это не
# усреднение, а проверка устойчивости: расхождение между прогонами и есть
# находка. Прогоны одной оси обязаны быть из одной сессии, иначе пара
# сравнивала бы разные состояния машины.
step "ось 1: упаковка"                   "$PY" scripts/run-package.py
step "ось 1: предупреждение компоновщика" "$PY" scripts/run-link.py
step "ось 2: сборка, прогон 1"           "$PY" scripts/run-build.py build.run-1.jsonl
step "ось 2: сборка, прогон 2"           "$PY" scripts/run-build.py build.jsonl
step "ось 3: воспроизводимость, прогон 1" "$PY" scripts/run-repro.py repro.run-1.jsonl
step "ось 3: воспроизводимость, прогон 2" "$PY" scripts/run-repro.py repro.jsonl
step "ось 4: соседи, прогон 1"           "$PY" scripts/run-siblings.py siblings.run-1.jsonl
step "ось 4: соседи, прогон 2"           "$PY" scripts/run-siblings.py siblings.jsonl

# Свидетельство по сессиям пересобирается ЗДЕСЬ, до разборов и до
# проверок. Оно строится из истории коммитов фикстур, а не из текущего
# рабочего дерева, поэтому свежий прогон в него попасть и не может — в
# нём лежат ПРОШЛЫЕ сессии. Но последний КОММИТ фикстур в нём быть
# обязан, иначе проверка свежести красная.
#
# Без этого шага получалась петля: прогон ставил маркер, фикстуры
# коммитились, и следующий прогон падал на проверке свежести, потому что
# свежий коммит в свидетельство никто не внёс. Лечилось ручным запуском
# run-evidence.py, о котором надо было помнить, — то есть не лечилось.
# Разборы читают свидетельство (analyze-build печатает разброс по
# сессиям), поэтому шаг стоит перед ними, а не перед одними проверками.
step "свидетельство по сессиям"  "$PY" scripts/run-evidence.py

step "разбор: упаковка"          "$PY" scripts/analyze-package.py
step "разбор: сборка"            "$PY" scripts/analyze-build.py
step "разбор: воспроизводимость" "$PY" scripts/analyze-repro.py
step "разбор: соседи"            "$PY" scripts/analyze-siblings.py

# Сводка снимается ДО проверок: они же её и сверяют со сводками других
# платформ.
step "сводка прогона"            "$PY" scripts/run-manifest.py

step "весь набор проверок"       "$PY" -m unittest discover -s scripts -p 'test_*.py' -t .

# Маркер держит СОСТОЯНИЕ, при котором прогон объявлен полным: суммы
# фикстур, число проверок, число диверсий. Строка времени протухала бы
# молча — её никто не сверял, и она пережила рост набора на пятнадцать
# проверок.
step "маркер полного прогона" "$PY" scripts/run-marker.py
printf '\nПРОГОН ЗАВЕРШЁН ПОЛНОСТЬЮ. Маркер: %s\n' "$MARKER"
