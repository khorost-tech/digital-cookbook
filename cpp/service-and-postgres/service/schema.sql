-- Схема стенда. Таблиц здесь нет намеренно: pg_sleep их не требует, а
-- любая таблица добавила бы в замер переменные, к осям не относящиеся.
--
-- Файл делает ровно три вещи:
--   1) создаёт роль, под которой сервис подключается;
--   2) включает загрузку pg_stat_statements;
--   3) создаёт расширение.
-- Без расширения ось 3 не сможет считать вызовы запроса.
--
-- Пароль роли лежит в открытом виде осознанно: это изолированный
-- измерительный стенд, поднимаемый на время прогона и уничтожаемый после
-- него. Ни одного чужого данного в этой базе нет.

CREATE ROLE stand LOGIN PASSWORD 'stand';
CREATE DATABASE stand OWNER stand;

-- shared_preload_libraries задаётся и здесь, и параметром запуска
-- контейнера. ПОЧЕМУ ДВАЖДЫ: ALTER SYSTEM записывает значение в
-- postgresql.auto.conf, но применяется оно только после перезапуска, а
-- первый прогон может случиться раньше. Параметр запуска действует сразу;
-- запись здесь оставлена, чтобы база, поднятая без него вручную, вела
-- себя так же.
ALTER SYSTEM SET shared_preload_libraries = 'pg_stat_statements';

\connect stand

CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

-- Право читать статистику отдано роли стенда: разбор ходит в
-- pg_stat_activity, pg_prepared_statements и pg_stat_statements под ней
-- же, а не под суперпользователем.
GRANT pg_read_all_stats TO stand;
