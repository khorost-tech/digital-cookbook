// две подмены подряд: тавтологию в сверке имён и дописанное `|| true` в
// этой самой классификации. Вынесенное решение можно ВЫЗВАТЬ с
// произвольным кодом и потребовать ответа — это и делает
// `service/behaviour_probe.cpp`.
bool is_resource_refusal(const std::string& sqlstate);
