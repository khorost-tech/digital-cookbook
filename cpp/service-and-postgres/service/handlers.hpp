#pragma once
#include <string>

// Ответ ручки: тело и код. Слой HTTP только доставляет их.
struct Reply { int status; std::string body; };

// /healthz — без похода в базу. Контроль живости: отличает
// «сервер занят» от «сервер умер».
// Занятость ОН СООБЩАЕТ САМ, и себя при этом не считает: счётчик
// спрашивают именно этим маршрутом, и наблюдатель, попавший в
// наблюдаемое, завышал бы ответ на единицу.
Reply healthz();

// /q?sleep_ms=N — параметризованный запрос, ожидание уходит В БАЗУ.
Reply query(int sleep_ms, const std::string& variant, int inflight);

// /block?ms=N — спит В САМОМ ОБРАБОТЧИКЕ, занимая рабочую единицу.
Reply block(int ms, const std::string& variant, int inflight);

// СЧЁТЧИК ОБРАБОТЧИКОВ В ПОЛЁТЕ — то, чем занятость ЧИТАЕТСЯ.
//
// ЗАЧЕМ ОН ЗАВЁЛСЯ. Прежняя редакция стенда ВЫВОДИЛА занятость из
// длительностей ответов: ответы делились на «волны», и чтобы отличить
// волну от дрожания машины, ожидание растянули до пятнадцати секунд. Так
// стенд мерил машину, а не варианты. Спека оси 1 отсчёта по времени не
// просила ни разу: она просит ПОСЧИТАТЬ — сколько обработчиков внутри
// разом. Счётчик растёт на входе, падает на выходе, и его значение на
// момент входа уходит в контрактную строку ответа. После этого дрожание
// перестаёт значить что-либо: ответ может прийти хоть через восемь
// секунд, число внутри всё равно прочитано.
//
// РИСК НАЗВАН ЗАРАНЕЕ. Это измеряющий код ВНУТРИ предмета, то есть слепой
// заодно с ним. Поэтому у него два контроля снаружи, в обвязке замера:
// положительный — счётчик обязан идти за числом рабочих единиц при
// прочем равном; отрицательный — в постановке с непересекающимися
// пробами он обязан читаться единицей. Плюс второй, независимый
// источник: счёт активных запросов варианта в самой базе. Без контролей
// ось недействительна.
int inflight_now();

// Сторож входа: пока он жив, обработчик числится в полёте.
//
// ПОЧЕМУ RAII, А НЕ ПАРА ВЫЗОВОВ. Обработчик умеет выйти исключением —
// отказ базы, кривой параметр, — и счётчик, уменьшаемый последней
// строкой тела, в этом случае не уменьшился бы. Счётчик, не убывающий на
// выходе, растёт сам по себе, и занятость читалась бы всё больше и
// больше. Обвязка замера ловит это отдельно: занятость ДО залпа обязана
// читаться нулём.
class InFlight {
  public:
    InFlight();
    ~InFlight();
    InFlight(const InFlight&) = delete;
    InFlight& operator=(const InFlight&) = delete;

    // Значение счётчика на момент входа, СЧИТАЯ этот обработчик.
    int entered_with() const { return entered_; }

  private:
    int entered_;
};

// Имя варианта из переменной окружения STAND_VARIANT.
//
// ПОЧЕМУ ЭТО ФУНКЦИЯ, А НЕ КОНСТАНТА. Образ у трёх вариантов общий, имя
// приходит при ЗАПУСКЕ. Запечённое в образ значение склеило бы два
// варианта в одну строку фикстуры — и прогон при этом выглядел бы
// успешным. Незаданное или пустое имя обязано ронять процесс, а не
// подставлять запасное: строка фикстуры без имени варианта не относится
// ни к одному из вариантов.
//
// СЛОЙ ОБЯЗАН ПОЗВАТЬ ЭТУ ФУНКЦИЮ В main() ДО ОТКРЫТИЯ ПОРТА и передать
// полученное значение во все ручки. Читать имя лениво, при первом
// запросе, нельзя: ошибка настройки выглядела бы тогда как молчащий
// сервер, а ось 1 меряет ровно различие «занят / умер» и прочла бы
// испорченную настройку как отсутствие живости. Падение до открытия
// порта не спутать ни с чем: порт закрыт, и клиент видит это сразу.
//
// Бросает std::runtime_error, если переменная не задана или пуста.
const std::string& stand_variant();

// Размер пула соединений из переменной окружения STAND_POOL.
//
// ЗАЧЕМ ЭТА РУЧКА ВООБЩЕ ЕСТЬ. Ось 2 считает, сколько соединений драйвер
// открыл на самом деле, и контролем ей служит ПАРА по размеру пула: пул
// на 1 против пула на 8, всё остальное одинаково. Счётчик обязан пойти
// за настройкой — не пошёл, значит меряется не пул. Настройка, которую
// нельзя изменить при запуске, контролем быть не может.
//
// ПОЧЕМУ ПРИ ЗАПУСКЕ, А НЕ ПРИ СБОРКЕ, И ПОЧЕМУ БЕЗ ЗАПАСНОГО ЗНАЧЕНИЯ.
// Образ у трёх вариантов общий. Запечённая величина склеила бы два
// прогона оси 2 в одну строку фикстуры, и контроль сравнивал бы пул сам
// с собой — причём прогон при этом выглядел бы успешным. Незаданное или
// пустое значение обязано ронять процесс, а не подставлять запасное: то
// же правило, что у имени варианта и числа рабочих единиц.
//
// СЛОЙ ОБЯЗАН ПОЗВАТЬ ЭТУ ФУНКЦИЮ В main() ДО ОТКРЫТИЯ ПОРТА. Пул
// создаётся лениво, при первом походе в базу; читай он размер там же,
// ошибка настройки приехала бы отказом ОДНОГО запроса и выглядела бы
// отказом базы, а не испорченным запуском.
//
// Бросает std::runtime_error, если переменная не задана, пуста или не
// является положительным целым.
int stand_pool_size();

// Отказала ли БАЗА, а не наша проба, при данном коде SQLSTATE.
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ УСЛОВИЕ ВНУТРИ ОБРАБОТЧИКА. Решение
// «отказ общего ресурса или наша поломка» — то самое, что отделяет
