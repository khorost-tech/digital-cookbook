// Разбор запроса и выбор ручки — ОБЩИЕ для трёх слоёв.
//
// ПОЧЕМУ ЭТО НЕ В ТОЧКАХ ВХОДА. Различаться обязан только слой HTTP. Три
// собственных разбора строки запроса — это три места, где варианты могут
// разойтись молча: один слой прочитал бы `sleep_ms=5` как 5, другой при
// опечатке подставил бы ноль, и ось мерила бы разницу разборов, выдавая
// её за разницу моделей. Поэтому слою оставлено ровно его дело: принять
// соединение, отдать строку запроса сюда и записать полученный ответ.
//
// Цель — строка запроса как её увидел слой, вместе с параметрами:
// "/healthz", "/q?sleep_ms=200", "/block?ms=200".
Reply dispatch(const std::string& target, const std::string& variant);

// Число рабочих единиц из переменной окружения STAND_WORKERS.
//
// ПОЧЕМУ ОНО ЗАДАЁТСЯ ЯВНО. У Drogon это число циклов событий, у Crow —
// размер пула потоков, у Beast — число потоков, крутящих io_context, и
// ДЕФОЛТЫ У ТРЁХ БИБЛИОТЕК РАЗНЫЕ. Без явной фиксации оси 1 и 2 мерили бы
// настройку, а не модель: расхождение объяснялось бы двумя причинами
// сразу, и различить их было бы нечем.
//
// ПОЧЕМУ ПРИ ЗАПУСКЕ, А НЕ ПРИ СБОРКЕ. Образ у трёх вариантов общий;
// запечённое в него значение склеило бы прогоны с разными настройками в
// одну строку фикстуры — и прогон при этом выглядел бы успешным.
//
// Как и имя варианта, запасного значения не имеет: бросает
// std::runtime_error, если переменная не задана, пуста или не является
// положительным целым. Слой обязан позвать эту функцию ДО ОТКРЫТИЯ ПОРТА.
int stand_workers();
