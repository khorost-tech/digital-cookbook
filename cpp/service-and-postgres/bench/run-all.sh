#!/usr/bin/env bash
# Сводный прогон стенда: с нуля до маркера завершения.
#
# МАРКЕР СТАВИТСЯ ТОЛЬКО ПОСЛЕ ВСЕГО.
#
# Оборванный прогон не должен выглядеть как полный — просто с меньшим
# числом строк в одной из пяти фикстур. Поэтому маркер пишется последним
# и только если прошли все четыре оси (у первой две фикстуры: занятость
# по настройкам и ожидание в базе), все разборы, сводка прогона И весь
# набор проверок.
#
# ПОЧЕМУ КОД ВОЗВРАТА СНИМАЕТСЯ ПОСЛЕ КАЖДОГО ШАГА. Конвейер глотает код
# возврата: `bash run-all.sh | tee log` вернёт код tee, и прогон,
# отбитый на середине, выглядел бы успешным — а разбор пошёл бы по
# стухшей фикстуре. Эта болезнь у соседнего стенда уже случалась.
#
# СКОЛЬКО ЭТО ИДЁТ. Около получаса: три образа вариантов собираются
# заново, база поднимается на каждой оси своя, ось 1 идёт залпами по трём
# настройкам, ось 2 — по двум размерам пула в трёх залпах, оси 3 и 4
# короткие. Набор проверок без докера — ещё около двух с половиной минут.
set -uo pipefail

# Каталог стенда: без проверки неудачный cd не остановил бы прогон, и
# дальнейшие шаги пошли бы по чужим фикстурам.
STAND_DIR="$(dirname "${BASH_SOURCE[0]}")/.."
if ! cd "$STAND_DIR"; then
    echo "НЕ УДАЛОСЬ ПЕРЕЙТИ В КАТАЛОГ СТЕНДА: $STAND_DIR" >&2
    exit 2
fi
if [ ! -f "scripts/run-manifest.py" ]; then
    echo "ЭТО НЕ КАТАЛОГ СТЕНДА: $(pwd) — нет scripts/run-manifest.py" >&2
    exit 2
fi

# Маркер снимается ПЕРВЫМ делом: пока прогон идёт, его нет, и это видно.
MARKER="fixtures/RUN-COMPLETE"
rm -f "$MARKER"

# --- предполётная проверка -------------------------------------------
#
# Хостовые зависимости объявляются и проверяются ДО первого замера. Своё
# окружение, выданное за свойство стенда, — ровно та болезнь, против
# которой стенд и построен: прогон, падающий на середине у читателя, у
# автора «проходил целиком».
missing=0
if ! command -v docker >/dev/null 2>&1; then
    echo "НЕТ ЗАВИСИМОСТИ: docker — все сборки и все замеры идут в контейнерах" >&2
    missing=1
fi

# Толкователь Python зовётся по-разному. Жёстко записанное «python» там,
# где есть только python3, роняет прогон на первом же шаге.
PY=""
for candidate in python3 python; do
    if command -v "$candidate" >/dev/null 2>&1; then PY="$candidate"; break; fi
done
if [ -z "$PY" ]; then
    echo "НЕТ ЗАВИСИМОСТИ: python3 — на нём написаны замеры и разборы" >&2
    missing=1
elif ! "$PY" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 8) else 1)'; then
    echo "СТАРЫЙ PYTHON: нужен 3.8 или новее, найден $("$PY" -V 2>&1)" >&2
    missing=1
fi

# Наличие клиента docker ещё не значит, что демон отвечает. Проверка
# отдельная: иначе первая же сборка упала бы сообщением про сокет, и
# читатель искал бы дефект в стенде.
if [ "$missing" -eq 0 ] && ! docker info >/dev/null 2>&1; then
    echo "DOCKER НЕ ОТВЕЧАЕТ: клиент есть, демон недоступен" >&2
    missing=1
fi

if [ "$missing" -ne 0 ]; then
    echo >&2
    echo "Прогон не начат: не хватает хостовых зависимостей." >&2
    echo "Нужны docker с работающим демоном и python 3.8+; компилятор," >&2
    echo "libpqxx и PostgreSQL приезжают образами." >&2
    exit 2
fi
echo "зависимости на месте: docker, $PY ($("$PY" -V 2>&1))"

# Вывод — в UTF-8, даже если консоль живёт в другой кодовой странице.
# Скрипты переключают свои потоки сами (scripts/console.py), но набор
# проверок печатает сообщения устами unittest, и ему нужна переменная.
export PYTHONIOENCODING=utf-8

step() {
    title="$1"; shift
    printf '\n=== %s\n' "$title"
    "$@"
    rc=$?
    if [ $rc -ne 0 ]; then
        printf '\nПРОГОН ОСТАНОВЛЕН на шаге «%s» (код %d).\n' "$title" $rc
        printf 'Маркер завершения не поставлен — фикстуры неполны.\n'
        exit $rc
    fi
}

# Порядок осей не произволен: ось 1 снимает сумму точки входа, а ось
# ожидания в базе сверяет с ней свою — снятая раньше, она сверялась бы с
# прошлой сборкой.
step "ось 1: занятость по настройкам" "$PY" scripts/run-variants.py
step "ось 1: ожидание в базе"         "$PY" scripts/run-db-wait.py
step "ось 2: соединения по размеру пула" "$PY" scripts/run-pool.py
step "ось 3: параметр против литерала"   "$PY" scripts/run-prepared.py
step "ось 4: обрыв клиента"              "$PY" scripts/run-cancel.py

step "разбор: соединения"  "$PY" scripts/analyze-pool.py
step "разбор: подготовка"  "$PY" scripts/analyze-prepared.py
step "разбор: обрыв"       "$PY" scripts/analyze-cancel.py

# Сводка снимается ДО проверок: они же её и сверяют со сводкой прошлой
# сессии. Имя `current` переписывается каждым прогоном намеренно —
# замороженная сводка прошлой сессии лежит рядом под своим именем.
step "сводка прогона" "$PY" scripts/run-manifest.py --session current

step "весь набор проверок" "$PY" -m unittest discover -s scripts -p 'test_*.py' -t .

# Маркер держит СОСТОЯНИЕ, при котором прогон объявлен полным: суммы
# пяти фикстур, число проверок, число диверсий.
step "маркер полного прогона" "$PY" scripts/run-marker.py
printf '\nПРОГОН ЗАВЕРШЁН ПОЛНОСТЬЮ. Маркер: %s\n' "$MARKER"
