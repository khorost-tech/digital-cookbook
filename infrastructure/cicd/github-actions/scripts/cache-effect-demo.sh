#!/usr/bin/env bash
# Раздел github-actions: эффект кэша зависимостей, замеренный локально.
#
# В CI actions/cache восстанавливает GOMODCACHE (скачанные модули) и GOCACHE
# (результаты компиляции) между прогонами. Здесь тот же механизм воспроизводится
# без облака: собираем один и тот же проект с холодным кэшем, потом с тёплым, и
# сравниваем время. Показываем три точки:
#   1. холодный кэш   — качаем модули и компилируем всё с нуля;
#   2. тёплый кэш      — ничего не изменилось, всё берётся из кэша;
#   3. правка исходника — GOCACHE своего пакета инвалидирован, но GOMODCACHE
#      зависимостей переиспользуется: пересборка дешевле холодной, дороже тёплой.
#
# ⚠️ Это не тайминги job'ов в GitHub Actions (их локально честно не воспроизвести).
# Переносим ХАРАКТЕР: тёплый кэш кратно дешевле холодного; правка кода не роняет
# кэш зависимостей. Абсолютные секунды host-зависимы.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/../app"

command -v go >/dev/null 2>&1 || { echo "ОШИБКА: go не найден в PATH." >&2; exit 1; }

export GOPROXY="${GOPROXY:-https://go.khorost.tech,direct}"
export GOSUMDB=off        # модуль уже зафиксирован в go.sum; внешний sumdb не дёргаем
export GOTOOLCHAIN=local

# Отдельные временные каталоги кэша — чтобы «холодный» был честно пустым и не
# зависел от кэша разработчика в $HOME.
TMP="$(mktemp -d)"
export GOCACHE="$TMP/gocache"
export GOMODCACHE="$TMP/gomodcache"

# main.go правится в шаге 3; восстанавливаем его при любом выходе.
SRC="main.go"
SRC_BAK="$(mktemp)"
cp "$SRC" "$SRC_BAK"
cleanup() {
    cp "$SRC_BAK" "$SRC"; rm -f "$SRC_BAK"
    chmod -R u+w "$TMP" 2>/dev/null || true   # GOMODCACHE кладёт read-only файлы
    rm -rf "$TMP"
}
trap cleanup EXIT

# Замер времени команды. Считаем через date +%s.%N (реальное прошедшее), а не
# по номинальной константе — тот же принцип, что в throughput-замерах: делитель/
# интервал должен быть настоящим, иначе подтормаживание оснастки исказит число.
measure() {
    local start end
    start=$(date +%s.%N)
    "$@" >/dev/null 2>&1
    end=$(date +%s.%N)
    awk "BEGIN{printf \"%.3f\", $end-$start}"
}

echo "=== Эффект кэша зависимостей (go build ./...) ==="
echo "GOCACHE и GOMODCACHE — во временных каталогах, холодный старт честно пуст."
echo

echo "--- (1) ХОЛОДНЫЙ кэш: качаем модули + компилируем всё с нуля ---"
T_COLD=$(measure go build ./...)
echo "время: ${T_COLD} с"

echo "--- (2) ТЁПЛЫЙ кэш: без изменений, всё из кэша ---"
T_WARM=$(measure go build ./...)
echo "время: ${T_WARM} с"

echo "--- (3) Правка исходника: GOCACHE пакета инвалидирован, GOMODCACHE цел ---"
# Меняем СОДЕРЖИМОЕ (go кэширует по хешу содержимого, не по mtime).
printf '\n// cache-bust %s\n' "$RANDOM$RANDOM" >> "$SRC"
T_EDIT=$(measure go build ./...)
echo "время: ${T_EDIT} с"

echo
echo "=== СВОДКА ==="
awk -v c="$T_COLD" -v w="$T_WARM" -v e="$T_EDIT" 'BEGIN{
    printf "холодный:            %6.3f с\n", c
    printf "тёплый (без правок): %6.3f с  (x%.1f быстрее холодного)\n", w, c/w
    printf "после правки кода:   %6.3f с  (x%.1f быстрее холодного)\n", e, c/e
}'

echo
echo "ПАДАЮЩИЙ ВАРИАНТ / что проверяем: тёплая сборка должна быть заметно быстрее"
echo "холодной, а сборка после правки кода — быстрее холодной (зависимости взяты"
echo "из GOMODCACHE, качать заново не пришлось). Если тёплая НЕ быстрее холодной —"
echo "кэш не работает."

# Самопроверка: тёплый обязан быть быстрее холодного (иначе кэш не действует).
awk -v c="$T_COLD" -v w="$T_WARM" 'BEGIN{ exit !(c > w) }' || {
    echo "ОШИБКА: тёплая сборка не быстрее холодной — кэш не даёт эффекта." >&2
    exit 1
}
echo
echo "OK: тёплый кэш быстрее холодного."
