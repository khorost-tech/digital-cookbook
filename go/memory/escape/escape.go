// escape.go — escape-анализ на живых примерах: что остаётся на стеке,
// а что компилятор вынужден разместить в куче.
//
// Escape-анализ — это статический проход компилятора Go, который решает,
// переживёт ли значение вызов функции. Если ДА — значение «убегает» (escapes)
// в кучу, и его потом убирает сборщик мусора. Если НЕТ — значение живёт на
// стеке и исчезает бесплатно при возврате из функции.
//
// Ключевое правило: не «указатель = куча», а «переживает ли значение свой
// кадр стека». Локальный указатель, не покидающий функцию, остаётся на стеке.
//
// Что покажет `go build -gcflags=-m ./...` — расписано у каждой функции.
// Смотреть строки вида «does not escape», «escapes to heap», «moved to heap».
package escape

// Point — небольшой конкретный тип для демонстраций.
type Point struct {
	X, Y int
}

// leaked — пакетная переменная. Всё, на что она держит указатель, переживает
// любой вызов, поэтому такие значения обязаны уходить в кучу (см. leakViaSlice).
var leaked []*Point

// newOnStack берёт адрес локального значения, но НЕ выпускает его наружу:
// указатель используется и «умирает» внутри функции. Компилятор видит это и
// оставляет Point на стеке.
//
// -gcflags=-m: «&Point{...} does not escape».
func newOnStack() int {
	p := &Point{X: 1, Y: 2} // адрес не покидает функцию → стек
	return p.X + p.Y
}

// newOnHeap возвращает указатель на локальную переменную. Значение обязано
// пережить кадр вызывающего, поэтому его нельзя держать на стеке.
//
// -gcflags=-m: «moved to heap: p» (плюс «&p escapes to heap»).
func newOnHeap() *Point {
	p := Point{X: 1, Y: 2} // p переживает функцию через возвращённый адрес
	return &p
}

// boxIntoInterface кладёт значение в interface{} (any). Интерфейс хранит пару
// (тип, указатель на данные), поэтому значение-примитив приходится «упаковать»
// (boxing) — а упаковка требует размещения в куче.
//
// -gcflags=-m: «x escapes to heap».
func boxIntoInterface(x int) any {
	var v any = x // боксинг int в интерфейс → escape
	return v
}

// leakViaSlice сохраняет указатель на локальную переменную в пакетный срез,
// переживающий вызов. Раз ссылка «утекает» в долгоживущую структуру —
// значение уходит в кучу.
//
// -gcflags=-m: «moved to heap: p» (плюс «&p escapes to heap»).
func leakViaSlice() {
	p := Point{X: 1, Y: 2}      // p доживает дольше вызова через срез
	leaked = append(leaked, &p) // ссылка утекает в пакетную переменную
}

// stackArg принимает *Point, но только читает его — указатель никуда не
// сохраняется и не возвращается. Такой аргумент НЕ заставляет вызывающего
// размещать значение в куче: переданный адрес не «убегает».
//
// -gcflags=-m: «p does not escape».
func stackArg(p *Point) int {
	return p.X + p.Y // указатель только читается, не утекает
}

// closureCapture возвращает замыкание, захватывающее локальную переменную n.
// Замыкание переживает функцию, значит захваченная переменная тоже должна
// пережить кадр — её переносят в кучу.
//
// -gcflags=-m: «moved to heap: n» и «func literal escapes to heap».
func closureCapture() func() int {
	n := 0 // захвачена замыканием, которое переживает функцию → куча
	return func() int {
		n++
		return n
	}
}

// sizeVarMake и sizeConstMake показывают ОТДЕЛЬНЫЙ от времени жизни механизм:
// эскейп по РАЗМЕРУ. Оба буфера локальны и НЕ покидают функцию (escape-анализ
// метит их «does not escape»), но make с размером-переменной n компилятор не может
// разместить на стеке — размер неизвестен на этапе компиляции, поэтому уходит в
// кучу; make с константой остаётся на стеке. То есть «does not escape» ≠ «0
// аллокаций»: бенч ловит разницу, которую -gcflags=-m по строкам не показывает.

//go:noinline
func sizeVarMake(n int) byte {
	buf := make([]byte, n) // размер-переменная → куча, хотя buf не убегает
	buf[0] = 1
	return buf[0]
}

//go:noinline
func sizeConstMake() byte {
	buf := make([]byte, 64) // размер-константа → стек
	buf[0] = 1
	return buf[0]
}
