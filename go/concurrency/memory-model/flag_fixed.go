// Пакет memorymodel — примеры к статье #3 «Модель памяти Go: happens-before»
// серии «Конкурентность в Go» (khorost.tech).
//
// flag_fixed.go — починенный busy-wait из cmd/broken-flag.
// Раздел «Как чинить: атомик как сигнал и закрытие канала как сигнал».
//
// Два способа установить happens-before между «производителем» сигнала и
// «потребителем»:
//   - atomic.Bool: атомарная запись happens-before последующего атомарного
//     чтения того же адреса, которое эту запись увидело;
//   - закрытие канала: close(ch) happens-before приёма (получения нулевого
//     значения) из закрытого канала.
package memorymodel

import "sync/atomic"

// WaitAtomicFlag крутит busy-wait по атомарному флагу, который выставляет
// параллельно запущенная горутина. В отличие от сломанной версии здесь есть
// happens-before: Store в горутине становится видимым для Load в цикле, поэтому
// цикл гарантированно завершается, а -race молчит.
func WaitAtomicFlag() {
	var flag atomic.Bool

	go func() {
		// Здесь могла бы быть подготовка данных; см. publish_safe.go для
		// безопасной публикации самих данных, а не только факта готовности.
		flag.Store(true) // атомарная запись — сигнал
	}()

	for !flag.Load() { // атомарное чтение — happens-after Store, когда увидит true
		// крутимся, пока не увидим сигнал
	}
}

// WaitChannelSignal использует закрытие канала как сигнал завершения.
// Приём из закрытого канала немедленно возвращает нулевое значение, а
// close(done) happens-before этого приёма — цикл гарантированно завершится.
func WaitChannelSignal() {
	done := make(chan struct{})

	go func() {
		close(done) // сигнал: канал закрыт
	}()

	<-done // блокируемся до сигнала; никакого busy-wait и никакой гонки
}
