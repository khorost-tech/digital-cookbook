// Демо к статье #3 «Модель памяти Go: happens-before»
// серии «Конкурентность в Go» (khorost.tech).
//
// Раздел «Race condition без data race: почему -race не всесилен».
//
// КЛЮЧЕВАЯ мысль раздела: детектор гонок ловит ГОНКИ ДАННЫХ (незащищённый
// конкурентный доступ к одной ячейке памяти), а НЕ логические race conditions
// (нарушение инварианта из-за неверных границ синхронизации).
//
// Здесь каждая отдельная операция с балансом защищена мьютексом, поэтому
// гонки данных НЕТ. Но составной инвариант «проверить остаток, затем списать»
// (check-then-act) разорван на две независимые критические секции. Между
// проверкой и списанием другая горутина успевает вклиниться — итог: двойное
// списание и отрицательный баланс, хотя каждая ячейка защищена.
//
// ВОСПРОИЗВОДИМОСТЬ. В реальном коде окно между проверкой и списанием узкое и
// проявляется по удаче планировщика. runtime.Gosched() лишь УСТУПАЕТ P, но НЕ
// синхронизирует горутины — поэтому нарушение всплывало не в каждом прогоне
// (пример: 25 раз из 30). Для стенда с «живыми числами» это не годится. Здесь
// окно сделано ДЕТЕРМИНИРОВАННЫМ настоящим барьером: обе горутины сначала
// проходят проверку (пока баланс ещё не тронут), и только когда ОБЕ её
// выполнили, барьер отпускает их на списание. Так «двойное списание»
// воспроизводится в КАЖДОМ прогоне. Барьер — это стендовая оснастка, делающая
// естественно существующее окно наблюдаемым, а не подделка гонки: границы
// синхронизации в brokenWithdraw остаются ровно теми же (два разных Lock).
//
// Что покажет запуск:
//
//	go run -race .
//	  → детектор МОЛЧИТ: WARNING: DATA RACE не появляется.
//	    Но вывод показывает двойное списание и отрицательный итоговый
//	    баланс — составной инвариант нарушен.
//
// Как чинить: держать замок на ВЕСЬ составной участок check-then-act, а не на
// отдельные операции. См. safeWithdraw ниже — она под тем же мьютексом делает
// и проверку, и списание, поэтому инвариант «баланс >= 0» сохраняется.
package main

import (
	"fmt"
	"os"
	"sync"
)

// Account — счёт с балансом под мьютексом.
type Account struct {
	mu      sync.Mutex
	balance int
}

// balanceOf атомарно (под замком) читает баланс — гонки данных нет.
func (a *Account) balanceOf() int {
	a.mu.Lock()
	defer a.mu.Unlock()
	return a.balance
}

// debit атомарно (под замком) списывает amount — гонки данных нет.
func (a *Account) debit(amount int) {
	a.mu.Lock()
	defer a.mu.Unlock()
	a.balance -= amount
}

// brokenWithdraw — СЛОМАННЫЙ check-then-act: проверка и списание идут под
// РАЗНЫМИ замками (двумя разными критическими секциями). Каждая операция
// защищена → -race молчит, но составной инвариант нарушен.
//
// checked/release — барьер стенда: горутина отмечает, что ПРОВЕРКУ выполнила
// (checked.Done), и ждёт (<-release), пока это сделают ВСЕ. Списание идёт
// только после барьера — значит проверку все прошли на НЕтронутом балансе.
// Это детерминированно воспроизводит окно, которое в бою держится на удаче
// планировщика (см. заголовок файла).
func brokenWithdraw(a *Account, amount int, checked *sync.WaitGroup, release <-chan struct{}) bool {
	passed := a.balanceOf() >= amount // критическая секция №1: только проверка
	checked.Done()                    // «проверку выполнил» (безусловно — иначе барьер зависнет)
	<-release                         // ждём, пока проверку выполнят ВСЕ — детерминированное окно
	if passed {
		a.debit(amount) // критическая секция №2: списание по уже устаревшему решению
		return true
	}
	return false
}

// safeWithdraw — ПРАВИЛЬНАЯ версия: проверка и списание под ОДНИМ замком.
// Составной инвариант не разрывается, двойного списания быть не может — при
// любом порядке планировщика, поэтому здесь барьер не нужен.
func safeWithdraw(a *Account, amount int) bool {
	a.mu.Lock()
	defer a.mu.Unlock()
	if a.balance >= amount {
		a.balance -= amount
		return true
	}
	return false
}

func main() {
	const (
		start   = 100
		amount  = 100
		workers = 2 // ровно двое: минимальная честная демонстрация «двойного списания»
	)

	// Сломанная версия: на балансе хватает ровно на ОДНО списание, но обе
	// горутины проходят проверку до любого списания (барьер) — и обе спишут.
	broken := &Account{balance: start}
	var wg sync.WaitGroup
	var okCount int
	var okMu sync.Mutex

	// Барьер: отпускаем на списание только после того, как ВСЕ прошли проверку.
	var checked sync.WaitGroup
	checked.Add(workers)
	release := make(chan struct{})
	go func() { checked.Wait(); close(release) }() // координатор: все проверились → открыть окно

	for range workers {
		wg.Add(1)
		go func() {
			defer wg.Done()
			if brokenWithdraw(broken, amount, &checked, release) {
				okMu.Lock()
				okCount++
				okMu.Unlock()
			}
		}()
	}
	wg.Wait()
	fmt.Printf("[broken] успешных списаний: %d (ожидалось не более 1), итоговый баланс: %d (ожидался 0)\n",
		okCount, broken.balance)
	brokenViolated := okCount > 1 || broken.balance < 0
	if brokenViolated {
		fmt.Println("[broken] инвариант нарушен: race condition без data race")
	}

	// Правильная версия для сравнения: та же конкуренция, один замок на весь
	// check-then-act — инвариант держится при любом порядке планировщика.
	safe := &Account{balance: start}
	var wg2 sync.WaitGroup
	var okCount2 int
	var okMu2 sync.Mutex
	for range workers {
		wg2.Add(1)
		go func() {
			defer wg2.Done()
			if safeWithdraw(safe, amount) {
				okMu2.Lock()
				okCount2++
				okMu2.Unlock()
			}
		}()
	}
	wg2.Wait()
	fmt.Printf("[safe]   успешных списаний: %d, итоговый баланс: %d\n", okCount2, safe.balance)

	// Самопроверка стенда (воспроизводимость «живых чисел»):
	//   — сломанная версия ОБЯЗАНА нарушить инвариант (иначе демо не демонстрирует);
	//   — безопасная версия НЕ должна нарушать никогда.
	if !brokenViolated {
		fmt.Println("DEMO FAILED: сломанная версия не нарушила инвариант — окно не сработало")
		os.Exit(1)
	}
	if okCount2 > 1 || safe.balance < 0 {
		fmt.Println("DEMO FAILED: безопасная версия нарушила инвариант — этого быть не должно")
		os.Exit(1)
	}
}
