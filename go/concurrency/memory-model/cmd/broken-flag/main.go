// Демо к статье #3 «Модель памяти Go: happens-before»
// серии «Конкурентность в Go» (khorost.tech).
//
// Раздел «Флаг без синхронизации: почему busy-wait может крутиться вечно».
//
// СЛОМАННЫЙ пример. Одна горутина пишет обычный bool-флаг, другая читает
// его в busy-wait без какой-либо синхронизации. Это гонка данных.
//
// Что покажет запуск:
//
//	go run -race .
//	  → WARNING: DATA RACE
//	    Write at 0x... by goroutine N:   main.main.func1  (done = true)
//	    Previous read at 0x... by main goroutine: main.main (for !done)
//
// Без -race программа компилируется и часто «работает» на конкретной машине,
// но это не гарантировано моделью памяти Go: без happens-before между записью
// и чтением компилятор/процессор вправе считать, что done в цикле не меняется,
// вынести чтение из цикла в регистр — и busy-wait закрутится ВЕЧНО.
// Правильные версии — в flag_fixed.go (atomic.Bool и закрытие канала).
package main

import (
	"fmt"
	"time"
)

// done — общий флаг БЕЗ синхронизации. Пишется в одной горутине,
// читается в другой — happens-before между ними не установлен.
var done bool

func main() {
	go func() {
		// Немного «работы», затем сигнал завершения.
		time.Sleep(10 * time.Millisecond)
		done = true // гонка данных: незащищённая запись
	}()

	// Busy-wait по незащищённому чтению. Компилятор вправе закешировать
	// done в регистре — тогда цикл никогда не увидит записи.
	for !done { // гонка данных: незащищённое чтение
		// крутимся вхолостую
	}

	fmt.Println("сигнал получен (но только по счастливой случайности)")
}
