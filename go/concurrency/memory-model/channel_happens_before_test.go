// channel_happens_before_test.go — тесты к статье #3
// «Модель памяти Go: happens-before» серии «Конкурентность в Go» (khorost.tech).
//
// Раздел «Каналы как happens-before: send happens-before receive completes».
//
// Гарантия модели памяти Go для каналов:
//   - для канала (любого) отправка happens-before завершения соответствующего
//     приёма. Значит, всё, что горутина записала ДО отправки в канал, видно
//     принимающей горутине ПОСЛЕ приёма — без дополнительных атомиков и замков.
//
// Небуферизованный vs буферизованный:
//   - у НЕбуферизованного канала гарантия сильнее и симметрична: приём
//     happens-before завершения отправки (отправитель разблокируется только
//     когда получатель принял). Это даёт двустороннюю синхронизацию —
//     рандеву. См. TestUnbufferedRendezvous.
//   - у БУФЕРИРОВАННОГО канала гарантия слабее: отправка happens-before приёма
//     того же значения, но отправитель НЕ ждёт получателя (кладёт в буфер и
//     идёт дальше). Обратной гарантии «приём happens-before отправки» здесь
//     нет — только направление «данные, записанные до send, видны после receive».
//     Для передачи данных этого достаточно; для рандеву — нет.
//
// Все тесты синхронизируют доступ к общей памяти именно через канал, поэтому
// гонок данных нет и suite проходит под -race.
package memorymodel

import "testing"

// TestSendHappensBeforeReceive: запись в обычную переменную ДО отправки в
// канал видна принимающей стороне ПОСЛЕ приёма. Синхронизация — только канал.
func TestSendHappensBeforeReceive(t *testing.T) {
	var data int          // обычная переменная, синхронизируется каналом
	ch := make(chan struct{}) // небуферизованный

	go func() {
		data = 42   // запись ДО отправки
		ch <- struct{}{} // send happens-before receive completes
	}()

	<-ch // приём: всё, записанное до send, теперь видно
	if data != 42 {
		t.Fatalf("ожидали видеть data==42 после приёма, получили %d", data)
	}
}

// TestUnbufferedRendezvous демонстрирует двустороннюю гарантию небуферизованного
// канала. Отправитель разблокируется только после того, как получатель принял,
// поэтому запись получателя ПОСЛЕ приёма, синхронизированная вторым каналом,
// видна отправителю. По сути — рандеву двух горутин.
func TestUnbufferedRendezvous(t *testing.T) {
	req := make(chan int)  // небуферизованный: отправитель ждёт приёмщика
	resp := make(chan int) // ответ обратно

	go func() {
		x := <-req    // принимаем запрос
		resp <- x * 2 // отвечаем; наша отправка happens-before приёма ниже
	}()

	req <- 21       // отправка блокируется до приёма worker'ом (рандеву)
	got := <-resp   // принимаем ответ
	if got != 42 {
		t.Fatalf("ожидали 42, получили %d", got)
	}
}

// TestBufferedStillCarriesData: у буферизованного канала слабее гарантия, но
// направление «данные до send видны после receive» сохраняется — этого хватает
// для безопасной передачи значения. Отправитель здесь НЕ ждёт получателя.
func TestBufferedStillCarriesData(t *testing.T) {
	type payload struct{ v int }
	ch := make(chan *payload, 1) // буферизованный на 1 элемент

	go func() {
		p := &payload{v: 7} // конструируем ДО отправки
		ch <- p             // отправка happens-before приёма этого значения;
		//                     отправитель не блокируется (в буфере есть место)
	}()

	p := <-ch // получаем значение; поля, записанные до send, видны
	if p.v != 7 {
		t.Fatalf("ожидали payload{7}, получили %+v", *p)
	}
}
