// tee.go демонстрирует вспомогательный паттерн tee-channel из раздела
// «Вспомогательные каналы: or-done, tee, bridge» статьи.
//
// Tee раздваивает один вход на два независимых выхода (например, поток на
// обработку и поток на логирование). ОБА выхода нужно читать — иначе
// отправитель заблокируется на медленном потребителе. Каждая итерация
// отправляет один элемент в оба выхода; трюк с обнулением локальных
// переменных-каналов внутри select гарантирует, что элемент уйдёт в каждый
// выход ровно один раз, не блокируясь на порядке готовности потребителей.
package patterns

import "context"

// Tee читает in и дублирует каждый элемент в два независимых выхода. Владелец
// закрывает оба выхода через defer close по исчерпании in или при отмене ctx.
// Оба выхода обязательно читать.
func Tee[T any](ctx context.Context, in <-chan T) (<-chan T, <-chan T) {
	out1 := make(chan T)
	out2 := make(chan T)
	go func() {
		defer close(out1)
		defer close(out2)
		for {
			select {
			case <-ctx.Done():
				return
			case v, ok := <-in:
				if !ok {
					return
				}
				// Локальные копии: обнуляем канал после отправки, чтобы в
				// следующей итерации select ветка стала блокирующей навсегда
				// и элемент ушёл в каждый выход ровно один раз.
				o1, o2 := out1, out2
				for i := 0; i < 2; i++ {
					select {
					case <-ctx.Done():
						return
					case o1 <- v:
						o1 = nil
					case o2 <- v:
						o2 = nil
					}
				}
			}
		}
	}()
	return out1, out2
}
