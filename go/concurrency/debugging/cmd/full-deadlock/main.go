// Демо к статье #5 «Отладка: гонки, утечки, дедлоки»
// серии «Конкурентность в Go» (khorost.tech).
//
// Раздел «Полный дедлок: инструмент — встроенный детектор рантайма».
//
// СЛОМАННЫЙ пример. Две горутины ждут друг друга по кругу: g1 сначала шлёт в
// chA, потом читает из chB; g2 сначала шлёт в chB, потом читает из chA. Каналы
// небуферизованные, поэтому отправка блокируется до готового приёмника. Обе
// горутины (и main, ожидающий их через WaitGroup) застревают на отправке —
// ни одна горутина не может продвинуться. Это ПОЛНЫЙ дедлок: спят ВСЕ горутины.
//
// Как запускать:
//
//	go run .
//
// Что увидишь (адреса/номера строк иллюстративны):
//
//	fatal error: all goroutines are asleep - deadlock!
//
//	goroutine 1 [semacquire]:
//	  sync.(*WaitGroup).Wait(...)
//	  main.main() .../cmd/full-deadlock/main.go:63
//	goroutine 6 [chan send]:
//	  main.main.func1() .../cmd/full-deadlock/main.go:47   // chA <- 1
//	goroutine 7 [chan send]:
//	  main.main.func2() .../cmd/full-deadlock/main.go:55   // chB <- 2
//	exit status 2
//
// Ключевое отличие от частичного дедлока (см. cmd/partial-deadlock): здесь
// рантайм САМ обнаруживает тупик и аварийно завершает процесс, потому что
// абсолютно все горутины заблокированы и планировщику некого запускать.
// Строки [chan send] в трейсе указывают ровно на зависшие отправки.
package main

import "sync"

func main() {
	chA := make(chan int) // небуферизованные каналы: отправка ждёт приёмника
	chB := make(chan int)

	var wg sync.WaitGroup
	wg.Add(2)

	go func() { // g1: сначала отправить в chA, потом принять из chB
		defer wg.Done()
		chA <- 1  // блокируется: приёмника для chA нет
		<-chB
	}()

	go func() { // g2: сначала отправить в chB, потом принять из chA
		defer wg.Done()
		chB <- 2  // блокируется: приёмника для chB нет
		<-chA
	}()

	// main ждёт обе горутины, но они застряли на отправке — тупик замкнут.
	wg.Wait()
}
