// leak_fixed.go: ИСПРАВЛЕННАЯ версия воркера из cmd/goroutine-leak.
//
// Та же «работа» — горутина ждёт сигнала, — но теперь у неё есть путь выхода:
// она слушает и рабочий канал, и ctx.Done(). Как только контекст отменён (или
// истёк дедлайн), select выбирает ветку ctx.Done() и горутина завершается.
// Никаких вечно висящих горутин: отсутствие утечки проверяет goleak в
// leak_fixed_test.go.
package debugging

import "context"

// SafeWorker запускает горутину, ожидающую задачу из in ЛИБО отмены ctx.
// Функция возвращает done-канал, который закрывается, когда горутина завершилась
// (по полученной задаче или по отмене контекста). Утечки нет: у горутины всегда
// есть выход через ctx.Done().
func SafeWorker(ctx context.Context, in <-chan struct{}) <-chan struct{} {
	done := make(chan struct{})
	go func() {
		defer close(done)
		select {
		case <-in:
			// получили задачу — «обработали» и вышли
		case <-ctx.Done():
			// контекст отменён — корректно завершаемся, не зависаем
		}
	}()
	return done
}
