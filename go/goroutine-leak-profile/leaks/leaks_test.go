// TestGoroutineLeakProfile — ЕДИНСТВЕННЫЙ тест пакета, который поднимает
// утечки. Раньше подъём был разнесён по двум тестам
// (TestClassesLeakAndProfileFindsExactlyThem и TestSecondWriteToSeesMoreThanFirst,
// каждый со своим набором горутин) — оба по отдельности были зелёными, но
// вместе давали флаки на Windows (2-3 падения из 10 прогонов пакета,
// mutex-holder-gone пропадал из профиля). Слияние в один тест НЕ исправило
// это само по себе — флак воспроизводился и с одним тестом, и даже отдельным
// изолированным модулем с той же последовательностью классов, причём только
// под `go test` (`cmd/leaks` тем же кодом отдельным процессом — 15/15 чисто
// на обеих платформах). Локализовано: причина в ПОРЯДКЕ подъёма классов, а не
// в количестве тестов. Контрольный класс `mutex-held-by-live-goroutine`
// поднимает горутину, которая держит мьютекс и спит `time.Sleep(time.Hour)` —
// генуинно живую и достижимую. Если эта горутина стартует ПОСЛЕ класса
// `mutex-holder-gone` (как было раньше — все "настоящие" классы, потом
// контрольный), под `go test` она примерно в 30-50% прогонов на обеих
// платформах сбивает анализ достижимости для СОВЕРШЕННО ДРУГОГО, уже
// созданного мьютекса `mutex-holder-gone`: тот перестаёт находиться детектором
// НАВСЕГДА до конца процесса (проверено пробой: 6 WriteTo() подряд после
// "плохого" первого — все 6 показывают тот же заниженный count, повторные
// снятия и лишние runtime.GC() ситуацию не чинят, иногда делают её хуже).
// Если же контрольный класс стартует ПЕРВЫМ, до всех остальных — 25/25
// прогонов на Linux и 15/15 на Windows чисто. Поэтому здесь контрольный класс
// поднимается ПЕРВЫМ. Это не объясняет механизм (он снова не установлен до
// конца — похоже на побочный эффект того, как `time.Sleep` в первой же
// горутине процесса взаимодействует с фазой GC), но фиксирует практическое
// правило: в этом стенде порядок подъёма классов — часть контракта теста, а
// не деталь без значения.
func TestGoroutineLeakProfile(t *testing.T) {
	if pprof.Lookup("goroutineleak") == nil {
		t.Skip("профиль goroutineleak недоступен — нужен Go 1.27+")
	}

	// Контрольный класс — ПЕРВЫМ. См. комментарий выше: обратный порядок
	// (сначала "настоящие" классы, контрольный последним) под `go test`
	// нестабильно ломает детекцию mutex-holder-gone на обеих платформах.
	control := Control()
	control.Start()
	time.Sleep(200 * time.Millisecond)

	want := 0
	for _, l := range All() {
		before := runtime.NumGoroutine()
		n := l.Start()
		// Предусловие: класс действительно заблокировался. Без паузы замер
		// поймал бы горутины ещё не заблокированными, и «утечки нет» значило
		// бы «мы поспешили», а не «профиль сломан». Это не главная проверка
		// теста — только гарантия, что проверка профиля ниже имеет смысл.
		time.Sleep(200 * time.Millisecond)
		if got := runtime.NumGoroutine() - before; got != n {
			t.Fatalf("класс %s: заявлено %d горутин, фактически заблокировано %d", l.Name, n, got)
		}
		want += n
	}

	prof := pprof.Lookup("goroutineleak")

	// Первый WriteTo() в этом процессе — наблюдение, а не контракт. Раньше
	// здесь стоял runtime.GC() «для верности» — это была неверная
	// причинность (WriteTo сам запускает цикл детекции внутри себя,
	// отдельный GC не нужен). Сохраняем ОБА снимка целиком, а не только
	// Count() — падение по числу утечек ниже покажет их полностью.
	var first bytes.Buffer
	if err := prof.WriteTo(&first, 1); err != nil {
		t.Fatalf("первое снятие профиля: %v", err)
	}
	firstCount := prof.Count()
	firstProfile := first.String()

	var second bytes.Buffer
	if err := prof.WriteTo(&second, 1); err != nil {
		t.Fatalf("второе снятие профиля: %v", err)
	}
	secondCount := prof.Count()
	secondProfile := second.String()

	t.Logf("первый WriteTo(): count=%d\n--- профиль 1 ---\n%s", firstCount, firstProfile)
	t.Logf("второй WriteTo(): count=%d\n--- профиль 2 ---\n%s", secondCount, secondProfile)

	// Главная проверка: профиль обязан найти РОВНО ожидаемое число утечек —
	// не прирост runtime.NumGoroutine(), а результат анализа детектора
	// goroutineleak, снятый ВТОРЫМ вызовом WriteTo().
	if secondCount != want {
		t.Fatalf("профиль нашёл %d утечек, ожидалось %d\n--- профиль 1 ---\n%s\n--- профиль 2 ---\n%s", secondCount, want, firstProfile, secondProfile)
	}

	// Требование к тесту — не "первый снимок обязан быть неполным" (это
	// частное наблюдение стенда, а не контракт runtime/pprof, и завтрашнее
	// улучшение рантайма превратило бы его в ложную регрессию CI), а слабее
	// и вернее: второй снимок не должен быть ХУЖЕ первого. Итоговая полнота
	// результата уже проверена выше (secondCount == want).
	if secondCount < firstCount {
		t.Fatalf("второй WriteTo() (count=%d) нашёл МЕНЬШЕ утечек, чем первый (count=%d) — это противоречит наблюдению стенда и требует разбора\n--- профиль 1 ---\n%s\n--- профиль 2 ---\n%s", secondCount, firstCount, firstProfile, secondProfile)
	}

	// Неполнота первого снимка — само по себе наблюдение стенда, а не
	// требование прохождения теста: логируем оба случая, не проваливаем ни
	// один из них.
	if firstCount < secondCount {
		t.Logf("наблюдение: первый WriteTo() нашёл МЕНЬШЕ утечек (count=%d), чем второй (count=%d) — согласуется с находкой стенда, что первый снимок в свежем процессе может быть неполон", firstCount, secondCount)
	} else {
		t.Logf("первый WriteTo() уже нашёл все утечки (count=%d) — если это воспроизводится стабильно, поведение рантайма изменилось к лучшему, и текст статьи вместе со стендом можно упростить", firstCount)
	}

	// Контрольный класс НЕ должен попасть в профиль утечек: держатель его
	// мьютекса детектор обязан признать достижимым (см. Control()).
	// Попадание сюда означает нарушение правила достижимости, а не «ещё одну
	// утечку», и должно останавливать сборку так же, как расхождение числа.
	if strings.Contains(secondProfile, "mutexHeldByLiveGoroutine") {
		t.Fatalf("контрольный класс mutex-held-by-live-goroutine найден в профиле утечек — нарушено правило достижимости\n%s", secondProfile)
	}
}

