// Package leaks — детерминированные утечки горутин по классам.
//
// Каждая функция ОСТАВЛЯЕТ горутины заблокированными навсегда: это не забытая
// уборка, а предмет измерения. Число утёкших горутин известно заранее, поэтому
// профиль можно проверять точным равенством, а не «примерно столько».
package leaks

import (
	"runtime"
	"sync"
	"time"
)

// PerClass — сколько горутин поднимает каждый класс. Одинаково для всех, чтобы
// суммарное ожидание считалось умножением, а не таблицей исключений.
const PerClass = 2

type Leak struct {
	Name  string
	Start func() int // возвращает число утёкших горутин, которые ДОЛЖЕН найти детектор
}

// All — классы, которые действительно являются утечками: детектор goroutineleak
// обязан найти их все, суммой PerClass * len(All()) == Total().
func All() []Leak {
	return []Leak{
		{"send-no-receiver", sendNoReceiver},
		{"receive-never-closed", receiveNeverClosed},
		{"waitgroup-missing-done", waitGroupMissingDone},
		{"mutex-holder-gone", mutexHolderGone},
		{"cond-never-signaled", condNeverSignaled},
	}
}

func Total() int { return len(All()) * PerClass }

// Control — контрольный класс: мьютекс держит ЖИВАЯ горутина (не блокирована
// навсегда — спит по таймеру и в принципе может проснуться и отпустить). По
// правилу достижимости детектора goroutineleak горутины, ждущие Lock() на
// таком мьютексе, НЕ утечка — хотя выглядят заблокированными точно так же,
// как в mutexHolderGone. Класс участвует в общем прогоне наравне с
// остальными, но НЕ входит в Total() и проверяется отдельно: попадание в
// профиль утечек означает, что правило достижимости нарушено, а не то, что
// «нашлась ещё одна утечка».
func Control() Leak {
	return Leak{"mutex-held-by-live-goroutine", mutexHeldByLiveGoroutine}
}

// Отправка в небуферизованный канал, который никто не читает.
func sendNoReceiver() int {
	ch := make(chan int)
	for i := 0; i < PerClass; i++ {
		go func() { ch <- 1 }()
	}
	return PerClass
}

// Приём из канала, который никто не закроет и в который никто не пишет.
func receiveNeverClosed() int {
	ch := make(chan int)
	for i := 0; i < PerClass; i++ {
		go func() { <-ch }()
	}
	return PerClass
}

// Wait при недосчитанном Done: счётчик никогда не дойдёт до нуля.
func waitGroupMissingDone() int {
	var wg sync.WaitGroup
	wg.Add(1) // Done не будет вызван никогда
	for i := 0; i < PerClass; i++ {
		go func() { wg.Wait() }()
	}
	return PerClass
}

// Мьютекс, чей держатель УСПЕЛ ЗАВЕРШИТЬСЯ: отпустить его больше некому —
// это настоящая утечка.
//
// Раньше (класс назывался mutexNeverUnlocked) держателем был сам вызывающий
// (main), который продолжает жить до конца программы, — с точки зрения
// детектора это НЕ утечка: он не винит горутину, ждущую примитив, который
// ещё может отпустить живой владелец (см. mutexHeldByLiveGoroutine ниже и
// находку 3 в results/00-findings.txt). Прежний стенд ошибочно ожидал здесь
// утечку и был неправ, а не детектор.
func mutexHolderGone() int {
	// Прогрев: без хотя бы одного цикла обычной сборки мусора, прошедшего
	// ДО выделения mu, свежевыделенная память по умолчанию считается
	// достижимой (Go красит недавно выделенные объекты «чёрным», чтобы не
	// собрать их раньше времени, если полный цикл сборки по куче ещё ни
	// разу не проходил) — и детектор goroutineleak увидит mu как
	// достижимую, даже если её реально некому разлочить. Это НЕ то же
	// самое, что находка про runtime.GC() перед WriteTo() (facts, находка
	// 1—2: там GC не нужен, чтобы ЗАПУСТИТЬ анализ и увидеть его результат
	// со второго снятия) — здесь GC нужен раньше, до выделения mu, чтобы
	// сама память была правильно раскрашена ДО того, как за неё возьмётся
	// анализ достижимости. Без этой строки на Linux mutex-holder-gone
	// стабильно не находился (count=0 вместо 2, проверено 5/5 прогонов).
	runtime.GC()

	var mu sync.Mutex
	holderLocked := make(chan struct{})
	go func() {
		mu.Lock()
		close(holderLocked)
		// Возврат без Unlock: держатель заканчивает работу здесь. Мьютекс
		// остаётся захваченным, а горутина, которая могла бы его отпустить,
		// уже завершилась — отпустить больше некому.
	}()
	<-holderLocked // дождаться захвата, чтобы он гарантированно случился раньше ожидающих
	for i := 0; i < PerClass; i++ {
		go func() { mu.Lock() }()
	}
	return PerClass
}

// Мьютекс держит ЖИВАЯ горутина — см. Control() выше. Начатые здесь
// ожидающие Lock() горутины блокированы визуально так же, как в
// mutexHolderGone, но детектор не должен их посчитать утечкой.
func mutexHeldByLiveGoroutine() int {
	var mu sync.Mutex
	holderLocked := make(chan struct{})
	go func() {
		mu.Lock()
		close(holderLocked)
		// Держатель НЕ завершается и не блокирован навсегда: он спит по
		// таймеру и рано или поздно проснётся и сможет отпустить мьютекс —
		// то есть остаётся достижимым. Это единственное отличие от
		// mutexHolderGone: снаружи оба держателя выглядят одинаково «мёртво
		// висящими», но для детектора достижимость решает всё.
		time.Sleep(time.Hour)
		mu.Unlock()
	}()
	<-holderLocked
	for i := 0; i < PerClass; i++ {
		go func() { mu.Lock() }()
	}
	return 0 // НЕ ожидаем, что детектор посчитает это утечкой
}

// Ожидание сигнала, которого не будет.
func condNeverSignaled() int {
	mu := &sync.Mutex{}
	cond := sync.NewCond(mu)
	for i := 0; i < PerClass; i++ {
		go func() {
			mu.Lock()
			cond.Wait()
			mu.Unlock()
		}()
	}
	return PerClass
}
