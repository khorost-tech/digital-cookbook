// Один и тот же набор утечек глазами разных инструментов:
//
//	pprof/goroutine — ВСЕ горутины вперемешку, утёкшие и работающие;
//	goroutineleak   — только те, что не могут быть разблокированы (Go 1.27+).
//
// Третий инструмент, go.uber.org/goleak, устроен иначе: он проверяет отсутствие
// утечек на выходе из теста и падает, если они есть. Это ответ на вопрос «есть
// ли утечка», а не «какая именно и где» в работающем процессе, — поэтому он
// участвует в сравнении текстом, а не числом.
package main

import (
	"bytes"
	"fmt"
	"runtime/pprof"
	"time"

	"tech.khorost/goroutine-leak-cookbook/leaks"
)

// workerCount — размер фонового пула ШТАТНО работающих горутин: они реально
// блокируются в ожидании тика (значит в момент снятия профиля видны как
// «running»/«waiting»), но блокировка снимается сама, десятки раз в секунду —
// это не утечка, а нормальное ожидание работы. Без такого фона сравнение
// вырождается: в пустой программе, где кроме утечек ничего не происходит,
// pprof/goroutine и goroutineleak почти совпадают по числу (11 против 10), и
// разница не читается. Число подобрано так, чтобы контраст был виден сразу:
// на реальном сервисе pprof/goroutine показывает сотни живых горутин, и
// десяток утёкших в этом списке теряется — здесь мы моделируем ту же картину
// в миниатюре (полсотни рабочих против десятка утёкших), а не одну горутину
// разницы.
const workerCount = 50

// runWorkers поднимает workerCount горутин, читающих из общего тикера. Все они
// заблокированы на приёме из tick.C большую часть времени — совершенно так же
// «заблокированы», как и настоящие утечки. Отличие для goroutineleak должно
// быть не во внешнем виде блокировки, а в достижимости: канал tick.C жив, на
// него всё ещё может (и будет) отправлять сам *time.Ticker, поэтому ни одна
// из этих горутин не является утечкой — рано или поздно каждая разблокируется.
func runWorkers(count int) {
	tick := time.NewTicker(10 * time.Millisecond)
	for i := 0; i < count; i++ {
		go func() {
			for range tick.C {
				// Имитация обработки тика: реальной нагрузки не требуется —
				// важно только, что горутина по-настоящему ждёт на канале,
				// а не крутится в busy-loop.
			}
		}()
	}
}

func main() {
	runWorkers(workerCount)

	for _, l := range leaks.All() {
		l.Start()
	}
	// Дать горутинам дойти до блокировки, прежде чем снимать любой профиль.
	time.Sleep(500 * time.Millisecond)

	all := pprof.Lookup("goroutine")
	leaked := pprof.Lookup("goroutineleak")

	fmt.Printf("%-22s %s\n", "ИНСТРУМЕНТ", "СКОЛЬКО ГОРУТИН ПОКАЗЫВАЕТ")

	// ВАЖНО: у обоих профилей Count() отражает состояние на момент ПОСЛЕДНЕГО
	// WriteTo() (для goroutineleak это буквально последний прогон анализа
	// рантайма, до первого WriteTo счётчик хранит устаревшее — как правило
	// нулевое — значение). Поэтому сначала пишем профиль в буфер, потом
	// читаем Count(): в обратном порядке goroutineleak.Count() вернул бы 0
	// не потому, что утечек нет, а потому, что анализ ещё не запускался.
	var bufAll, bufLeaked bytes.Buffer
	if err := all.WriteTo(&bufAll, 1); err != nil {
		fmt.Printf("ошибка записи профиля goroutine: %v\n", err)
		return
	}
	fmt.Printf("%-22s %d\n", "pprof/goroutine", all.Count())

	if leaked == nil {
		fmt.Println("goroutineleak недоступен — нужен Go 1.27+")
		return
	}

	// ВАЖНО: WriteTo сам запускает цикл детекции — отдельный runtime.GC()
	// перед снятием не нужен (results/00-findings.txt, находка 1: раньше
	// здесь стоял runtime.GC() по неверной причине). В прогонах этого
	// стенда цикл, запущенный первым WriteTo, давал менее полный результат,
	// чем второй — счётчик становился полнее лишь на следующем снятии
	// (находка 2). Это наблюдение на конкретных версиях, а не
	// документированный контракт runtime/pprof. Поэтому здесь пишем дважды
	// и используем второй результат: первый вызов в discard ниже нужен
	// только чтобы поставить детекцию, реальный буфер идёт вторым.
	var discard bytes.Buffer
	if err := leaked.WriteTo(&discard, 1); err != nil {
		fmt.Printf("ошибка первого снятия профиля goroutineleak: %v\n", err)
		return
	}
	if err := leaked.WriteTo(&bufLeaked, 1); err != nil {
		fmt.Printf("ошибка записи профиля goroutineleak: %v\n", err)
		return
	}
	fmt.Printf("%-22s %d\n", "goroutineleak", leaked.Count())
	fmt.Printf("\nожидалось утечек: %d\n", leaks.Total())

	// Главная мысль сравнения: goroutineleak не просто «показывает меньше» —
	// он ЗНАЕТ, какие горутины блокированы навсегда, и отсеивает все
	// остальные, включая workerCount штатно работающих. Если хоть одна из
	// них попала бы в leaked.Count(), это была бы находка (ложное
	// срабатывание детектора), а не округление, и требовала бы разбора, а не
	// подгонки чисел.
	sifted := all.Count() - leaked.Count()
	fmt.Printf("\nвсего горутин (pprof/goroutine):        %d\n", all.Count())
	fmt.Printf("из них утёкших (goroutineleak):         %d\n", leaked.Count())
	fmt.Printf("рабочих/служебных, отсеянных как НЕ утечка: %d (из них %d — пул воркеров, остальное — main)\n",
		sifted, workerCount)

	fmt.Printf("\nразмер текстового профиля goroutine:      %d байт\n", bufAll.Len())
	fmt.Printf("размер текстового профиля goroutineleak:  %d байт\n", bufLeaked.Len())

	fmt.Println("\ngoleak в этом сценарии неприменим: он проверяет ОТСУТСТВИЕ утечек")
	fmt.Println("на выходе из теста, то есть отвечает «есть или нет», но не показывает")
	fmt.Println("утечки в работающем процессе.")
}
