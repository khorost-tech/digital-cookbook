// Package redact — маскировка чувствительных данных (токены, пароли, PII) в
// логах slog двумя дополняющими способами:
//
//   - LogValuer: тип САМ знает, что он секрет, и подставляет в лог маску вместо
//     значения. Точечно и типобезопасно — забыть замаскировать нельзя, если
//     секрет обёрнут в такой тип.
//   - ReplaceAttr: страховочная сетка на уровне хендлера — ловит атрибуты по
//     ИМЕНИ ключа и заменяет значение, даже если исходное значение обычная строка.
//
// Честная граница обоих способов — в тестах и в докстрингах ниже: LogValuer
// срабатывает, когда секрет залогирован как самостоятельный атрибут slog; если
// он спрятан полем внутри обычной структуры, отданной в slog.Any, хендлер
// сериализует структуру своим кодировщиком (JSON), и LogValue поля не
// вызывается — секрет утечёт. ReplaceAttr по ключу в этом случае тоже не
// поможет: вся структура это один атрибут с чужим ключом.
package redact

import "log/slog"

// Secret — строка-секрет (токен, пароль, ключ). Реализует slog.LogValuer,
// поэтому slog печатает "REDACTED" вместо значения, когда Secret передан как
// значение САМОСТОЯТЕЛЬНОГО slog-атрибута — slog.Any("token", secret) или
// slog.String через тип-обёртку. Граница: если Secret спрятан полем внутри
// структуры, отданной в slog.Any целиком, его LogValue НЕ вызывается (кодировщик
// хендлера сериализует структуру сам) — см. TestBoundaryStructLeaks.
type Secret string

// LogValue возвращает маску вместо самого секрета.
func (Secret) LogValue() slog.Value { return slog.StringValue("REDACTED") }

// Card — номер платёжной карты. LogValue показывает только последние 4 цифры,
// остальное маскирует — типичный приём для PII, где нужен «хвост» для поддержки,
// но не весь номер.
type Card string

// LogValue возвращает маску вида "**** **** **** 1234".
func (c Card) LogValue() slog.Value {
	s := string(c)
	if len(s) < 4 {
		return slog.StringValue("****")
	}
	return slog.StringValue("**** **** **** " + s[len(s)-4:])
}

// RedactKeys возвращает функцию для slog.HandlerOptions.ReplaceAttr, которая
// заменяет значение любого атрибута с ключом из keys на "***" — на любом уровне
// вложенности групп (ReplaceAttr вызывается для каждого атрибута, включая
// атрибуты внутри slog-групп). Это страховочная сетка «по имени поля» поверх
// LogValuer: ловит password/authorization/set-cookie и подобное, что залогировали
// обычной строкой, забыв обернуть в тип-секрет.
//
// Ограничение: ReplaceAttr обходит slog-ГРУППЫ, но не заглядывает внутрь
// произвольной структуры, отданной в slog.Any как единый атрибут, — там ключа
// вложенного поля просто нет в поле зрения ReplaceAttr.
func RedactKeys(keys ...string) func([]string, slog.Attr) slog.Attr {
	set := make(map[string]struct{}, len(keys))
	for _, k := range keys {
		set[k] = struct{}{}
	}
	return func(_ []string, a slog.Attr) slog.Attr {
		if _, ok := set[a.Key]; ok {
			a.Value = slog.StringValue("***")
		}
		return a
	}
}
