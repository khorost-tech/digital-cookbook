// Демо к мини-серии «Основы Go вглубь» (khorost.tech), раздел «Методы и ресиверы».
//
// Ловушка value-ресивера на большой структуре. Метод с value-ресивером
// получает КОПИЮ всей структуры (включая её поля и содержимое массивов).
// Любые изменения внутри такого метода вносятся в копию и теряются, как только
// метод вернёт управление — оригинал остаётся нетронутым. Компилятор ошибку не
// выдаёт: код собирается, «мутация» просто тихо пропадает.
//
// Что печатает запуск (go run ./methods/cmd/receiver-copy):
//
//	== value-ресивер: мутация теряется ==
//	до  Fill(7):  data[0]=0 sum=0
//	после Fill(7): data[0]=0 sum=0   <- ничего не изменилось: метод правил КОПИЮ
//
//	== pointer-ресивер: мутация сохраняется ==
//	до  FillPtr(7):  data[0]=0 sum=0
//	после FillPtr(7): data[0]=7 sum=1792  <- оригинал изменён (256*7)
//
// Как чинить: объявить метод на pointer-ресивере (func (b *Big) …), тогда он
// правит оригинал. Дополнительный плюс указателя на большой структуре — не
// копировать её при каждом вызове (см. бенч receiver_bench_test.go).
package main

import "fmt"

// Big — намеренно «тяжёлая» структура с массивом внутри, чтобы копирование при
// value-ресивере было и заметным по смыслу, и дорогим по памяти.
type Big struct {
	data [256]int
}

// sum — сумма всех элементов (для наглядной печати эффекта).
func (b Big) sum() int {
	s := 0
	for _, v := range b.data {
		s += v
	}
	return s
}

// Fill — VALUE-ресивер: заполняет data значением v, но правит КОПИЮ.
// Снаружи вызова изменения не видны.
func (b Big) Fill(v int) {
	for i := range b.data {
		b.data[i] = v
	}
}

// FillPtr — POINTER-ресивер: заполняет data в оригинале. Изменения сохраняются.
func (b *Big) FillPtr(v int) {
	for i := range b.data {
		b.data[i] = v
	}
}

func main() {
	fmt.Println("== value-ресивер: мутация теряется ==")
	a := Big{}
	fmt.Printf("до  Fill(7):  data[0]=%d sum=%d\n", a.data[0], a.sum())
	a.Fill(7) // правит копию — оригинал не меняется
	fmt.Printf("после Fill(7): data[0]=%d sum=%d   <- ничего не изменилось: метод правил КОПИЮ\n", a.data[0], a.sum())

	fmt.Println()
	fmt.Println("== pointer-ресивер: мутация сохраняется ==")
	c := Big{}
	fmt.Printf("до  FillPtr(7):  data[0]=%d sum=%d\n", c.data[0], c.sum())
	c.FillPtr(7) // правит оригинал
	fmt.Printf("после FillPtr(7): data[0]=%d sum=%d  <- оригинал изменён (256*7)\n", c.data[0], c.sum())
}
