// Демо к мини-серии «Основы Go вглубь» (khorost.tech), раздел «Интерфейсы».
//
// Ловушка nil-интерфейса (общий случай той же природы, что typed-nil в
// разделе про ошибки). Переменная-указатель *T со значением nil, положенная
// в интерфейсную переменную, делает интерфейс НЕ равным nil.
//
// Причина: интерфейсное значение — пара (тип, значение). Даже когда значение
// (указатель) равно nil, тип пары не nil (он равен *T). Интерфейс равен nil
// ТОЛЬКО когда пусты оба поля пары.
//
// Что печатает запуск (из папки interfaces/: go run ./cmd/nil-interface;
// из корня go-fundamentals: go run ./interfaces/cmd/nil-interface):
//
//	p (указатель *T) == nil            -> true
//	i (интерфейс с этим указателем) == nil -> false
//	пустой интерфейс var e any == nil  -> true
//
// Практический вывод: не «протаскивайте» типизированный nil-указатель через
// интерфейс, если хотите, чтобы проверка `iface == nil` была истинной.
package main

import "fmt"

// T — произвольный конкретный тип.
type T struct{ id int }

// Speaker — минимальный интерфейс для демонстрации.
type Speaker interface {
	Speak() string
}

func (t *T) Speak() string { return fmt.Sprintf("T#%d", t.id) }

func main() {
	var p *T = nil // nil-указатель конкретного типа

	// Кладём nil-указатель в интерфейсную переменную.
	var i Speaker = p // пара (тип=*T, значение=nil)

	// Настоящий nil-интерфейс: пара (тип=nil, значение=nil).
	var e any = nil

	fmt.Printf("p (указатель *T) == nil            -> %v\n", p == nil)
	fmt.Printf("i (интерфейс с этим указателем) == nil -> %v\n", i == nil)
	fmt.Printf("пустой интерфейс var e any == nil  -> %v\n", e == nil)

	fmt.Println("итог: type != nil  =>  interface != nil, даже если значение внутри — nil")
}
