// Демо к мини-серии «Основы Go вглубь» (khorost.tech), раздел «Слайсы и карты».
//
// Порядок обхода map НЕ определён и намеренно рандомизирован рантаймом:
// разные проходы по одной и той же карте (и разные запуски программы) дают
// разный порядок ключей. Это сделано специально, чтобы код не полагался на
// случайно стабильный порядок.
//
// Что печатает запуск (go run ./slices-maps/cmd/map-order):
//   несколько строк вида "проход N: [...]" — порядок между проходами обычно
//   различается. Конкретные перестановки зависят от запуска.
//
// Как получить стабильный порядок: собрать ключи в срез и отсортировать
// (sort.Strings / slices.Sort), затем обходить срез.
package main

import (
	"fmt"
	"sort"
)

func main() {
	m := map[string]int{
		"alpha": 1, "bravo": 2, "charlie": 3,
		"delta": 4, "echo": 5, "foxtrot": 6,
	}

	// Несколько проходов по одной карте — порядок обычно скачет.
	for pass := 1; pass <= 3; pass++ {
		keys := make([]string, 0, len(m))
		for k := range m { // порядок range по map не определён
			keys = append(keys, k)
		}
		fmt.Printf("проход %d: %v\n", pass, keys)
	}

	// Детерминированный обход: сортируем ключи.
	sorted := make([]string, 0, len(m))
	for k := range m {
		sorted = append(sorted, k)
	}
	sort.Strings(sorted)
	fmt.Printf("\nотсортированный обход (стабильный): %v\n", sorted)
}
