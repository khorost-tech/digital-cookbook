// Демо к мини-серии «Основы Go вглубь» (khorost.tech), раздел «Слайсы и карты».
//
// ВНИМАНИЕ: эта программа ПАДАЕТ НАМЕРЕННО. Встроенная map не безопасна для
// конкурентного использования. Когда несколько горутин пишут в одну карту
// одновременно, рантайм детектирует это и аварийно завершает процесс —
// это не паника, которую можно перехватить через recover, а фатальная ошибка.
//
// Что печатает запуск (go run ./slices-maps/cmd/concurrent-map):
//
//	fatal error: concurrent map writes
//	  goroutine ... [running]:
//	  ... main.main.func1 ...
//	exit status 2
//
// Как чинить:
//   - защитить доступ sync.Mutex/sync.RWMutex вокруг чтения и записи;
//   - либо использовать sync.Map (оптимизирован под «много читателей»/
//     непересекающиеся ключи).
// Про эти примитивы синхронизации — соседний стенд go-concurrency (раздел sync).
package main

import (
	"fmt"
	"sync"
)

func main() {
	fmt.Println("сейчас запустим конкурентную запись в map — рантайм уронит процесс")
	fmt.Println("ожидаемо: fatal error: concurrent map writes")

	m := make(map[int]int)
	var wg sync.WaitGroup

	// Много горутин пишут в ОДНУ незащищённую карту -> concurrent map writes.
	for g := 0; g < 8; g++ {
		wg.Add(1)
		go func(base int) {
			defer wg.Done()
			for i := 0; i < 100_000; i++ {
				m[base] = i // незащищённая конкурентная запись
			}
		}(g)
	}

	wg.Wait() // до сюда обычно не доходим — процесс уже упал
	fmt.Println("если вы это видите — гонка не проявилась в этом запуске, повторите")
}
