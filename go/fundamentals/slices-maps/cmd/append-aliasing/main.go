// Демо к мини-серии «Основы Go вглубь» (khorost.tech), раздел «Слайсы и карты».
//
// Коварный алиасинг backing-массива. Слайс — это тройка (указатель на массив,
// длина, ёмкость). reslice (b := a[:2]) НЕ копирует данные: b смотрит в тот же
// массив, что и a. Если у b есть запас ёмкости, append в b пишет в общий
// массив ПОВЕРХ элементов, которые видны через a. Никакой ошибки — тихая
// перезапись данных «соседа».
//
// Что печатает запуск (go run ./slices-maps/cmd/append-aliasing):
//
//	исходный full:      [10 20 30 40]
//	view := full[:2]    len=2 cap=4  -> [10 20]
//	после append(view, 99):
//	  view: [10 20 99]
//	  full: [10 20 99 40]   <- элемент full[2] МОЛЧА изменился с 30 на 99
//
// Как избежать: делать независимую копию (slices.Clone) или ограничить
// ёмкость трёхиндексным срезом full[:2:2], тогда append выделит новый массив.
package main

import "fmt"

func main() {
	full := []int{10, 20, 30, 40}
	fmt.Printf("исходный full:      %v\n", full)

	// view делит backing-массив с full и имеет запас ёмкости (cap=4).
	view := full[:2]
	fmt.Printf("view := full[:2]    len=%d cap=%d  -> %v\n", len(view), cap(view), view)

	// append влезает в имеющуюся ёмкость — новый массив НЕ выделяется,
	// запись идёт в общий массив, в ячейку, которую видит full[2].
	view = append(view, 99)

	fmt.Println("после append(view, 99):")
	fmt.Printf("  view: %v\n", view)
	fmt.Printf("  full: %v   <- элемент full[2] МОЛЧА изменился с 30 на 99\n", full)

	// Безопасный вариант: трёхиндексный срез обрезает ёмкость, append
	// вынужден выделить новый массив и сосед не пострадает.
	base := []int{1, 2, 3, 4}
	safe := base[:2:2] // cap=2, запаса нет
	safe = append(safe, 777)
	fmt.Printf("\nбезопасно через base[:2:2]: safe=%v, base не тронут=%v\n", safe, base)
}
