// Package coverage демонстрирует артефакт «100% покрытие операторов
// (statements) при живом баге».
//
// DiscountedPrice — прямолинейная реализация скидки без валидации входа.
// Все ветви функции достижимы «нормальными» входами (pct в диапазоне 0..100),
// поэтому тест с такими кейсами даёт 100% покрытие операторов (statements),
// но не проверяет границу pct > 100 — а именно там прячется баг: цена
// уходит в минус.
package coverage

// DiscountedPrice возвращает цену base со скидкой pct процентов.
//
// БАГ: pct не валидируется. При pct > 100 (например, 150) результат
// становится отрицательным (base - base*pct/100 < 0), что для цены
// бессмысленно. Правильная реализация должна была бы ограничивать pct
// сверху (clamp до 100) или возвращать ошибку — но в этой версии такой
// ветки нет вовсе, поэтому покрытия операторов (statements) функции
// недостаточно, чтобы заметить проблему: у бага нет отдельного
// оператора/ветки, которую тесты могли бы "не задеть".
func DiscountedPrice(base int, pct int) int {
	discount := base * pct / 100
	return base - discount
}
