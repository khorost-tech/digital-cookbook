#!/usr/bin/env bash
# Замеры 1-4 и 7: пропускная способность и потребление ресурсов.
# Использование: ./scripts/bench.sh <nats|kafka> <agent|passthrough|nofilter> <rate>
set -euo pipefail

TRANSPORT="${1:-nats}"
VARIANT="${2:-agent}"
RATE="${3:-5000}"
DURATION=60

case "$VARIANT" in
  agent)       AGENT_CONFIG="/etc/vector/agent.yaml" ;;
  passthrough) AGENT_CONFIG="/etc/vector/variants/passthrough.yaml" ;;
  nofilter)    AGENT_CONFIG="/etc/vector/variants/nofilter.yaml" ;;
  *) echo "вариант: agent | passthrough | nofilter" >&2; exit 2 ;;
esac
if [[ "$TRANSPORT" == "kafka" && "$VARIANT" == "agent" ]]; then
  AGENT_CONFIG="/etc/vector/agent-kafka.yaml"
fi

cd "$(dirname "$0")/.."

# Страховка для Windows/Git Bash — та же, что в up.sh: AGENT_CONFIG похож на
# POSIX-путь, MSYS иначе переписал бы его в Windows-путь при вызове docker.exe,
# и подстановка ниже долетала бы до compose испорченной.
export MSYS_NO_PATHCONV=1

OUT="results/bench-${TRANSPORT}-${VARIANT}-${RATE}.csv"

# down.sh идемпотентен и возвращает 0 даже когда гасить нечего (проверено
# живьём) — отдельной страховки || true не нужно, а без неё реальный сбой
# (например, недоступен docker daemon) уронит скрипт здесь, а не всплывёт
# позже менее понятной ошибкой из up.sh.
./scripts/down.sh
AGENT_CONFIG="$AGENT_CONFIG" ./scripts/up.sh "$TRANSPORT"

# Снимаем CPU/RAM ПОТОКОВЫМ docker stats (без --no-stream), а не редкими
# мгновенными снимками. Так делали в первой версии скрипта — и она себя не
# оправдала: живьём измерено, что один вызов `docker stats --no-stream` на
# этой машине (Docker Desktop/Windows) сам занимает ~2.2 с, так что реальный
# интервал между снимками при "sleep 2" в коде получался ближе к ~4 с, а не 2.
# При этом Vector забирает новые данные из log-файлов НЕ равномерно: генератор
# копит запись в буфере 1 МиБ (bufio.Writer в loadgen) и сбрасывает его на диск
# скачками — CPU агента реально скачет между ~0-1% и ~50-140% с периодом около
# секунды (проверено потоковым docker stats на живом прогоне: подряд идущие
# точки 1.01% → 47.75% → 1.28% → 1.27% → 1.07% → 48.04% → ...). Редкие снимки
# то попадают на всплеск, то нет — отсюда невоспроизводимость: повтор
# kafka/agent/5000 первой версией скрипта дал 9.3% и 1.6% CPU агента, почти
# 6-кратное расхождение при формально одинаковых параметрах.
# Потоковый `docker stats` считает дельту CPU-времени от предыдущего
# внутреннего обновления БЕЗ пропусков — каждое окно ~1 с учитывается, а не
# выборочно. На этой сборке вывод даже при редиректе в файл несёт ANSI-коды
# терминала (^[[H ^[[K ^[[J) — чистятся ниже sed'ом.
#
# ВАЖНО про дубли: docker stats перерисовывает одно и то же обновление дважды
# подряд (двойной кадр на одно реальное обновление), и agent/agg чередуются
# в потоке — то есть подряд идущие СТРОКИ почти никогда буквально не совпадают
# (разный контейнер в каждой строке), даже когда речь об одном и том же кадре.
# `uniq` в такой раскладке НЕ ловит дубль в принципе (он схлопывает только
# буквально соседние одинаковые строки) — раньше здесь стоял `uniq` с
# комментарием, что он это чистит; это было неверно, проверено на реальных
# CSV (grep живьём: каждое значение идёт подряд дважды, местами трижды).
# Правильная дедупликация "по предыдущему кадру ТОГО ЖЕ контейнера" была бы
# возможна, но сознательно не делается: на idle-фазе многие подряд идущие
# кадры ОДНОГО контейнера ЗАКОННО одинаковы (реальный простой, CPU 0.00% час
# за часом) — их отбрасывание по признаку "совпадает с предыдущим" убрало бы
# настоящие данные, а не задвоенные кадры. Средние ниже считаются по СЫРЫМ
# кадрам, включая повторную перерисовку: сверено на всех шести CSV прогонов —
# усреднение по сырым кадрам и по кадрам, дедуплицированным вручную построчно
# на каждый контейнер, расходится не больше чем на ~8% (см. task-11-report.md,
# "Проверка на существующих CSV"), то есть направление и порядок всех выводов
# не меняются, но подпись "по N кадрам" ниже — это число СЫРЫХ кадров
# (примерно вдвое больше числа отличимых обновлений), а не независимых
# измерений.
sample_stream() {
  local phase="$1" seconds="$2" raw
  raw="$(mktemp)"
  docker stats --format '{{.Name}},{{.CPUPerc}},{{.MemUsage}}' vp-agent vp-agg > "$raw" 2>&1 &
  local pid=$!
  sleep "$seconds"
  # Намеренное завершение фонового потока после истечения окна замера — это
  # не сбой, который нужно скрывать через || true без разбора: код возврата
  # ниже проверяется явно через число полученных строк, а не глотается молча.
  kill "$pid" 2>/dev/null || true
  wait "$pid" 2>/dev/null || true
  sed 's/\x1b\[[0-9;]*[A-Za-z]//g' "$raw" | grep -aE '^vp-(agent|agg),' \
    | sed 's/%//; s/MiB.*//; s|/.*||' \
    | awk -F, -v p="$phase" '{printf "%s,%s,%s,%s\n", p, $1, $2, $3}' >> "$OUT"
  rm -f "$raw"
  local got
  got=$(awk -F, -v p="$phase" '$1==p' "$OUT" | wc -l)
  if (( got < 4 )); then
    echo "снято подозрительно мало метрик на фазе $phase ($got строк) — docker stats не сработал?" >&2
    exit 1
  fi
  # Слабая страховка от "поток застрял и шлёт один и тот же кадр вечно" —
  # именно тот класс дефекта, из-за которого ложная надежда на uniq выше
  # осталась бы незамеченной. Только для фазы load: под нагрузкой CPU агента
  # реально скачет (см. комментарий выше про буферизованную запись генератора),
  # так что застрявший на одном значении поток — верный признак сбоя. На idle
  # эта же проверка была бы ложной тревогой: там 0.00% час за часом — законное
  # показание, а не зависший docker stats, и требовать различимости было бы
  # неверно. Проверяется per-container (частая ошибка — смешать оба контейнера
  # в одном множестве значений: тогда "vp-agent всегда 40%" и "vp-agg всегда
  # 90%" дали бы 2 различимых пары и страховка не сработала бы вообще).
  if [[ "$phase" == "load" ]]; then
    for c in vp-agent vp-agg; do
      local distinct
      distinct=$(awk -F, -v p="$phase" -v c="$c" '$1==p && $2==c {print $3}' "$OUT" | sort -u | wc -l)
      if (( distinct < 2 )); then
        echo "на фазе load контейнер $c показывает одно и то же CPU все кадры ($distinct значение) — docker stats завис?" >&2
        exit 1
      fi
    done
  fi
}

echo "phase,container,cpu_pct,mem_mb" > "$OUT"

# idle-замер до нагрузки
sample_stream idle 10

# -d, поэтому код возврата ниже подтверждает только успешный СТАРТ контейнера
# генератора, а не завершение прогона — это единственное, что можно проверить
# синхронно в фоновом режиме. Полноту самого прогона подтверждает сверка
# gen_total с rate*duration ниже, после того как манифест прочитан.
if ! docker compose run -d --rm loadgen -rate "$RATE" -duration "${DURATION}s" >/dev/null; then
  echo "не запустить генератор" >&2
  exit 1
fi

# нагрузочный замер: потоково весь прогон длительности DURATION
sample_stream load "$DURATION"

sleep 30   # дать конвейеру слить хвост

# выборки парсятся в предположении, что память в MiB; гигабайтные значения
# посчитались бы как мегабайты и дали бы молча неверные числа
if grep -q "GiB" "$OUT"; then
  echo "ПРОВАЛ: память контейнера превысила 1 GiB — парсер выборок неверен, править bench.sh" >&2
  exit 1
fi

if ! manifest="$(docker compose run --rm --entrypoint sh loadgen -c 'cat /logs/manifest.json')"; then
  echo "не прочитать манифест генератора" >&2
  exit 1
fi
mfield() { printf '%s' "$manifest" | tr -d '\r\n' | sed "s/.*\"$1\":\([0-9]*\).*/\1/"; }
gen_total="$(mfield total)"
nginx_expected="$(mfield nginx_expected)"
app_expected="$(mfield app_expected)"
for v in "$gen_total" "$nginx_expected" "$app_expected"; do
  if ! [[ "$v" =~ ^[0-9]+$ ]]; then
    echo "манифест генератора неполон: $manifest" >&2
    exit 1
  fi
done

# manifest.json перезаписывается только в САМОМ КОНЦЕ прогона генератора
# (main.go, после завершения цикла тиков): если контейнер стартовал, но
# процесс внутри упал по дороге (OOM, паника), файл на томе остаётся от
# предыдущего запуска и был бы молча принят за текущий результат. total
# для rate/duration детерминирован по построению (тики по 10 мс), но не
# гарантирован день в день секунда в секунду: под нагрузкой хоста тикер
# может фактически сработать на 1-2 тика меньше/больше 6000 — это дрожание
# таймера, а не потеря данных. Допуск 2% отличает такое дрожание (доли
# процента на живой машине, проверено: 1199800 из 1200000 на rate=20000)
# от настоящей деградации — обрыва на середине прогона или манифеста от
# совсем другого rate/duration, где расхождение на порядки больше допуска.
expected_total=$(( RATE * DURATION ))
tolerance=$(( expected_total * 2 / 100 ))
diff=$(( gen_total - expected_total ))
if (( diff < 0 )); then diff=$(( -diff )); fi
if (( diff > tolerance )); then
  echo "манифест не от этого прогона: total=$gen_total, ожидалось rate*duration=$expected_total (допуск ${tolerance})" >&2
  echo "(генератор мог упасть по дороге, а на томе остался манифест от прошлого прогона)" >&2
  exit 1
fi

# вариант passthrough не парсит и не фильтрует, поэтому доехать должно ВСЁ;
# в остальных вариантах ожидание — то же, что у самопроверки
if [[ "$VARIANT" == "passthrough" ]]; then
  expected="$gen_total"
elif [[ "$VARIANT" == "nofilter" ]]; then
  # парсинг есть, отсечения нет — доезжает весь поток
  expected="$gen_total"
else
  expected=$(( nginx_expected + app_expected ))
fi

# Одиночный сетевой сбой (обрыв TLS-рукопожатия через self-signed HTTPS и
# проброшенный Docker-порт) уже наблюдался живьём в verify.sh — там же и
# страховка: несколько попыток с паузой вместо падения на первом же сбое.
# Здесь тот же сбой воспроизведён (rc=28 на ровном месте, стенд при этом
# был полностью здоров — повтор тем же curl немедленно прошёл). Недоступность
# фиксируем, только если НИ ОДНА из попыток не дала ответа.
indexed=""
for _ in $(seq 1 8); do
  if out="$(curl -sk --connect-timeout 3 --max-time 5 -u "admin:VectorDemo#2026" \
      "https://localhost:9224/logs-app-*/_count" | sed 's/.*"count":\([0-9]*\).*/\1/')" \
      && [[ "$out" =~ ^[0-9]+$ ]]; then
    indexed="$out"
    break
  fi
  sleep 2
done
if [[ -z "$indexed" ]]; then
  echo "не прочитать _count индекса: OpenSearch недоступен?" >&2
  exit 1
fi

# Отдельно от индекса — сколько событий реально дошло до архива на агрегаторе.
# Синк archive пишет файлом без шаблона в пути, поэтому не зависит от template
# confinement синка opensearch (см. results/08-confinement.txt). Если archived
# и indexed расходятся — потери не в транспорте/агрегаторе, а именно в
# маршрутизации в индекс (см. пометку для passthrough ниже).
if ! archived="$(docker compose exec -T aggregator sh -c 'wc -l < /archive/events.log 2>/dev/null || echo 0' | tr -d ' \r')"; then
  echo "не прочитать архив агрегатора" >&2
  exit 1
fi
if ! [[ "$archived" =~ ^[0-9]+$ ]]; then
  echo "архив агрегатора вернул не число: $archived" >&2
  exit 1
fi

{
  echo "=== $TRANSPORT / $VARIANT / rate=$RATE"
  echo "сгенерировано: $gen_total"
  echo "ожидалось:     $expected"
  echo "в архиве:      $archived"
  echo "в индексе:     $indexed"
  echo "недоставлено:  $(( expected - indexed ))"
  # passthrough не задаёт поле service (нет парсинга), а bulk.index агрегатора
  # ("logs-app-{{ service }}") без него не рендерится — Vector роняет ЭТИ
  # события синком opensearch, оставляя внятную ошибку в логах агрегатора
  # (error_type="template_failed"). В архив при этом уходит полный поток
  # (проверено живьём: 5000/5000). Это не деградация транспорта или агента —
  # значимое для замера 3 число CPU агента ниже это не затрагивает.
  if [[ "$VARIANT" == "passthrough" && "$indexed" -lt "$archived" ]]; then
    echo "  (passthrough не ставит service → синк opensearch не рендерит bulk.index"
    echo "   и роняет эти события; в архиве при этом полный поток — потери не в"
    echo "   транспорте/CPU-цене, а в маршрутизации индекса, см. Task 8/confinement)"
  fi
  # "кадрам", не "выборкам": docker stats в потоковом режиме перерисовывает
  # каждое обновление дважды, так что N здесь — число сырых кадров (примерно
  # вдвое больше числа отличимых обновлений), не независимых измерений.
  awk -F, '$1=="load" && $2=="vp-agent" {c+=$3; m+=$4; n++} END {
    if (n) printf "agent под нагрузкой: CPU %.1f%%, RAM %.0f MiB (по %d кадрам)\n", c/n, m/n, n }' "$OUT"
  awk -F, '$1=="load" && $2=="vp-agg" {c+=$3; m+=$4; n++} END {
    if (n) printf "aggregator под нагрузкой: CPU %.1f%%, RAM %.0f MiB (по %d кадрам)\n", c/n, m/n, n }' "$OUT"
  awk -F, '$1=="idle" && $2=="vp-agent" {c+=$3; m+=$4; n++} END {
    if (n) printf "agent idle: CPU %.1f%%, RAM %.0f MiB\n", c/n, m/n }' "$OUT"
  awk -F, '$1=="idle" && $2=="vp-agg" {c+=$3; m+=$4; n++} END {
    if (n) printf "aggregator idle: CPU %.1f%%, RAM %.0f MiB\n", c/n, m/n }' "$OUT"
  echo
} >> results/bench-summary.txt

tail -16 results/bench-summary.txt
